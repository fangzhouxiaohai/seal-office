const fs=require('node:fs'),path=require('node:path'),os=require('node:os')
const {createService}=require('./service')
const http=require('node:http')
let directory,secureFile,safeStorage,transport
const saved={token:'saved-token',account:{id:'saved-account',phone:'13800138000',enabled:true},root:Buffer.alloc(32,1).toString('base64')}
beforeEach(()=>{
  directory=fs.mkdtempSync(path.join(os.tmpdir(),'seal-cloud-unlock-'))
  secureFile=path.join(directory,'cloud.secure')
  fs.writeFileSync(secureFile,JSON.stringify(saved),{mode:0o600})
  safeStorage={isEncryptionAvailable:vi.fn(()=>true),decryptString:vi.fn(value=>value.toString()),encryptString:vi.fn(value=>Buffer.from(value))}
  transport=vi.fn(async()=>saved.account)
})
afterEach(()=>fs.rmSync(directory,{recursive:true,force:true}))
describe('macOS 云会话按需解锁',()=>{
  it('启动、状态、更新服务地址和同步轮询不访问钥匙串',async()=>{
    const original=fs.readFileSync(secureFile)
    const service=createService({directory,safeStorage,transport,deferUnlock:true})
    expect(service.status()).toMatchObject({sessionLocked:true,account:null,unlocked:false})
    expect(service.status().url).toBe('https://seal.xingmasoft.com/api')
    expect(await service.refresh()).toMatchObject({sessionLocked:true})
    expect(await service.flush()).toMatchObject({sessionLocked:true,errors:[]})
    expect(safeStorage.isEncryptionAvailable).not.toHaveBeenCalled()
    expect(safeStorage.decryptString).not.toHaveBeenCalled()
    expect(transport).not.toHaveBeenCalled()
    expect(()=>service.login('13800138000','000000')).toThrow('恢复本机云会话')
    expect(()=>service.logout()).toThrow('恢复本机云会话')
    expect(fs.readFileSync(secureFile)).toEqual(original)
  })
  it('公开能力和更新查询无需恢复会话且不附带认证',async()=>{
    const service=createService({directory,safeStorage,transport,deferUnlock:true})
    await service.request('/v1/capabilities')
    await service.request('/v1/updates/latest?platform=macos-arm64')
    expect(transport).toHaveBeenCalledTimes(2)
    expect(transport.mock.calls[0][1].headers.Authorization).toBeUndefined()
    expect(safeStorage.decryptString).not.toHaveBeenCalled()
    expect(()=>service.request('/v1/me')).toThrow('恢复本机云会话')
  })
  it('用户恢复后读取旧账号，后续请求沿用原令牌',async()=>{
    const service=createService({directory,safeStorage,transport,deferUnlock:true})
    expect(service.resumeSession()).toMatchObject({sessionLocked:false,account:saved.account,unlocked:true})
    await service.refresh()
    expect(transport.mock.calls[0][1].headers.Authorization).toBe('Bearer saved-token')
    expect(safeStorage.decryptString).toHaveBeenCalledTimes(1)
    service.resumeSession()
    expect(safeStorage.decryptString).toHaveBeenCalledTimes(1)
  })
  it('拒绝授权时保留加密记录并可重试',()=>{
    const original=fs.readFileSync(secureFile)
    safeStorage.decryptString.mockImplementationOnce(()=>{throw new Error('User denied')})
    const service=createService({directory,safeStorage,transport,deferUnlock:true})
    expect(()=>service.resumeSession()).toThrow('原记录已保留')
    expect(service.status().sessionLocked).toBe(true)
    expect(fs.readFileSync(secureFile)).toEqual(original)
    expect(service.resumeSession().account).toEqual(saved.account)
  })
  it('全新安装没有会话时可直接登录，不读取不存在的凭据',async()=>{
    fs.unlinkSync(secureFile)
    transport.mockResolvedValue({token:'new-token',account:saved.account})
    const service=createService({directory,safeStorage,transport,deferUnlock:true})
    expect(service.status().sessionLocked).toBe(false)
    await service.login('13800138000','000000')
    expect(safeStorage.decryptString).not.toHaveBeenCalled()
    expect(safeStorage.encryptString).toHaveBeenCalled()
  })
  it('锁定时可匿名探测实时协作能力，不读取凭据',async()=>{
    transport.mockResolvedValue({realtime:1,diagramRealtime:1})
    const service=createService({directory,safeStorage,transport,deferUnlock:true})
    expect(await service.realtimeCapabilities()).toEqual({realtime:1,diagramRealtime:1})
    expect(transport.mock.calls[0][1].headers.Authorization).toBe('')
    expect(safeStorage.decryptString).not.toHaveBeenCalled()
  })
  it('匿名请求的迟到 401 不清除刚恢复的原会话',async()=>{
    let rejectRequest
    transport.mockImplementation(()=>new Promise((_,reject)=>{rejectRequest=reject}))
    const original=fs.readFileSync(secureFile)
    const service=createService({directory,safeStorage,transport,deferUnlock:true})
    const pending=service.request('/v1/capabilities')
    service.resumeSession()
    rejectRequest(Object.assign(new Error('公开服务拒绝请求'),{status:401}))
    await expect(pending).rejects.toThrow('公开服务拒绝请求')
    expect(service.status().account).toEqual(saved.account)
    expect(fs.readFileSync(secureFile)).toEqual(original)
    expect(safeStorage.encryptString).not.toHaveBeenCalled()
  })
  it('实际 HTTP 匿名 401 返回原错误，锁定状态不持久写入或崩溃',async()=>{
    const server=http.createServer((_,response)=>{response.writeHead(401,{'Content-Type':'application/json'});response.end(JSON.stringify({error:'公开服务拒绝请求'}))})
    await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve))
    try{
      const original=fs.readFileSync(secureFile)
      const service=createService({directory,safeStorage,deferUnlock:true,defaultUrl:'http://127.0.0.1:'+server.address().port})
      await expect(service.request('/v1/capabilities')).rejects.toThrow('公开服务拒绝请求')
      expect(service.status().sessionLocked).toBe(true)
      expect(safeStorage.isEncryptionAvailable).not.toHaveBeenCalled()
      expect(safeStorage.encryptString).not.toHaveBeenCalled()
      expect(fs.readFileSync(secureFile)).toEqual(original)
    }finally{await new Promise(resolve=>server.close(resolve))}
  })

})
