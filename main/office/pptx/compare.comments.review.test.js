const { 写入pptx, 读取pptx } = require('../pptxCodec')
const { 比较演示文稿 } = require('./compare')

const 页 = (标识) => ({ id: 标识, title: 标识, 背景色: '#FFFFFF', 文本框: [{ id: `${标识}-文字`, text: '内容', x: 40, y: 40, width: 300, height: 60, 字号: 20 }] })
const 批注 = (id, 覆盖 = {}) => ({ id, 页标识: '页一', 作者: '甲', 内容: '请核对', 时间: '2026-10-06T10:00:00.000Z', ...覆盖 })
const 稿 = (批注列表, 页列表 = [页('页一')]) => ({ id: '稿', name: '稿', 当前索引: 0, 模型版本: 2, 资源索引: {}, 幻灯片列表: 页列表, 批注列表 })
const 批注差异 = (结果) => [...结果.页面.flatMap(页项 => 页项.差异 ?? []), ...(结果.批注?.差异 ?? [])].filter(项 => 项.类型 === '批注')

describe('复审：比对必须覆盖批注（计划 3.5 要求比较批注）', () => {
  it('模型级报出批注新增、对象锚点、解决状态与回复差异', () => {
    const 左 = 稿([批注('批甲')])
    const 右 = 稿([
      { ...批注('批甲'), 已解决: true, 回复: [{ id: '回一', 作者: '乙', 内容: '已修改', 时间: '2026-10-06T11:00:00.000Z' }] },
      批注('批乙', { 内容: '新增批注', 对象标识: '页一-文字' }),
    ])
    const 结果 = 比较演示文稿(左, 右)
    const 项 = 批注差异(结果)
    expect(项.some(项 => 项.标识 === '批乙' && 项.字段 === '存在')).toBe(true)
    expect(项.some(项 => 项.标识 === '批甲' && 项.字段 === '已解决' && 项.右 === true)).toBe(true)
    expect(项.some(项 => 项.标识 === '批甲' && 项.字段 === '回复')).toBe(true)
    expect(结果.汇总.差异项).toBeGreaterThan(0)
  })

  it('批注差异归属到所在页面，而不是被丢弃', () => {
    const 左 = 稿([批注('批甲')])
    const 右 = 稿([{ ...批注('批甲'), 内容: '改后的批注内容' }])
    const 结果 = 比较演示文稿(左, 右)
    const 页项 = 结果.页面.find(项 => 项.标识 === '页一')
    expect(页项).toBeTruthy()
    expect(页项.类型).toBe('修改')
    expect((页项.差异 ?? []).some(项 => 项.类型 === '批注' && 项.字段 === '内容')).toBe(true)
  })

  it('真实文件写入→读取→比对仍能报出批注差异', async () => {
    const 左读 = await 读取pptx(await 写入pptx({ 幻灯片: [页('页一')], 批注列表: [批注('批甲')] }))
    const 右读 = await 读取pptx(await 写入pptx({ 幻灯片: [页('页一')], 批注列表: [批注('批甲'), 批注('批乙', { 内容: '新增批注' })] }))
    expect(左读.演示文稿.批注列表).toHaveLength(1)
    expect(右读.演示文稿.批注列表).toHaveLength(2)
    expect(左读.警告).toEqual([])
    expect(批注差异(比较演示文稿(左读.演示文稿, 右读.演示文稿)).length).toBeGreaterThan(0)
  })

  it('批注页标识指向已删除页面时不崩溃，并按页面登记差异', () => {
    const 左 = 稿([批注('批甲')])
    const 右 = 稿([批注('批甲', { 页标识: '已删除页' })])
    const 结果 = 比较演示文稿(左, 右)
    const 项 = 批注差异(结果)
    expect(项.some(项 => 项.标识 === '批甲' && 项.字段 === '页标识')).toBe(true)
  })
})
