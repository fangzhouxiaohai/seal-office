const { 比较演示文稿 } = require('./compare')

const 文本框 = (id, 文本, 覆盖 = {}) => ({ id, text: 文本, x: 40, y: 40, width: 300, height: 80, 字号: 20, 加粗: false, 斜体: false, 下划线: false, 颜色: '#1A1D24', 对齐: 'left', ...覆盖 })
const 图形 = (id, 覆盖 = {}) => ({ id, 类型: '图形', x: 200, y: 60, width: 160, height: 80, 形状: { 种类: '矩形', 文本: '节点', 填充: '#FFFFFF', 线条: '#334455', 线宽: 2, 颜色: '#112233', 字号: 20, 加粗: false }, ...覆盖 })
const 页 = (id, 覆盖 = {}) => ({ id, title: id, 版式: '标题和内容', 背景色: '#FFFFFF', 文本框列表: [文本框(`${id}-文字`, '正文')], ...覆盖 })
const 稿 = (页列表, 覆盖 = {}) => ({ 模型版本: 2, id: '稿', name: '对比.pptx', 当前索引: 0, 资源索引: {}, 幻灯片列表: 页列表, ...覆盖 })

describe('演示文稿比对', () => {
  it('相同文稿没有差异', () => {
    const 结果 = 比较演示文稿(稿([页('页一'), 页('页二')]), 稿([页('页一'), 页('页二')]))
    expect(结果.汇总).toEqual({ 新增页: 0, 删除页: 0, 移动页: 0, 修改页: 0, 差异项: 0 })
    expect(结果.页面).toEqual([])
  })

  it('按稳定标识识别页面新增与删除，不把新增页当成修改', () => {
    const 结果 = 比较演示文稿(稿([页('页一'), 页('页二')]), 稿([页('页一'), 页('页二'), 页('页三')]))
    expect(结果.汇总).toMatchObject({ 新增页: 1, 删除页: 0, 修改页: 0 })
    expect(结果.页面).toEqual([expect.objectContaining({ 标识: '页三', 类型: '新增', 右索引: 2 })])
    const 反向 = 比较演示文稿(稿([页('页一'), 页('页二')]), 稿([页('页一')]))
    expect(反向.汇总).toMatchObject({ 删除页: 1, 修改页: 0 })
    expect(反向.页面[0]).toMatchObject({ 标识: '页二', 类型: '删除', 左索引: 1 })
  })

  it('顺序变化识别为移动且不产生内容差异', () => {
    const 结果 = 比较演示文稿(稿([页('页一'), 页('页二')]), 稿([页('页二'), 页('页一')]))
    expect(结果.汇总).toEqual({ 新增页: 0, 删除页: 0, 移动页: 2, 修改页: 0, 差异项: 0 })
    expect(结果.页面.map(项 => 项.类型)).toEqual(['移动', '移动'])
  })

  it('文本、样式和位置差异逐项列出', () => {
    const 左 = 稿([页('页一', { 文本框列表: [文本框('甲', '原文', { 字号: 20, 颜色: '#1A1D24', 加粗: false })] })])
    const 右 = 稿([页('页一', { 文本框列表: [文本框('甲', '改后文本', { 字号: 28, 颜色: '#C00000', 加粗: true, x: 100 })] })])
    const 结果 = 比较演示文稿(左, 右)
    expect(结果.汇总.修改页).toBe(1)
    const 字段 = 结果.页面[0].差异.map(项 => 项.字段)
    expect(字段).toEqual(expect.arrayContaining(['text', '字号', '颜色', '加粗', 'x']))
    expect(结果.页面[0].差异.find(项 => 项.字段 === 'text')).toMatchObject({ 左: '原文', 右: '改后文本' })
  })

  it('对象增删、位置尺寸旋转与形状样式分别登记', () => {
    const 左 = 稿([页('页一', { 对象列表: [图形('形甲', { x: 200, 旋转: 0 }), 图形('形乙')] })])
    const 右 = 稿([页('页一', { 对象列表: [图形('形甲', { x: 260, width: 200, 旋转: 30, 形状: { ...图形('形甲').形状, 填充: '#FFEE00' } })] })])
    const 结果 = 比较演示文稿(左, 右)
    const 项 = 结果.页面[0]
    expect(项.差异).toEqual(expect.arrayContaining([
      expect.objectContaining({ 类型: '对象', 标识: '形乙', 字段: '存在' }),
      expect.objectContaining({ 类型: '对象', 标识: '形甲', 字段: 'x' }),
      expect.objectContaining({ 类型: '对象', 标识: '形甲', 字段: 'width' }),
      expect.objectContaining({ 类型: '对象', 标识: '形甲', 字段: '旋转' }),
      expect.objectContaining({ 类型: '对象', 标识: '形甲', 字段: '形状.填充' }),
    ]))
  })

  it('备注、背景、切换与批注差异都能识别，且批注按独立模型比较', () => {
    const 左 = 稿([页('页一', { 备注: '旧备注', 背景色: '#FFFFFF', 批注: [{ id: '批甲', 作者: '甲', 内容: '请核对', 已解决: false }] })])
    const 右 = 稿([页('页一', { 备注: '新备注', 背景色: '#EEEEEE', 批注: [{ id: '批甲', 作者: '甲', 内容: '请核对', 已解决: true }, { id: '批乙', 作者: '乙', 内容: '补充', 已解决: false }] })])
    const 结果 = 比较演示文稿(左, 右)
    const 字段 = 结果.页面[0].差异.map(项 => `${项.类型}:${项.字段}`)
    expect(字段).toEqual(expect.arrayContaining(['备注:备注', '页面:背景色', '批注:已解决', '批注:存在']))
    expect(结果.页面[0].差异.find(项 => 项.字段 === '已解决')).toMatchObject({ 标识: '批甲', 左: false, 右: true })
  })

  it('不修改被比较的两份文稿', () => {
    const 左 = 稿([页('页一', { 文本框列表: [文本框('甲', '原文')] })]), 右 = 稿([页('页一', { 文本框列表: [文本框('甲', '改后')] })])
    const 左快照 = JSON.stringify(左), 右快照 = JSON.stringify(右)
    比较演示文稿(左, 右)
    expect(JSON.stringify(左)).toBe(左快照)
    expect(JSON.stringify(右)).toBe(右快照)
  })

  it('拒绝无效输入并给出真实原因', () => {
    expect(() => 比较演示文稿(null, 稿([]))).toThrow('被比较的演示文稿无效')
    expect(() => 比较演示文稿(稿([]), { 幻灯片列表: 'x' })).toThrow('被比较的演示文稿无效')
  })
})
