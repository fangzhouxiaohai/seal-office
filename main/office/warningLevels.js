// 导入警告分级：区分“保真风险”（只影响观感或已原样保留，允许覆盖保存并提示）
// 与“内容风险”（保存后会丢失实际内容，需另存副本）。
// 渲染层 renderer/src/fileWarnings.ts 的白名单须与这里的保真风险清单保持一致。

/** 颜色类告警统一使用此文案，不再区分主题色、透明色或索引色。 */
const 颜色告警 = '部分颜色按近似值导入'
/** 筛选子条件无法解析时按原始 XML 原样写回，本机暂不能据此隐藏行。 */
const 筛选降级告警 = '部分筛选条件已按原样保留，本机暂不按该条件隐藏行'
/** 除打印区域、打印标题与筛选数据库外的其他 Excel 内部名称不会写回。 */
const 内部名称告警 = '部分打印设置或内部名称未保留'
/** Word 域缓存（由文字模块产生，此处仅登记级别）。 */
const 域缓存告警 = '域代码未完整导入，已保留可读取的缓存结果'
/** 数字格式代码会原样写回，只是预览可能与 Excel 不同。 */
const 数字格式预览告警 = '部分数字格式不能准确预览，保存时保留原始格式代码'
const 数字格式颜色告警 = '数字格式中的颜色或区域语言仅保留代码，预览可能不同'

const 保真风险告警 = new Set([颜色告警, 筛选降级告警, 内部名称告警, 域缓存告警, 数字格式预览告警, 数字格式颜色告警])

/** 已知的内容风险，列出以便核对；未登记的告警一律按内容风险处理，避免误放行。 */
const 内容风险告警 = new Set([
  '图片或媒体未导入', '绘图对象未导入', '图表未导入', '数据透视表未导入', '结构化表格未导入',
  '线程批注未导入', '外部数据连接未导入', '命名区域未导入', '筛选条件未导入', '条件格式未导入',
  '工作表保护设置未导入', '隐藏行列或分组状态未导入',
])

/** 返回告警级别；无法识别的告警按内容风险处理。 */
function 告警级别(告警) {
  return 保真风险告警.has(告警) ? '保真风险' : '内容风险'
}

module.exports = { 颜色告警, 筛选降级告警, 内部名称告警, 域缓存告警, 保真风险告警, 内容风险告警, 告警级别 }
