// 演示生成编排：提纲、页面、单页、美化建议、智能图形与素材语义搜索。
// 全部结构化输出都要经过严格校验；模型缺失、坏 JSON、截断、越界引用一律拒绝，绝不写入文稿。
const 提纲页数上限 = 60
const 单页要点上限 = 8
const 图形节点上限 = 24
const 标题上限 = 120
const 正文上限 = 2000
const 要点上限 = 200
const 说明上限 = 200
const 版式白名单 = ['标题幻灯片', '标题和内容', '空白']
const 图形类型白名单 = ['流程', '层级', '循环', '脑图']
const 对齐白名单 = ['左对齐', '居中', '右对齐']
const 背景白名单 = ['浅色', '深色', '保持不变']
const 美化字段白名单 = ['页标识', '对齐', '字号建议', '要点上限', '背景建议', '版式建议', '说明']

const 是记录 = (值) => typeof 值 === 'object' && 值 !== null && !Array.isArray(值)
const 非空文本 = (值, 上限) => typeof 值 === 'string' && 值.trim().length > 0 && 值.length <= 上限

function 要求模型(调用模型) {
  if (typeof 调用模型 !== 'function') throw new Error('演示文稿生成必须调用 AI 模型服务，不能使用固定模板')
}

function 解析Json(文本) {
  const 精简 = String(文本 ?? '').trim().replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '')
  let 数据
  try { 数据 = JSON.parse(精简) } catch { throw new Error('模型返回的数据格式无效（可能被截断），未修改文稿') }
  if (!是记录(数据)) throw new Error('模型返回的数据格式无效（不是对象），未修改文稿')
  return 数据
}

async function 请求({ 调用模型, 系统提示, 用户内容, 推送, 信号 }) {
  if (信号?.aborted) throw new Error('已停止生成')
  const 结果 = await 调用模型({ 系统提示, 用户内容, 推送: 推送 ?? (() => {}), 信号 })
  if (信号?.aborted) throw new Error('已停止生成')
  return 解析Json(结果)
}

const 通用系统提示 = [
  '你是演示文稿写作助手。只输出一个 JSON 对象，不要输出解释、Markdown 代码块或思考过程。',
  '所有文本使用简体中文，避免空话与重复；要点短句化，每条不超过 40 个汉字。',
  '严格按用户给出的字段与数量要求输出；无法满足时必须减少内容而不是编造事实。',
].join('\n')

/** 生成提纲：先确认提纲，再生成正文。 */
async function 生成提纲({ 主题, 受众, 页数, 风格, 素材约束, 调用模型, 推送, 信号 }) {
  要求模型(调用模型)
  if (!非空文本(主题, 500)) throw new Error('请填写有效的演示主题')
  if (!Number.isInteger(页数) || 页数 < 1 || 页数 > 提纲页数上限) throw new Error(`页数必须是 1 到 ${提纲页数上限} 之间的整数`)
  const 数据 = await 请求({
    调用模型,
    系统提示: 通用系统提示,
    用户内容: `请为下列需求生成演示提纲，只返回 {"提纲":[{"页标识":"p1","标题":"","版式":"标题幻灯片|标题和内容|空白","要点":[""]}]}。\n` + JSON.stringify({
      主题, ...(受众 ? { 受众 } : {}), 页数, ...(风格 ? { 风格 } : {}), ...(素材约束 ? { 素材约束 } : {}),
    }),
    推送, 信号,
  })
  if (!Array.isArray(数据.提纲)) throw new Error('模型返回的提纲格式无效（缺少提纲数组），未修改文稿')
  if (数据.提纲.length !== 页数) throw new Error(`模型返回的提纲数量不符：要求 ${页数} 页，实际 ${数据.提纲.length} 页`)
  const 标识集合 = new Set()
  const 提纲 = 数据.提纲.map((项, 序号) => {
    if (!是记录(项)) throw new Error(`第 ${序号 + 1} 条提纲格式无效`)
    if (!非空文本(项.页标识, 64)) throw new Error(`第 ${序号 + 1} 条提纲缺少有效的页标识`)
    if (标识集合.has(项.页标识)) throw new Error(`提纲存在重复页标识：${项.页标识}`)
    标识集合.add(项.页标识)
    if (!非空文本(项.标题, 标题上限)) throw new Error(`第 ${序号 + 1} 页标题无效或过长（最多 ${标题上限} 字）`)
    if (!版式白名单.includes(项.版式)) throw new Error(`第 ${序号 + 1} 页版式无效：只支持 ${版式白名单.join('、')}`)
    const 要点 = 项.要点 ?? []
    if (!Array.isArray(要点)) throw new Error(`第 ${序号 + 1} 页要点格式无效`)
    if (要点.length > 单页要点上限) throw new Error(`第 ${序号 + 1} 页要点过多：最多 ${单页要点上限} 条`)
    for (const 点 of 要点) if (!非空文本(点, 要点上限)) throw new Error(`第 ${序号 + 1} 页存在无效要点（每条最多 ${要点上限} 字）`)
    return { 页标识: 项.页标识.trim(), 标题: 项.标题.trim(), 版式: 项.版式, 要点: 要点.map((点) => 点.trim()) }
  })
  return { 提纲 }
}

function 校验页面项(项, 序号, 允许标识) {
  if (!是记录(项)) throw new Error(`第 ${序号 + 1} 页格式无效`)
  if (!非空文本(项.页标识, 64)) throw new Error(`第 ${序号 + 1} 页缺少有效的页标识`)
  if (!允许标识.has(项.页标识)) throw new Error(`模型返回了不属于本次请求的页标识：${项.页标识}`)
  if (!非空文本(项.标题, 标题上限)) throw new Error(`第 ${序号 + 1} 页标题无效或过长（最多 ${标题上限} 字）`)
  if (typeof 项.正文 !== 'string') throw new Error(`第 ${序号 + 1} 页正文格式无效`)
  if (项.正文.length > 正文上限) throw new Error(`第 ${序号 + 1} 页正文过长（最多 ${正文上限} 字），已拒绝写入`)
  if (项.版式 !== undefined && !版式白名单.includes(项.版式)) throw new Error(`第 ${序号 + 1} 页版式无效：只支持 ${版式白名单.join('、')}`)
  const 要点 = 项.要点 ?? []
  if (!Array.isArray(要点)) throw new Error(`第 ${序号 + 1} 页要点格式无效`)
  if (要点.length > 单页要点上限) throw new Error(`第 ${序号 + 1} 页要点过多：最多 ${单页要点上限} 条`)
  for (const 点 of 要点) if (!非空文本(点, 要点上限)) throw new Error(`第 ${序号 + 1} 页存在无效要点（每条最多 ${要点上限} 字）`)
  return { 页标识: 项.页标识.trim(), 标题: 项.标题.trim(), 正文: 项.正文.trim(), ...(项.版式 ? { 版式: 项.版式 } : {}), 要点: 要点.map((点) => 点.trim()) }
}

/** 按已确认的提纲生成可编辑页面。 */
async function 生成页面({ 提纲, 调用模型, 推送, 信号 }) {
  要求模型(调用模型)
  if (!Array.isArray(提纲) || 提纲.length === 0) throw new Error('请先确认提纲再生成正文')
  const 允许标识 = new Set()
  for (const 项 of 提纲) {
    if (!是记录(项) || !非空文本(项.页标识, 64)) throw new Error('提纲条目的页标识无效')
    if (允许标识.has(项.页标识)) throw new Error(`提纲存在重复页标识：${项.页标识}`)
    允许标识.add(项.页标识)
  }
  const 数据 = await 请求({
    调用模型,
    系统提示: 通用系统提示,
    用户内容: `请按下列已确认提纲生成每页正文，只返回 {"页面":[{"页标识":"","标题":"","正文":"","版式":"","要点":[""]}]}，必须与提纲的页标识一一对应。\n` + JSON.stringify({ 提纲 }),
    推送, 信号,
  })
  if (!Array.isArray(数据.页面)) throw new Error('模型返回的页面格式无效（缺少页面数组），未修改文稿')
  const 页面 = 数据.页面.map((项, 序号) => 校验页面项(项, 序号, 允许标识))
  const 返回标识 = new Set(页面.map((页) => 页.页标识))
  for (const 标识 of 允许标识) if (!返回标识.has(标识)) throw new Error(`模型返回的页面缺少提纲中的页标识：${标识}`)
  return { 页面 }
}

/** 生成封面或单页：与文稿生成共享同一结构协议。 */
async function 生成单页({ 内容, 版式, 调用模型, 推送, 信号 }) {
  要求模型(调用模型)
  if (!非空文本(内容, 正文上限)) throw new Error('请填写有效的单页内容')
  if (版式 !== undefined && !版式白名单.includes(版式)) throw new Error(`版式无效：只支持 ${版式白名单.join('、')}`)
  const 数据 = await 请求({
    调用模型,
    系统提示: 通用系统提示,
    用户内容: `请生成一页演示内容，只返回 {"页面":{"标题":"","正文":"","版式":"","要点":[""]}}。\n` + JSON.stringify({ 内容, ...(版式 ? { 版式 } : {}) }),
    推送, 信号,
  })
  if (!是记录(数据.页面)) throw new Error('模型返回的单页格式无效（缺少页面对象），未修改文稿')
  // 单页生成不需要模型提供页标识，交由调用方在插入时分配稳定标识。
  const 原始页 = { ...数据.页面, 页标识: 数据.页面.页标识 ?? 'p1' }
  const 页面 = 校验页面项(原始页, 0, new Set([原始页.页标识]))
  return { 页面 }
}

/** 智能美化：由模型给出结构化布局建议，再由界面校验与预览后应用。 */
async function 生成美化建议({ 页面列表, 主题摘要, 调用模型, 推送, 信号 }) {
  要求模型(调用模型)
  if (!Array.isArray(页面列表) || 页面列表.length === 0) throw new Error('没有需要美化的页面')
  const 允许标识 = new Set()
  for (const 项 of 页面列表) {
    if (!是记录(项) || !非空文本(项.页标识, 64)) throw new Error('页面列表的页标识无效')
    允许标识.add(项.页标识)
  }
  const 数据 = await 请求({
    调用模型,
    系统提示: 通用系统提示,
    用户内容: `请分析下列页面并给出本机可执行的布局建议，只返回 {"建议":[{"页标识":"","对齐":"左对齐|居中|右对齐","字号建议":24,"要点上限":4,"背景建议":"浅色|深色|保持不变","版式建议":"标题幻灯片|标题和内容|空白","说明":""}]}。不得给出未登记字段。\n` + JSON.stringify({ ...(主题摘要 ? { 主题摘要 } : {}), 页面列表 }),
    推送, 信号,
  })
  if (!Array.isArray(数据.建议)) throw new Error('模型返回的美化建议格式无效（缺少建议数组），未修改文稿')
  const 建议 = 数据.建议.map((项, 序号) => {
    if (!是记录(项)) throw new Error(`第 ${序号 + 1} 条美化建议格式无效`)
    const 未登记 = Object.keys(项).filter((键) => !美化字段白名单.includes(键))
    if (未登记.length) throw new Error(`第 ${序号 + 1} 条美化建议包含未登记字段：${未登记.join('、')}`)
    if (!非空文本(项.页标识, 64)) throw new Error(`第 ${序号 + 1} 条美化建议缺少页标识`)
    if (!允许标识.has(项.页标识)) throw new Error(`模型返回了不属于本次请求的页标识：${项.页标识}`)
    if (!对齐白名单.includes(项.对齐)) throw new Error(`第 ${序号 + 1} 条美化建议的对齐方式无效`)
    if (!Number.isInteger(项.字号建议) || 项.字号建议 < 8 || 项.字号建议 > 96) throw new Error(`第 ${序号 + 1} 条美化建议的字号超出 8 到 96 的范围`)
    if (!Number.isInteger(项.要点上限) || 项.要点上限 < 1 || 项.要点上限 > 12) throw new Error(`第 ${序号 + 1} 条美化建议的要点上限超出 1 到 12 的范围`)
    if (!背景白名单.includes(项.背景建议)) throw new Error(`第 ${序号 + 1} 条美化建议的背景建议无效`)
    if (!版式白名单.includes(项.版式建议)) throw new Error(`第 ${序号 + 1} 条美化建议的版式建议无效`)
    if (项.说明 !== undefined && !非空文本(项.说明, 说明上限)) throw new Error(`第 ${序号 + 1} 条美化建议的说明无效或过长`)
    return { 页标识: 项.页标识.trim(), 对齐: 项.对齐, 字号建议: 项.字号建议, 要点上限: 项.要点上限, 背景建议: 项.背景建议, 版式建议: 项.版式建议, ...(项.说明 ? { 说明: 项.说明.trim() } : {}) }
  })
  return { 建议 }
}

/** 智能图形与思维导图：模型给出节点与关系，校验后插入可编辑对象。 */
async function 生成智能图形({ 主题, 类型, 调用模型, 推送, 信号 }) {
  要求模型(调用模型)
  if (!非空文本(主题, 500)) throw new Error('请填写有效的图形主题')
  if (!图形类型白名单.includes(类型)) throw new Error(`图形类型无效：只支持 ${图形类型白名单.join('、')}`)
  const 数据 = await 请求({
    调用模型,
    系统提示: 通用系统提示,
    用户内容: `请生成结构化图形，只返回 {"节点":[{"标识":"n1","文本":""}],"连线":[{"起点":"n1","终点":"n2","文本":""}]}。节点标识必须唯一，连线两端必须是已给出的节点标识。\n` + JSON.stringify({ 主题, 类型 }),
    推送, 信号,
  })
  if (!Array.isArray(数据.节点) || 数据.节点.length === 0) throw new Error('模型返回的图形节点格式无效（缺少节点数组），未修改文稿')
  if (数据.节点.length > 图形节点上限) throw new Error(`模型返回的节点过多：最多 ${图形节点上限} 个`)
  const 标识集合 = new Set()
  const 节点 = 数据.节点.map((项, 序号) => {
    if (!是记录(项) || !非空文本(项.标识, 64)) throw new Error(`第 ${序号 + 1} 个节点缺少有效标识`)
    if (标识集合.has(项.标识)) throw new Error(`模型返回了重复节点标识：${项.标识}`)
    标识集合.add(项.标识)
    if (!非空文本(项.文本, 60)) throw new Error(`节点 ${项.标识} 的文本无效或过长（最多 60 字）`)
    return { 标识: 项.标识.trim(), 文本: 项.文本.trim() }
  })
  const 连线原文 = 数据.连线 ?? []
  if (!Array.isArray(连线原文)) throw new Error('模型返回的连线格式无效')
  const 连线 = 连线原文.map((项, 序号) => {
    if (!是记录(项) || !非空文本(项.起点, 64) || !非空文本(项.终点, 64)) throw new Error(`第 ${序号 + 1} 条连线格式无效`)
    if (!标识集合.has(项.起点) || !标识集合.has(项.终点)) throw new Error(`第 ${序号 + 1} 条连线引用了不存在的节点：${项.起点} → ${项.终点}`)
    if (项.文本 !== undefined && !非空文本(项.文本, 40)) throw new Error(`第 ${序号 + 1} 条连线的文本无效或过长`)
    return { 起点: 项.起点.trim(), 终点: 项.终点.trim(), ...(项.文本 ? { 文本: 项.文本.trim() } : {}) }
  })
  return { 节点, 连线 }
}

/** 素材语义搜索：模型只对给定素材排序，不得编造或遗漏。 */
async function 摘要素材候选({ 查询, 素材列表, 调用模型, 推送, 信号 }) {
  要求模型(调用模型)
  if (!非空文本(查询, 200)) throw new Error('请填写有效的检索关键词')
  if (!Array.isArray(素材列表) || 素材列表.length === 0) throw new Error('没有可检索的素材')
  const 允许标识 = new Set()
  for (const 项 of 素材列表) {
    if (!是记录(项) || !非空文本(项.标识, 128)) throw new Error('素材列表的标识无效')
    允许标识.add(项.标识)
  }
  const 数据 = await 请求({
    调用模型,
    系统提示: 通用系统提示,
    用户内容: `请按相关性对下列素材排序，只返回 {"结果":[{"标识":"","相关度":0,"理由":""}]}。标识必须来自给定列表，不得新增、删除或改名。\n` + JSON.stringify({ 查询, 素材列表 }),
    推送, 信号,
  })
  if (!Array.isArray(数据.结果)) throw new Error('模型返回的检索结果格式无效（缺少结果数组）')
  const 结果 = 数据.结果.map((项, 序号) => {
    if (!是记录(项) || !非空文本(项.标识, 128)) throw new Error(`第 ${序号 + 1} 条检索结果缺少有效标识`)
    if (!允许标识.has(项.标识)) throw new Error(`模型返回了不属于候选列表的素材标识：${项.标识}`)
    if (typeof 项.相关度 !== 'number' || !Number.isFinite(项.相关度) || 项.相关度 < 0 || 项.相关度 > 100) throw new Error(`素材 ${项.标识} 的相关度无效`)
    if (!非空文本(项.理由, 说明上限)) throw new Error(`素材 ${项.标识} 的理由无效或过长`)
    return { 标识: 项.标识.trim(), 相关度: 项.相关度, 理由: 项.理由.trim() }
  })
  const 返回标识 = new Set(结果.map((项) => 项.标识))
  for (const 标识 of 允许标识) if (!返回标识.has(标识)) throw new Error(`模型返回的检索结果缺少素材：${标识}`)
  return { 结果 }
}

/** 应用候选前核对原内容版本：页面消失或版本变化一律阻止写入。 */
function 校验候选可应用(候选, 当前页面列表, 版本表) {
  if (!Array.isArray(候选) || !Array.isArray(当前页面列表) || !是记录(版本表)) throw new Error('候选或当前文稿信息格式无效')
  const 当前表 = new Map(当前页面列表.map((项) => [项.页标识, 项.版本]))
  return 候选.map((项) => {
    if (!是记录(项) || !非空文本(项.页标识, 64)) throw new Error('候选条目的页标识无效')
    if (!当前表.has(项.页标识)) throw new Error(`页面已不存在，已阻止写入：${项.页标识}`)
    if (版本表[项.页标识] !== 当前表.get(项.页标识)) throw new Error(`页面 ${项.页标识} 的文稿已变化，已阻止写入`)
    return 项
  })
}

