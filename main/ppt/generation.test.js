const {
  生成提纲, 生成页面, 生成单页, 生成美化建议, 生成智能图形, 摘要素材候选, 校验候选可应用,
  提纲页数上限, 单页要点上限, 图形节点上限,
} = require('./generation')

/** 构造一个按顺序返回固定 JSON 的假模型；记录收到的提示词便于断言。 */
const 假模型 = (...响应列表) => {
  const 调用 = []
  const 函数 = async ({ 系统提示, 用户内容, 推送, 信号 }) => {
    调用.push({ 系统提示, 用户内容, 推送: Boolean(推送), 信号: Boolean(信号) })
    const 下一个 = 响应列表.shift()
    if (下一个 instanceof Error) throw 下一个
    return typeof 下一个 === 'string' ? 下一个 : JSON.stringify(下一个)
  }
  函数.调用 = 调用
  return 函数
}

describe('演示文稿生成编排', () => {
  it('生成提纲：按页数与结构约束返回可确认的提纲', async () => {
    const 模型 = 假模型({
      提纲: [
        { 页标识: 'p1', 标题: '季度目标', 版式: '标题幻灯片', 要点: ['收入目标', '交付节奏'] },
        { 页标识: 'p2', 标题: '关键举措', 版式: '标题和内容', 要点: ['渠道扩展'] },
      ],
    })
    const 结果 = await 生成提纲({ 主题: '季度汇报', 受众: '管理层', 页数: 2, 风格: '简洁', 调用模型: 模型 })
    expect(结果.提纲).toHaveLength(2)
    expect(结果.提纲[0]).toMatchObject({ 页标识: 'p1', 标题: '季度目标', 版式: '标题幻灯片' })
    expect(模型.调用[0].用户内容).toContain('季度汇报')
    expect(模型.调用[0].系统提示).toContain('JSON')
  })

  it('生成提纲：页数越界、坏 JSON、要点超限与缺少模型入口都给出真实原因', async () => {
    await expect(生成提纲({ 主题: 'x', 页数: 0, 调用模型: 假模型() })).rejects.toThrow('页数')
    await expect(生成提纲({ 主题: 'x', 页数: 提纲页数上限 + 1, 调用模型: 假模型() })).rejects.toThrow('页数')
    await expect(生成提纲({ 主题: 'x', 页数: 1 })).rejects.toThrow('必须调用 AI 模型服务')
    await expect(生成提纲({ 主题: 'x', 页数: 1, 调用模型: 假模型('这不是 JSON') })).rejects.toThrow('格式无效')
    await expect(生成提纲({ 主题: 'x', 页数: 1, 调用模型: 假模型({ 提纲: [{ 页标识: 'p1', 标题: 't', 版式: '未知版式', 要点: [] }] }) })).rejects.toThrow('版式')
    await expect(生成提纲({ 主题: 'x', 页数: 1, 调用模型: 假模型({ 提纲: [{ 页标识: 'p1', 标题: 't', 版式: '空白', 要点: new Array(单页要点上限 + 1).fill('点') }] }) })).rejects.toThrow('要点')
    await expect(生成提纲({ 主题: 'x', 页数: 2, 调用模型: 假模型({ 提纲: [{ 页标识: 'p1', 标题: 't', 版式: '空白', 要点: [] }] }) })).rejects.toThrow('数量')
  })

  it('生成提纲：模型服务错误原样透出，取消后停止', async () => {
    await expect(生成提纲({ 主题: 'x', 页数: 1, 调用模型: 假模型(new Error('模型服务鉴权失败，请检查密钥和访问权限')) })).rejects.toThrow('鉴权失败')
    const 控制器 = new AbortController(); 控制器.abort()
    await expect(生成提纲({ 主题: 'x', 页数: 1, 调用模型: 假模型({ 提纲: [] }), 信号: 控制器.signal })).rejects.toThrow('已停止生成')
  })

  it('生成页面：提纲每一项都要有结果，超长文本与非法标识拒绝', async () => {
    const 提纲 = [
      { 页标识: 'p1', 标题: '一', 版式: '标题幻灯片', 要点: [] },
      { 页标识: 'p2', 标题: '二', 版式: '标题和内容', 要点: [] },
    ]
    const 正常 = 假模型({ 页面: [
      { 页标识: 'p1', 标题: '一', 正文: '开场', 版式: '标题幻灯片', 要点: [] },
      { 页标识: 'p2', 标题: '二', 正文: '内容', 版式: '标题和内容', 要点: ['a', 'b'] },
    ] })
    const 结果 = await 生成页面({ 提纲, 调用模型: 正常 })
    expect(结果.页面.map((页) => 页.页标识)).toEqual(['p1', 'p2'])
    await expect(生成页面({ 提纲, 调用模型: 假模型({ 页面: [{ 页标识: 'p1', 标题: '一', 正文: '', 版式: '标题幻灯片', 要点: [] }] }) })).rejects.toThrow('缺少')
    await expect(生成页面({ 提纲, 调用模型: 假模型({ 页面: [
      { 页标识: 'p1', 标题: '一', 正文: '', 版式: '标题幻灯片', 要点: [] },
      { 页标识: 'p9', 标题: '二', 正文: '', 版式: '空白', 要点: [] },
    ] }) })).rejects.toThrow('不属于')
    await expect(生成页面({ 提纲, 调用模型: 假模型({ 页面: [
      { 页标识: 'p1', 标题: '一', 正文: '', 版式: '标题幻灯片', 要点: [] },
      { 页标识: 'p2', 标题: '二', 正文: 'x'.repeat(4000), 版式: '标题和内容', 要点: [] },
    ] }) })).rejects.toThrow('过长')
  })

  it('生成单页：版式白名单与内容长度校验', async () => {
    const 模型 = 假模型({ 页面: { 标题: '封面', 正文: '副标题', 版式: '标题幻灯片', 要点: [] } })
    const 结果 = await 生成单页({ 内容: '季度总结', 版式: '标题幻灯片', 调用模型: 模型 })
    expect(结果.页面.标题).toBe('封面')
    await expect(生成单页({ 内容: 'x', 版式: '整页图片', 调用模型: 假模型() })).rejects.toThrow('版式')
  })

  it('智能美化：只接受登记字段，页面标识必须来自请求，范围越界拒绝', async () => {
    const 请求页 = [
      { 页标识: 'p1', 版式: '标题和内容' },
      { 页标识: 'p2', 版式: '空白' },
    ]
    const 模型 = 假模型({ 建议: [
      { 页标识: 'p1', 对齐: '左对齐', 字号建议: 28, 要点上限: 4, 背景建议: '浅色', 版式建议: '标题和内容', 说明: '压缩要点' },
      { 页标识: 'p2', 对齐: '居中', 字号建议: 24, 要点上限: 3, 背景建议: '深色', 版式建议: '空白', 说明: '突出标题' },
    ] })
    const 结果 = await 生成美化建议({ 页面列表: 请求页, 主题摘要: '深色主题', 调用模型: 模型 })
    expect(结果.建议).toHaveLength(2)
    await expect(生成美化建议({ 页面列表: 请求页, 调用模型: 假模型({ 建议: [{ 页标识: 'p9', 对齐: '左对齐', 字号建议: 24, 要点上限: 3, 背景建议: '浅色', 版式建议: '空白' }] }) })).rejects.toThrow('不属于')
    await expect(生成美化建议({ 页面列表: 请求页, 调用模型: 假模型({ 建议: [
      { 页标识: 'p1', 对齐: '左对齐', 字号建议: 24, 要点上限: 3, 背景建议: '浅色', 版式建议: '空白' },
      { 页标识: 'p2', 对齐: '左对齐', 字号建议: 999, 要点上限: 3, 背景建议: '浅色', 版式建议: '空白' },
    ] }) })).rejects.toThrow('字号')
    await expect(生成美化建议({ 页面列表: 请求页, 调用模型: 假模型({ 建议: [
      { 页标识: 'p1', 对齐: '左对齐', 字号建议: 24, 要点上限: 3, 背景建议: '浅色', 版式建议: '空白', 额外字段: 1 },
      { 页标识: 'p2', 对齐: '左对齐', 字号建议: 24, 要点上限: 3, 背景建议: '浅色', 版式建议: '空白' },
    ] }) })).rejects.toThrow('未登记字段')
  })

  it('智能图形：节点标识唯一、连线引用必须存在、数量与类型受限', async () => {
    const 模型 = 假模型({ 节点: [
      { 标识: 'n1', 文本: '开始' },
      { 标识: 'n2', 文本: '处理' },
    ], 连线: [{ 起点: 'n1', 终点: 'n2', 文本: '是' }] })
    const 结果 = await 生成智能图形({ 主题: '审批流程', 类型: '流程', 调用模型: 模型 })
    expect(结果.连线).toHaveLength(1)
    await expect(生成智能图形({ 主题: 'x', 类型: '散点', 调用模型: 假模型() })).rejects.toThrow('类型')
    await expect(生成智能图形({ 主题: 'x', 类型: '流程', 调用模型: 假模型({ 节点: [{ 标识: 'n1', 文本: 'a' }, { 标识: 'n1', 文本: 'b' }], 连线: [] }) })).rejects.toThrow('重复')
    await expect(生成智能图形({ 主题: 'x', 类型: '流程', 调用模型: 假模型({ 节点: [{ 标识: 'n1', 文本: 'a' }], 连线: [{ 起点: 'n1', 终点: 'n9' }] }) })).rejects.toThrow('连线')
    await expect(生成智能图形({ 主题: 'x', 类型: '流程', 调用模型: 假模型({ 节点: new Array(图形节点上限 + 1).fill(0).map((_, i) => ({ 标识: `n${i}`, 文本: 'a' })), 连线: [] }) })).rejects.toThrow('节点')
  })

  it('素材语义搜索：只能重排给定素材，不得编造或遗漏', async () => {
    const 素材 = [{ 标识: 'a1', 名称: '商务封面' }, { 标识: 'a2', 名称: '数据图表' }]
    const 模型 = 假模型({ 结果: [{ 标识: 'a2', 相关度: 90, 理由: '与数据页匹配' }, { 标识: 'a1', 相关度: 60, 理由: '可用于封面' }] })
    const 结果 = await 摘要素材候选({ 查询: '数据页配图', 素材列表: 素材, 调用模型: 模型 })
    expect(结果.结果.map((项) => 项.标识)).toEqual(['a2', 'a1'])
    await expect(摘要素材候选({ 查询: 'x', 素材列表: 素材, 调用模型: 假模型({ 结果: [{ 标识: 'a9', 相关度: 1, 理由: 'x' }] }) })).rejects.toThrow('不属于')
    await expect(摘要素材候选({ 查询: 'x', 素材列表: 素材, 调用模型: 假模型({ 结果: [{ 标识: 'a1', 相关度: 1, 理由: 'x' }] }) })).rejects.toThrow('缺少')
    await expect(摘要素材候选({ 查询: 'x', 素材列表: [], 调用模型: 假模型() })).rejects.toThrow('没有可检索的素材')
  })

  it('应用候选前核对原内容版本', () => {
    const 候选 = [{ 页标识: 'p1', 标题: '新标题' }]
    expect(校验候选可应用(候选, [{ 页标识: 'p1', 版本: 'v1' }], { p1: 'v1' })).toHaveLength(1)
    expect(() => 校验候选可应用(候选, [{ 页标识: 'p1', 版本: 'v1' }], { p1: 'v2' })).toThrow('文稿已变化')
    expect(() => 校验候选可应用(候选, [], { p1: 'v1' })).toThrow('页面已不存在')
  })
})
