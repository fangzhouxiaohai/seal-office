const { 语义校对, 校验建议可应用 } = require('./proofread')

const 条目 = (标识, 原文) => ({ 对象标识: 标识, 原文, 来源: `第 2 页/${标识}` })
const 模型返回 = (建议) => async () => JSON.stringify({ 建议 })

describe('演示语义校对', () => {
  it('返回逐条建议并保留对象标识与原文', async () => {
    const 调用模型 = vi.fn(模型返回([
      { 对象标识: '甲', 问题类型: '语义', 说明: '表述含糊', 建议文本: '明确的三月目标' },
      { 对象标识: '乙', 问题类型: '表达', 说明: '口语化', 建议文本: '敬请指正' },
    ]))
    const 结果 = await 语义校对({ 条目: [条目('甲', '三月目标'), 条目('乙', '请大家指正')], 调用模型 })
    expect(结果.建议).toEqual([
      { 对象标识: '甲', 原文: '三月目标', 问题类型: '语义', 说明: '表述含糊', 建议文本: '明确的三月目标' },
      { 对象标识: '乙', 原文: '请大家指正', 问题类型: '表达', 说明: '口语化', 建议文本: '敬请指正' },
    ])
    expect(调用模型.mock.calls[0][0].系统提示).toContain('JSON')
    expect(调用模型.mock.calls[0][0].系统提示).toContain('语义')
  })

  it('没有问题时返回空建议而不是报错', async () => {
    const 结果 = await 语义校对({ 条目: [条目('甲', '内容正确')], 调用模型: 模型返回([]) })
    expect(结果.建议).toEqual([])
    expect(结果.检查对象数).toBe(1)
  })

  it('越界对象标识、缺字段与空建议文本一律拒绝', async () => {
    await expect(语义校对({ 条目: [条目('甲', '内容')], 调用模型: 模型返回([{ 对象标识: '丙', 问题类型: '语义', 说明: 'x', 建议文本: 'y' }]) }))
      .rejects.toThrow('不属于本次校对范围')
    await expect(语义校对({ 条目: [条目('甲', '内容')], 调用模型: 模型返回([{ 对象标识: '甲', 说明: '缺少类型', 建议文本: 'y' }]) }))
      .rejects.toThrow('建议格式无效')
    await expect(语义校对({ 条目: [条目('甲', '内容')], 调用模型: 模型返回([{ 对象标识: '甲', 问题类型: '语义', 说明: 'x', 建议文本: '   ' }]) }))
      .rejects.toThrow('建议文本为空')
  })

  it('模型被截断或返回非 JSON 时报真实原因', async () => {
    await expect(语义校对({ 条目: [条目('甲', '内容')], 调用模型: async () => '{"建议":[{"对象标识":"甲"' })).rejects.toThrow('校对结果格式无效')
    await expect(语义校对({ 条目: [条目('甲', '内容')], 调用模型: async () => '我无法完成这个任务' })).rejects.toThrow('校对结果格式无效')
  })

  it('停止、缺少模型入口与空范围分别给出真实原因', async () => {
    const 控制器 = new AbortController()
    await expect(语义校对({ 条目: [条目('甲', '内容')], 调用模型: async () => { 控制器.abort(); return JSON.stringify({ 建议: [] }) }, 信号: 控制器.signal }))
      .rejects.toThrow('已停止生成')
    await expect(语义校对({ 条目: [条目('甲', '内容')] })).rejects.toThrow('必须调用 AI 模型服务')
    await expect(语义校对({ 条目: [], 调用模型: async () => '{}' })).rejects.toThrow('没有需要校对的内容')
    await expect(语义校对({ 条目: [条目('甲', '   ')], 调用模型: async () => '{}' })).rejects.toThrow('没有需要校对的内容')
  })

  it('分批校对时按批次核对对象范围', async () => {
    const 调用模型 = vi.fn(async ({ 用户内容 }) => {
      const 数据 = JSON.parse(用户内容.slice(用户内容.indexOf('{')))
      return JSON.stringify({ 建议: 数据.条目.map((项) => ({ 对象标识: 项.对象标识, 问题类型: '语义', 说明: '需检查', 建议文本: '改-' + 项.对象标识 })) })
    })
    const 结果 = await 语义校对({ 条目: ['a', 'b', 'c'].map((标识) => 条目(标识, `原文-${标识}`)), 每批条数: 2, 调用模型 })
    expect(调用模型).toHaveBeenCalledTimes(2)
    expect(结果.建议.map((项) => 项.建议文本)).toEqual(['改-a', '改-b', '改-c'])
  })
})

describe('校对建议应用前的原内容核对', () => {
  it('原文变化或对象消失时阻止应用', () => {
    const 建议 = [{ 对象标识: '甲', 原文: '旧文本', 建议文本: '新文本' }]
    expect(() => 校验建议可应用(建议, [{ 对象标识: '甲', 原文: '已改动' }])).toThrow('原文已变化')
    expect(() => 校验建议可应用(建议, [{ 对象标识: '乙', 原文: '旧文本' }])).toThrow('对象已不存在')
    expect(校验建议可应用(建议, [{ 对象标识: '甲', 原文: '旧文本' }])).toHaveLength(1)
  })
})
