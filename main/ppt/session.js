// 演示文稿会话：同文件多个编辑窗口共享内容、版本、保存结果与路径占用。
// 纯内存实现，不触碰文件系统；调用方（主进程通道、窗口管理）负责持久化与广播。
/** 文稿标识 -> { 版本, 内容, 已保存, 路径, 视图:Set } */
function 创建文稿会话服务() {
  const 文稿表 = new Map()
  /** 保存路径 -> 文稿标识，用于另存路径占用 */
  const 路径占用 = new Map()

  const 取文稿 = (标识) => 文稿表.get(标识) ?? null
  const 失败 = (错误) => ({ 成功: false, 错误 })

  return {
    /** 注册视图：首次注册时带初始内容，之后注册复用既有内容与版本 */
    注册视图(文稿标识, 视图标识, 初始内容, 路径) {
      if (typeof 文稿标识 !== 'string' || 文稿标识.trim().length === 0) throw new Error('文稿标识无效')
      if (typeof 视图标识 !== 'string' || 视图标识.trim().length === 0) throw new Error('视图标识无效')
      let 文稿 = 取文稿(文稿标识)
      if (!文稿) {
        if (初始内容 === undefined) throw new Error('首次注册视图必须提供文稿内容')
        文稿 = { 版本: 1, 内容: 初始内容, 已保存: true, 路径: typeof 路径 === 'string' && 路径.length > 0 ? 路径 : null, 视图: new Set() }
        文稿表.set(文稿标识, 文稿)
      }
      文稿.视图.add(视图标识)
      return { 版本: 文稿.版本, 内容: 文稿.内容, 路径: 文稿.路径, 已保存: 文稿.已保存, 视图数: 文稿.视图.size }
    },

    /** 注销视图：返回是否为最后一个视图，最后一个视图关闭时释放文稿与路径占用 */
    注销视图(文稿标识, 视图标识) {
      const 文稿 = 取文稿(文稿标识)
      if (!文稿) return 失败('文稿不存在或已关闭')
      if (!文稿.视图.has(视图标识)) return 失败('该视图未注册到此文稿')
      文稿.视图.delete(视图标识)
      if (文稿.视图.size === 0) {
        if (文稿.路径 && 路径占用.get(文稿.路径) === 文稿标识) 路径占用.delete(文稿.路径)
        文稿表.delete(文稿标识)
        return { 成功: true, 是否最后视图: true }
      }
      return { 成功: true, 是否最后视图: false, 视图数: 文稿.视图.size }
    },

    读取(文稿标识) {
      const 文稿 = 取文稿(文稿标识)
      if (!文稿) return 失败('文稿不存在或已关闭')
      return { 成功: true, 版本: 文稿.版本, 内容: 文稿.内容, 路径: 文稿.路径, 已保存: 文稿.已保存, 视图: [...文稿.视图] }
    },

    /** 提交修改：版本必须与当前版本一致，过期版本拒绝并提示重新读取 */
    提交修改(文稿标识, 期望版本, 新内容) {
      const 文稿 = 取文稿(文稿标识)
      if (!文稿) return 失败('文稿不存在或已关闭')
      if (新内容 === undefined) return 失败('修改内容无效')
      if (!Number.isInteger(期望版本)) return 失败('内容版本无效')
      if (期望版本 !== 文稿.版本) return 失败(`内容版本已过期（当前版本 ${文稿.版本}），请重新读取最新内容后再提交`)
      文稿.版本 += 1
      文稿.内容 = 新内容
      文稿.已保存 = false
      return { 成功: true, 版本: 文稿.版本, 视图: [...文稿.视图] }
    },

    /** 标记已保存：写盘成功后所有视图看到一致的保存状态与路径 */
    标记已保存(文稿标识, 路径) {
      const 文稿 = 取文稿(文稿标识)
      if (!文稿) return 失败('文稿不存在或已关闭')
      if (路径 !== undefined) {
        if (typeof 路径 !== 'string' || 路径.trim().length === 0) return 失败('保存路径无效')
        const 占用者 = 路径占用.get(路径)
        if (占用者 !== undefined && 占用者 !== 文稿标识) return 失败(`保存路径已被其他文稿占用：${路径}`)
        if (文稿.路径 && 文稿.路径 !== 路径 && 路径占用.get(文稿.路径) === 文稿标识) 路径占用.delete(文稿.路径)
        文稿.路径 = 路径
        路径占用.set(路径, 文稿标识)
      }
      文稿.已保存 = true
      return { 成功: true, 版本: 文稿.版本, 路径: 文稿.路径, 视图数: 文稿.视图.size }
    },

    /** 认领保存路径：同一路径只能被一个文稿占用 */
    认领路径(文稿标识, 路径) {
      const 文稿 = 取文稿(文稿标识)
      if (!文稿) return 失败('文稿不存在或已关闭')
      if (typeof 路径 !== 'string' || 路径.trim().length === 0) return 失败('保存路径无效')
      const 占用者 = 路径占用.get(路径)
      if (占用者 !== undefined && 占用者 !== 文稿标识) return 失败(`保存路径已被其他文稿占用：${路径}`)
      if (文稿.路径 && 文稿.路径 !== 路径 && 路径占用.get(文稿.路径) === 文稿标识) 路径占用.delete(文稿.路径)
      文稿.路径 = 路径
      路径占用.set(路径, 文稿标识)
      return { 成功: true, 路径 }
    },

    /** 释放路径占用（另存失败或取消时使用） */
    释放路径(文稿标识, 路径) {
      const 文稿 = 取文稿(文稿标识)
      if (!文稿) return 失败('文稿不存在或已关闭')
      if (路径占用.get(路径) === 文稿标识) 路径占用.delete(路径)
      if (文稿.路径 === 路径) 文稿.路径 = null
      return { 成功: true }
    },

    列出视图(文稿标识) {
      const 文稿 = 取文稿(文稿标识)
      return 文稿 ? [...文稿.视图] : []
    },

    /** 会话视图总数，供关闭窗口时判断是否为最后一个视图 */
    视图总数() {
      let 总数 = 0
      for (const 文稿 of 文稿表.values()) 总数 += 文稿.视图.size
      return 总数
    },

    列出文稿() {
      return [...文稿表.keys()]
    },
  }
}

module.exports = { 创建文稿会话服务 }
