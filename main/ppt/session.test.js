const { 创建文稿会话服务 } = require('./session')

const 内容 = (文本) => ({ 幻灯片: [{ id: '页', title: '页', 背景色: '#FFFFFF', 文本框: [{ id: '文字', text: 文本, x: 0, y: 0, width: 100, height: 40, 字号: 18 }] }] })

describe('演示文稿会话与内容版本', () => {
  it('两个视图共享同一份内容与版本', () => {
    const 会话 = 创建文稿会话服务()
    会话.注册视图('文稿甲', '窗口一', 内容('初始'), 'E:\\资料\\甲.pptx')
    const 第二 = 会话.注册视图('文稿甲', '窗口二')
    expect(第二.版本).toBe(1)
    expect(第二.路径).toBe('E:\\资料\\甲.pptx')
    expect(会话.读取('文稿甲').内容.幻灯片[0].文本框[0].text).toBe('初始')
    expect(会话.列出视图('文稿甲').sort()).toEqual(['窗口一', '窗口二'])
  })

  it('先提交的修改生效，过期版本提交被拒绝并提示重新读取', () => {
    const 会话 = 创建文稿会话服务()
    const 甲 = 会话.注册视图('文稿甲', '窗口一', 内容('初始'))
    const 乙 = 会话.注册视图('文稿甲', '窗口二')
    const 成功 = 会话.提交修改('文稿甲', 甲.版本, 内容('窗口一改'))
    expect(成功).toMatchObject({ 成功: true, 版本: 2 })
    expect(会话.读取('文稿甲').内容.幻灯片[0].文本框[0].text).toBe('窗口一改')
    const 冲突 = 会话.提交修改('文稿甲', 乙.版本, 内容('窗口二改'))
    expect(冲突.成功).toBe(false)
    expect(冲突.错误).toContain('版本')
    expect(会话.读取('文稿甲').内容.幻灯片[0].文本框[0].text).toBe('窗口一改')
    const 重试 = 会话.提交修改('文稿甲', 会话.读取('文稿甲').版本, 内容('窗口二改'))
    expect(重试).toMatchObject({ 成功: true, 版本: 3 })
    expect(会话.读取('文稿甲').内容.幻灯片[0].文本框[0].text).toBe('窗口二改')
  })

  it('标记已保存后所有视图看到一致的保存状态', () => {
    const 会话 = 创建文稿会话服务()
    const 甲 = 会话.注册视图('文稿甲', '窗口一', 内容('初始'))
    会话.注册视图('文稿甲', '窗口二')
    会话.提交修改('文稿甲', 甲.版本, 内容('改过'))
    expect(会话.读取('文稿甲').已保存).toBe(false)
    const 保存 = 会话.标记已保存('文稿甲', 'E:\\资料\\甲.pptx')
    expect(保存).toMatchObject({ 版本: 2, 路径: 'E:\\资料\\甲.pptx' })
    expect(会话.读取('文稿甲').已保存).toBe(true)
    expect(会话.读取('文稿甲').路径).toBe('E:\\资料\\甲.pptx')
  })

  it('关闭最后一个视图才释放文稿，其余视图关闭不影响内容', () => {
    const 会话 = 创建文稿会话服务()
    会话.注册视图('文稿甲', '窗口一', 内容('初始'))
    会话.注册视图('文稿甲', '窗口二')
    expect(会话.注销视图('文稿甲', '窗口一')).toMatchObject({ 成功: true, 是否最后视图: false })
    expect(会话.读取('文稿甲').内容.幻灯片[0].文本框[0].text).toBe('初始')
    expect(会话.注销视图('文稿甲', '窗口二')).toMatchObject({ 成功: true, 是否最后视图: true })
    expect(会话.读取('文稿甲')).toMatchObject({ 成功: false })
    expect(会话.读取('文稿甲').错误).toContain('不存在')
  })

  it('同一路径只能被一个文稿认领，释放后可再次认领', () => {
    const 会话 = 创建文稿会话服务()
    会话.注册视图('文稿甲', '窗口一', 内容('甲'))
    会话.注册视图('文稿乙', '窗口二', 内容('乙'))
    expect(会话.认领路径('文稿甲', 'E:\\资料\\同一.pptx')).toMatchObject({ 成功: true })
    const 冲突 = 会话.认领路径('文稿乙', 'E:\\资料\\同一.pptx')
    expect(冲突.成功).toBe(false)
    expect(冲突.错误).toContain('已被')
    expect(会话.认领路径('文稿甲', 'E:\\资料\\同一.pptx')).toMatchObject({ 成功: true })
    会话.注销视图('文稿甲', '窗口一')
    expect(会话.认领路径('文稿乙', 'E:\\资料\\同一.pptx')).toMatchObject({ 成功: true })
  })

  it('对不存在的文稿或未注册视图给出真实原因', () => {
    const 会话 = 创建文稿会话服务()
    expect(会话.读取('不存在').成功).toBe(false)
    expect(会话.读取('不存在').错误).toContain('不存在')
    expect(会话.提交修改('不存在', 1, 内容('x')).成功).toBe(false)
    会话.注册视图('文稿甲', '窗口一', 内容('初始'))
    expect(会话.注销视图('文稿甲', '窗口九').成功).toBe(false)
    expect(会话.注销视图('文稿甲', '窗口九').错误).toContain('视图')
    expect(会话.提交修改('文稿甲', 0, 内容('x')).成功).toBe(false)
    expect(会话.提交修改('文稿甲', 99, 内容('x')).错误).toContain('版本')
  })
})
