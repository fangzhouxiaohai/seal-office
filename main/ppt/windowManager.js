// 多窗口管理：新建窗口、重排窗口与关闭视图的会话语义。
// 通过注入「创建浏览器窗口」与屏幕尺寸，使窗口行为可在无 Electron 环境下回归。
function 创建窗口管理器({ 会话, 创建浏览器窗口, 屏幕尺寸, 应用入口 = () => '' }) {
  const 窗口表 = new Map()
  let 序号 = 0

  const 失败 = (错误) => ({ 成功: false, 错误 })

  return {
    /** 新建窗口：沿用同一应用入口，并把视图注册到既有文稿；文稿不存在时拒绝 */
    新建窗口(文稿标识, 视图标识) {
      const 读取 = 会话.读取(文稿标识)
      if (!读取.成功) return 失败(`文稿不存在或已关闭：${文稿标识}`)
      序号 += 1
      const 窗口标识 = `窗口${序号}`
      const 窗口 = 创建浏览器窗口({ 入口: 应用入口(), 窗口标识, 文稿标识, 视图标识 })
      窗口表.set(窗口标识, { 窗口标识, 文稿标识, 视图标识, 窗口 })
      const 注册 = 会话.注册视图(文稿标识, 视图标识)
      return { 成功: true, 窗口标识, 版本: 注册.版本 }
    },

    /**
     * 关闭窗口：注销视图并返回剩余窗口数与未保存威胁。
     * 只有「最后一个视图且内容未保存」才算有丢失风险；其他视图仍持有文稿时不重复提示。
     */
    关闭窗口(窗口标识) {
      const 记录 = 窗口表.get(窗口标识)
      if (!记录) return 失败('窗口不存在或已关闭')
      const 关闭前 = 会话.读取(记录.文稿标识)
      const 注销 = 会话.注销视图(记录.文稿标识, 记录.视图标识)
      if (!注销.成功) return 失败(注销.错误)
      窗口表.delete(窗口标识)
      try { 记录.窗口?.destroy?.() } catch { /* 窗口已销毁时忽略 */ }
      const 威胁 = []
      if (注销.是否最后视图 && 关闭前.成功 && 关闭前.已保存 === false) {
        威胁.push({ 文稿标识: 记录.文稿标识, 未保存: true })
      }
      return { 成功: true, 剩余窗口数: 窗口表.size, 威胁 }
    },

    列出窗口() {
      return [...窗口表.values()].map(记录 => ({ 窗口标识: 记录.窗口标识, 文稿标识: 记录.文稿标识, 视图标识: 记录.视图标识 }))
    },

    /** 重排窗口：只调整窗口位置与大小，不触碰会话内容与版本 */
    重排窗口(布局) {
      if (布局 !== '平铺' && 布局 !== '层叠') return 失败('布局不受支持，只支持 平铺 或 层叠')
      const 记录列表 = [...窗口表.values()]
      if (记录列表.length === 0) return 失败('没有可重排的窗口')
      const { x: 起点x, y: 起点y, 宽, 高 } = 屏幕尺寸()
      const 位置 = []
      if (布局 === '平铺') {
        const 列数 = Math.ceil(Math.sqrt(记录列表.length))
        const 行数 = Math.ceil(记录列表.length / 列数)
        const 单元宽 = Math.floor(宽 / 列数)
        const 单元高 = Math.floor(高 / 行数)
        记录列表.forEach((记录, i) => {
          const 列 = i % 列数
          const 行 = Math.floor(i / 列数)
          const 项 = { x: 起点x + 列 * 单元宽, y: 起点y + 行 * 单元高, 宽: 单元宽, 高: 单元高 }
          位置.push(项)
          记录.窗口?.setBounds?.(项)
        })
      } else {
        const 单窗 = 记录列表.length === 1
        记录列表.forEach((记录, i) => {
          const 项 = 单窗
            ? { x: 起点x, y: 起点y, 宽, 高 }
            : { x: 起点x + i * 24, y: 起点y + i * 24, 宽: Math.max(480, 宽 - i * 48), 高: Math.max(320, 高 - i * 48) }
          位置.push(项)
          记录.窗口?.setBounds?.(项)
        })
      }
      return { 成功: true, 布局, 位置 }
    },
  }
}

module.exports = { 创建窗口管理器 }
