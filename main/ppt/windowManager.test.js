const { 创建窗口管理器 } = require('./windowManager')
const { 创建文稿会话服务 } = require('../ppt/session')

const 内容 = (文本) => ({ 幻灯片: [{ id: '页', title: '页', 背景色: '#FFFFFF', 文本框: [{ id: '文字', text: 文本, x: 0, y: 0, width: 100, height: 40, 字号: 18 }] }] })

const 准备 = () => {
  const 会话 = 创建文稿会话服务()
  const 已创建 = []
  const 管理器 = 创建窗口管理器({
    会话,
    创建浏览器窗口: (选项) => {
      const 窗口 = { id: `窗口${已创建.length + 1}`, 选项, 已销毁: false, destroy() { this.已销毁 = true } }
      已创建.push(窗口)
      return 窗口
    },
    屏幕尺寸: () => ({ x: 0, y: 0, 宽: 1600, 高: 900 }),
    应用入口: () => '应用入口地址',
  })
  return { 会话, 管理器, 已创建 }
}

describe('多窗口管理', () => {
  it('新建窗口沿用同一应用入口并登记视图', () => {
    const { 管理器, 会话, 已创建 } = 准备()
    会话.注册视图('文稿甲', '视图一', 内容('初始'), 'E:\\资料\\甲.pptx')
    const 结果 = 管理器.新建窗口('文稿甲', '视图二')
    expect(结果).toMatchObject({ 成功: true, 窗口标识: '窗口1' })
    expect(已创建[0].选项).toMatchObject({ 入口: '应用入口地址' })
    // 新窗口必须带上文稿与视图身份，主进程据此登记会话身份，渲染端才能接管同一文稿
    expect(已创建[0].选项).toMatchObject({ 文稿标识: '文稿甲', 视图标识: '视图二' })
    expect(会话.列出视图('文稿甲').sort()).toEqual(['视图一', '视图二'])
    expect(管理器.列出窗口()).toHaveLength(1)
  })

  it('关闭一个视图而同一文稿还有其他视图时不报告未保存威胁', () => {
    const { 管理器, 会话 } = 准备()
    会话.注册视图('文稿甲', '视图一', 内容('初始'))
    const 窗口一 = 管理器.新建窗口('文稿甲', '视图一')
    const 窗口二 = 管理器.新建窗口('文稿甲', '视图二')
    const 版本 = 会话.读取('文稿甲').版本
    会话.提交修改('文稿甲', 版本, 内容('改过'))
    const 结果 = 管理器.关闭窗口(窗口一.窗口标识)
    expect(结果).toMatchObject({ 成功: true, 剩余窗口数: 1, 威胁: [] })
    expect(会话.读取('文稿甲').内容.幻灯片[0].文本框[0].text).toBe('改过')
    expect(管理器.列出窗口().map(项 => 项.窗口标识)).toEqual([窗口二.窗口标识])
  })

  it('关闭最后一个持有未保存内容的视图时报告威胁，已保存则不再提示', () => {
    const { 管理器, 会话 } = 准备()
    会话.注册视图('文稿甲', '视图一', 内容('初始'))
    const 窗口一 = 管理器.新建窗口('文稿甲', '视图一')
    会话.提交修改('文稿甲', 会话.读取('文稿甲').版本, 内容('改过'))
    expect(管理器.关闭窗口(窗口一.窗口标识).威胁).toEqual([{ 文稿标识: '文稿甲', 未保存: true }])

    会话.注册视图('文稿乙', '视图一', 内容('另一份'))
    const 窗口二 = 管理器.新建窗口('文稿乙', '视图一')
    会话.提交修改('文稿乙', 会话.读取('文稿乙').版本, 内容('乙改过'))
    会话.标记已保存('文稿乙', 'E:\\资料\\乙.pptx')
    expect(管理器.关闭窗口(窗口二.窗口标识).威胁).toEqual([])
  })

  it('重排窗口只改变显示位置，不改动内容与版本', () => {
    const { 管理器, 会话 } = 准备()
    会话.注册视图('文稿甲', '视图一', 内容('初始'))
    管理器.新建窗口('文稿甲', '视图一')
    管理器.新建窗口('文稿甲', '视图一')
    const 版本前 = 会话.读取('文稿甲').版本
    const 结果 = 管理器.重排窗口('平铺')
    expect(结果.成功).toBe(true)
    expect(结果.位置).toEqual([
      { x: 0, y: 0, 宽: 800, 高: 900 },
      { x: 800, y: 0, 宽: 800, 高: 900 },
    ])
    expect(会话.读取('文稿甲').版本).toBe(版本前)
    expect(会话.读取('文稿甲').内容.幻灯片[0].文本框[0].text).toBe('初始')
  })

  it('层叠布局按序号错开，窗口数量为一时占满工作区', () => {
    const { 管理器, 会话 } = 准备()
    会话.注册视图('文稿甲', '视图一', 内容('初始'))
    管理器.新建窗口('文稿甲', '视图一')
    expect(管理器.重排窗口('层叠').位置[0]).toEqual({ x: 0, y: 0, 宽: 1600, 高: 900 })
    管理器.新建窗口('文稿甲', '视图一')
    const 位置 = 管理器.重排窗口('层叠').位置
    expect(位置).toHaveLength(2)
    expect(位置[1].x).toBeGreaterThan(位置[0].x)
    expect(位置[1].y).toBeGreaterThan(位置[0].y)
    expect(位置[1].宽).toBeLessThan(位置[0].宽)
  })

  it('未知窗口、未知布局与未注册文稿给出真实原因', () => {
    const { 管理器 } = 准备()
    expect(管理器.关闭窗口('窗口九').成功).toBe(false)
    expect(管理器.关闭窗口('窗口九').错误).toContain('窗口')
    expect(管理器.重排窗口('随机').成功).toBe(false)
    expect(管理器.重排窗口('随机').错误).toContain('布局')
    const 结果 = 管理器.新建窗口('文稿甲', '视图一')
    expect(结果.成功).toBe(false)
    expect(结果.错误).toContain('不存在')
  })
})
