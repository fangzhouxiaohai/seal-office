// Production file:// UI regression with a deterministic Harmony host transport.
// It does not substitute for installing a signed HAP on a HarmonyOS device.
const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), JSZip = require('jszip')
const root = path.resolve(__dirname, '../..'), output = path.join(root, '.upgrade-private/harmony-review-20261015/verification')
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
app.disableHardwareAcceleration(); app.setPath('userData', path.join(output, 'profile-' + process.pid))
app.whenReady().then(async () => {
  fs.mkdirSync(output, { recursive: true })
  const win = new BrowserWindow({ show: false, width: 390, height: 844, webPreferences: { offscreen: true, sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } })
  const checks = [], errors = []
  win.webContents.on('will-prevent-unload', event => event.preventDefault())
  win.webContents.on('render-process-gone', (_, details) => errors.push(details.reason))
  const diagnostics=[]
  win.webContents.on('console-message', (_,level,message)=>{if(level>=3)diagnostics.push(message.slice(0,1000))})
  const evaluate = async code => {
    const result = await win.webContents.executeJavaScript(`(async()=>{try{return {value:await (0,eval)(${JSON.stringify(code)})}}catch(e){return {error:e.stack||String(e)}}})()`, true)
    if (result.error) throw new Error(result.error)
    return result.value
  }
  const until = async code => { for (let i=0;i<150;i++) { if(await evaluate(code))return; await wait(100) } throw new Error('Timeout: '+code+'\n'+await evaluate('document.body.textContent.slice(-2000)')) }
  const click = async (name, selector='button') => { await evaluate(`(()=>{const b=Array.from(document.querySelectorAll(${JSON.stringify(selector)})).filter(b=>b.getClientRects().length && !b.closest('.ant-zoom-leave,.ant-fade-leave') && (b.getAttribute('aria-label')||b.textContent).replace(/\\s/g,'')===${JSON.stringify(name.replace(/\s/g,''))}).at(-1);if(!b)throw new Error('Missing button '+${JSON.stringify(name)});b.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,pointerType:'touch'}));b.click()})()`); await wait(100) }
  const type = async (selector, value) => evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw new Error('Missing input');Object.getOwnPropertyDescriptor(e instanceof HTMLTextAreaElement?HTMLTextAreaElement.prototype:HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  const back = async () => { await evaluate(`window.dispatchEvent(new Event('seal-native-back',{cancelable:true}));true`); await wait(200) }
  const selectText = async (end=false) => evaluate(`(()=>{const e=document.querySelector('.wps-editor-canvas__content');e.focus();const r=document.createRange();r.selectNodeContents(Array.from(e.querySelectorAll('p,li')).find(n=>!n.closest('[data-seal-notes]'))||e);${end?'r.collapse(false);':''}window.getSelection().removeAllRanges();window.getSelection().addRange(r);document.dispatchEvent(new Event('selectionchange'))})()`)
  const record = name => { checks.push(name); console.log('PASS '+name) }
  try {
    await win.loadFile(path.join(root,'mobile/static/office/index.html'))
    await until(`!!document.querySelector('.wps-app')`)
    await evaluate(`window.__nativeFont=${JSON.stringify(fs.readFileSync(path.join(root,'mobile/static/office/fonts/NotoSansSC.ttf')).toString('base64'))};true`)
    await evaluate(`window.__nativeSerifFont=${JSON.stringify(fs.readFileSync(path.join(root,'mobile/static/office/fonts/NotoSerifCJKsc-Regular.otf')).toString('base64'))};true`)
    await evaluate(`window.__nativeActions=[];window.__pickerQueue=[];window.__saveMode='saved';window.__clipboard='';window.sealNative={platform:'harmony',token:'review-fixture'};window.uni={webView:{postMessage:({data})=>{
      window.__nativeActions.push(data);
      const reply=(type,extra={})=>window.sealReceiveNative({id:data.id,type,...extra});
      if(data.action==='ping'){reply('ready');return}
      if(data.action==='save'||data.action==='print'){if(window.__saveMode!=='pending')setTimeout(()=>reply(data.action==='print'?'printed':window.__saveMode,{path:'file://selected/'+data.name}),0)}
      if(data.action==='pick-files'){const f=window.__pickerQueue.shift();if(!f){reply('cancel');return}reply('file-start',{name:f.name});for(let i=0;i<f.data.length;i+=32768)reply('chunk',{data:f.data.slice(i,i+32768)});reply('file-end');reply('end')}
      if(data.action==='clipboard-write'){window.__clipboard=data.text;reply('written')}
      if(data.action==='font'){const font=data.family==='serif'?window.__nativeSerifFont:window.__nativeFont;for(let i=0;i<font.length;i+=32768)reply('chunk',{data:font.slice(i,i+32768)});reply('end')}
      if(data.action==='request'){reply('end',{status:401,headers:{'Content-Type':'application/json'},data:btoa(JSON.stringify({error:'not_authenticated'}))})}
    }}};window.sealClipboard={writeText:async text=>{window.__clipboard=text}};Object.defineProperty(navigator,'clipboard',{configurable:true,value:{readText:async()=>{throw new DOMException('User paste required','NotAllowedError')}}});true`)
    // This historical review checks the Office export choice. The application
    // keeps its native default; only this fixture's selected Save As format is
    // DOCX/XLSX during the corresponding genuine ZIP/content assertions.
    await evaluate(`window.__reviewSaveFormat=null;window.__reviewFormatSelections=[];(()=>{const choose=window.electronAPI.showSaveDialog.bind(window.electronAPI);window.electronAPI.showSaveDialog=(name,kind)=>{const selected=window.__reviewSaveFormat?name.replace(/\\.[^.]+$/,'')+'.'+window.__reviewSaveFormat:name;window.__reviewFormatSelections.push({name,selected,kind});return choose(selected,kind)}})();true`)
    await click('未登录，点击登录')
    await until(`!!document.querySelector('.seal-login__brand img')`)
    assert.equal(await evaluate(`(async()=>{const i=document.querySelector('.seal-login__brand img');await i.decode();return i.naturalWidth>0})()`),true)
    await back(); await until(`!Array.from(document.querySelectorAll('.ant-modal-wrap')).some(e=>e.getClientRects().length&&getComputedStyle(e).display!=='none')`)
    await click('全部功能'); await back()
    assert.equal(await evaluate(`document.querySelector('[aria-label="全部功能"]').getAttribute('aria-expanded')`),'false')
    await click('全部功能'); await click('我的云空间')
    await until(`!!document.querySelector('.seal-drive-welcome')`)
    await click('登录并开通云空间'); await until(`!!document.querySelector('.seal-login__brand img')`)
    await back(); await back()
    assert.equal(await evaluate(`!!document.querySelector('.seal-drive-welcome')`),false)
    assert.equal(await evaluate(`location.protocol`),'file:')
    record('登录、云空间入口保持工作台；返回先关登录/功能面板，再回上级')
    await click('全部功能')
    assert.equal(await evaluate(`!!document.querySelector('[data-nav-key="database"]')`),false)
    await evaluate(`document.querySelector('[data-document-type="word"]').click()`)
    await until(`!!document.querySelector('.wps-editor-canvas__content')`)
    await evaluate(`(()=>{const e=document.querySelector('.wps-editor-canvas__content');e.focus();document.execCommand('insertText',false,'鸿蒙审核整改：中文字体、注释与保存。');e.dispatchEvent(new Event('input',{bubbles:true}))})()`)
    await evaluate(`document.querySelector('.wps-editor-canvas__content').dispatchEvent(new MouseEvent('dblclick',{bubbles:true}));true`)
    await wait(1600);assert.equal(await evaluate(`!!document.querySelector('.wps-editor-canvas__content')&&!document.body.textContent.includes('ERR_FILE_NOT_FOUND')`),true)
    await selectText()
    await click('字体')
    await click('思源宋体','.ant-dropdown-menu-item')
    await until(`document.querySelector('.wps-editor-canvas__content').innerHTML.includes('思源宋体')`)
    assert.ok(await evaluate(`(async()=>{await document.fonts.load('20px "思源宋体"');await document.fonts.load('20px "思源黑体"');return document.fonts.check('20px "思源宋体"')&&document.fonts.check('20px "思源黑体"')})()`))
    const metrics=await evaluate(`(()=>{const canvas=document.createElement('canvas');canvas.width=200;canvas.height=70;const c=canvas.getContext('2d');const draw=font=>{c.clearRect(0,0,200,70);c.font='40px "'+font+'"';c.fillText('汉字测试',0,50);return canvas.toDataURL()};return [draw('思源宋体'),draw('思源黑体')]})()`)
    assert.notEqual(metrics[0],metrics[1], 'Two bundled fonts must render different glyph pixels')
    record('触摸打开字体菜单保留选区；包内黑体/宋体实际加载并呈现不同字形')
    await selectText(); await click('复制'); await wait(150)
    assert.match(await evaluate(`window.__clipboard`),/鸿蒙审核整改/)
    await selectText(true); await click('粘贴')
    await until(`(document.querySelector('.wps-editor-canvas__content').textContent.match(/鸿蒙审核整改/g)||[]).length===2`)
    record('复制再粘贴实际插入文字，不依赖网页获得系统剪贴板读取权限')
    await selectText(); await click('编号'); await click('中文数字','.ant-dropdown-menu-item')
    await until(`getComputedStyle(document.querySelector('.wps-editor-canvas__content ol')).listStyleType==='cjk-ideographic'`)
    await click('页面布局','[role="tab"]'); await click('行号')
    await until(`document.querySelectorAll('.wps-line-numbers span').length>0`)
    const lines=await evaluate(`Array.from(document.querySelectorAll('.wps-line-numbers span')).map(e=>({n:e.textContent,top:e.getBoundingClientRect().top}))`)
    assert.equal(lines[0].n,'1'); assert.ok(Number.isFinite(lines[0].top))
    await selectText(true); await click('插入','[role="tab"]'); await click('脚注')
    await until(`!!document.querySelector('textarea[placeholder="脚注内容"]')`)
    await type('textarea[placeholder="脚注内容"]','鸿蒙脚注 & 测试')
    await click('插入','.ant-modal button')
    await until(`!!document.querySelector('[data-seal-notes="footnote"]')`)
    await selectText(true); await click('尾注'); await type('textarea[placeholder="尾注内容"]','鸿蒙尾注 & 测试'); await click('插入','.ant-modal button')
    await until(`!!document.querySelector('[data-seal-notes="endnote"]')`)
    await click('开始','[role="tab"]')
    await evaluate(`window.__reviewSaveFormat='docx';window.__saveMode='pending';true`)
    const before=await evaluate(`window.__nativeActions.filter(e=>e.action==='save').length`)
    await click('另存为')
    await until(`window.__nativeActions.filter(e=>e.action==='save').length>${before}`)
    assert.equal(await evaluate(`Array.from(document.querySelectorAll('.ant-message-notice')).some(e=>e.textContent.includes('文件已另存为'))`),false,'Must not claim saved before native acknowledgement')
    await evaluate(`(()=>{const d=window.__nativeActions.filter(e=>e.action==='save').at(-1);window.sealReceiveNative({id:d.id,type:'cancel'})})()`)
    await wait(250)
    assert.equal(await evaluate(`Array.from(document.querySelectorAll('.ant-modal-title')).some(e=>e.textContent.includes('保存失败'))`),false)
    await evaluate(`window.__saveMode='saved';true`); await click('另存为')
    await until(`document.body.textContent.includes('文件已另存为')`)
    const exported=await evaluate(`window.__nativeActions.filter(e=>e.action==='save').at(-1)`)
    const zip=await JSZip.loadAsync(Buffer.from(exported.data,'base64'))
    const xml=await zip.file('word/document.xml').async('string')
    assert.match(xml,/<w:footnoteReference/); assert.match(xml,/<w:endnoteReference/); assert.match(xml,/<w:lnNumType/)
    assert.match(await zip.file('word/numbering.xml').async('string'),/chineseCounting/)
    const bytes=Buffer.from(exported.data,'base64'); fs.writeFileSync(path.join(output,'review-word.docx'),bytes)
    const read=await evaluate(`window.electronAPI.office.readDocx(${JSON.stringify(exported.data)})`)
    assert.equal(read.成功,true); assert.deepEqual(read.警告,[]); assert.match(read.html,/鸿蒙脚注 &amp; 测试/); assert.match(read.html,/鸿蒙尾注 &amp; 测试/)
    assert.ok(await evaluate(`window.__reviewFormatSelections.some(item=>item.selected.endsWith('.docx'))`))
    await evaluate(`window.__reviewSaveFormat=null;true`)
    record('中文编号、真实行号、脚注尾注随 DOCX 保存读回；另存为等待宿主确认，取消无假成功')
    await evaluate(`(()=>{const preview=window.electronAPI.printPreview;window.electronAPI.printPreview=(html,format)=>{window.__lastPrintHTML=html;return preview(html,format)}})()`)
    await click('打印'); await until(`!!document.querySelector('.seal-print-preview .pdf-viewer__canvas')?.width`)
    // Canvas receives its dimensions before PDF.js asynchronously builds the text layer.
    await until(`document.querySelector('.seal-print-preview .pdf-viewer__text-layer')?.textContent.includes('鸿蒙审核整改')`)
    assert.equal(await evaluate(`document.querySelector('.seal-print-preview .pdf-viewer__text-layer').textContent.includes('鸿蒙审核整改')`),true)
    await click('打印','.ant-modal button')
    await until(`window.__nativeActions.some(e=>e.action==='print')`)
    record('中文打印预览完成渲染；确认后发送系统 print 而不是另存为 save')
    await until(`!Array.from(document.querySelectorAll('.ant-modal-wrap')).some(e=>e.getClientRects().length&&getComputedStyle(e).display!=='none')`)
    await click('导出为 PDF')
    await until(`window.__nativeActions.filter(e=>e.action==='save').at(-1)?.name.endsWith('.pdf')`)
    await until(`document.querySelector('.pdf-viewer__text-layer')?.textContent.includes('鸿蒙审核整改')`)
    const pdfExport=await evaluate(`window.__nativeActions.filter(e=>e.action==='save').at(-1)`)
    assert.equal(Buffer.from(pdfExport.data,'base64').subarray(0,5).toString(),'%PDF-')
    fs.writeFileSync(path.join(output,'review-export.pdf'),Buffer.from(pdfExport.data,'base64'))
    record('真实“导出为 PDF”按钮生成 .pdf 后缀文件并自动打开，不把 PDF 字节存成 .docx')
    const preview=await evaluate(`window.electronAPI.printPreview('<p>原生 PDF 导入验收</p>','html')`)
    assert.equal(preview.成功,true,JSON.stringify(preview))
    await evaluate(`window.__pickerQueue.push({name:'审核文档.pdf',data:${JSON.stringify(preview.数据)}});true`)
    await click('打开文件')
    await until(`document.querySelector('.pdf-viewer__text-layer')?.textContent.includes('原生 PDF 导入验收')`)
    await click('复制本页文字')
    await until(`window.__clipboard.includes('原生 PDF 导入验收')`)
    assert.ok(await evaluate(`window.__nativeActions.some(e=>e.action==='pick-files')`))
    record('鸿蒙原生选择器分块导入 PDF，扩展名校验及实际文字渲染通过')
    await click('全部功能'); await click('设置')
    await until(`!!document.querySelector('.wps-main--settings')`)
    await back(); await until(`!!document.querySelector('.pdf-viewer__text-layer')`)
    record('从已打开 PDF 进入设置后，返回恢复原 PDF 编辑标签')
    const xlsx=await evaluate(`window.electronAPI.office.writeXlsx({工作表:[{名称:'真实图表',数据:[['地区','收入'],['华北',120],['华南',200]]}]})`)
    assert.equal(xlsx.成功,true)
    await evaluate(`window.__pickerQueue.push({name:'图表.xlsx',data:${JSON.stringify(xlsx.数据)}});true`)
    await click('打开文件'); await until(`!!document.querySelector('.wps-sheet-toolbar')`)
    await click('插入','[role="tab"]'); await click('图表')
    await until(`!!document.querySelector('[aria-label="图表数据范围"]')`)
    await type('[aria-label="图表数据范围"]','A1:B3')
    await until(`!!document.querySelector('img[alt="图表预览"]')`)
    await click('插入图表图片','.ant-modal button')
    await until(`document.body.textContent.includes('图表图片已插入')`)
    await evaluate(`window.__reviewSaveFormat='xlsx';true`)
    await click('开始','[role="tab"]'); await click('另存为')
    await until(`window.__nativeActions.filter(e=>e.action==='save').at(-1)?.name.endsWith('.xlsx')`)
    const savedSheet=await evaluate(`window.__nativeActions.filter(e=>e.action==='save').at(-1)`)
    const xzip=await JSZip.loadAsync(Buffer.from(savedSheet.data,'base64'))
    assert.ok(Object.keys(xzip.files).some(name=>/^xl\/media\/.*\.png$/.test(name)))
    fs.writeFileSync(path.join(output,'review-chart.xlsx'),Buffer.from(savedSheet.data,'base64'))
    assert.ok(await evaluate(`window.__reviewFormatSelections.some(item=>item.selected.endsWith('.xlsx'))`))
    await evaluate(`window.__reviewSaveFormat=null;true`)
    record('表格按真实两列数据生成图表图片；XLSX 保存含真实 PNG，不宣称原生可编辑图表')
    await win.capturePage().then(image=>fs.writeFileSync(path.join(output,'review-sheet.png'),image.toPNG()))
    await click('返回首页'); await back()
    await until(`window.__nativeActions.some(e=>e.action==='back-root')`)
    const backup=await evaluate(`window.electronAPI.backupLoad()`)
    assert.equal(backup.成功,true); assert.ok(backup.内容)
    assert.deepEqual(errors,[])
    record('仅首页一级页面确认工作区备份后请求返回桌面')
    fs.writeFileSync(path.join(output,'harmony-browser-review.json'),JSON.stringify({passed:true,checks,deviceValidation:false,scope:'Electron file:// production IIFE + simulated Harmony transport; native UTS separately compiled'},null,2))
    console.log(JSON.stringify({passed:true,checks,output},null,2)); app.exit(0)
  } catch(error) {
    console.error(error.stack||error)
    await win.capturePage().then(image=>fs.writeFileSync(path.join(output,'failure.png'),image.toPNG())).catch(()=>{})
    const actions=await evaluate(`window.__nativeActions?.map(e=>({action:e.action,name:e.name}))`).catch(()=>[])
    const printHtml=await evaluate(`window.__lastPrintHTML`).catch(()=>null)
    if(printHtml)fs.writeFileSync(path.join(output,'failure-print.html'),printHtml)
    fs.writeFileSync(path.join(output,'harmony-browser-review.json'),JSON.stringify({passed:false,checks,error:error.stack||String(error),diagnostics,actions,deviceValidation:false},null,2))
    app.exit(1)
  }
})
