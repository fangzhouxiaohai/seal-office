/** 选区文本在提示词里的引用方式：明确要求只改这一段，便于助手按原文校验 */
function 引用选区(选区: string): string {
  return `\n\n只处理下面这段内容（保持其余内容不变，并保留原有格式）：\n"""\n${选区}\n"""`
}

