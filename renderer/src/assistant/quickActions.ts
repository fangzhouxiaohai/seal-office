/** 表格/演示/PDF 复用同一批写作类指令，个别模块可按需传入自己的集合 */
export const 通用AI指令 = 写作快捷指令

/** 打开助手并直接发送一条指令；助手会按“预览确认后应用”的流程处理改动 */
export function 交给助手(指令: 快捷指令, 选区文本: string): void {
  const 文本 = 选区文本.trim()
  if (文本 === '') return
  window.dispatchEvent(new CustomEvent('seal-assistant-ask', { detail: { 文本: 指令.提示词(文本) } }))
}

/** 把 AI 快捷动作转成浮窗按钮，接在本地按钮之后 */
export function 构建AI按钮(取选区: () => string, 指令集: 快捷指令[] = 通用AI指令): 浮窗按钮[] {
  return 指令集.map((指令) => ({
    id: 指令.id,
    标签: 指令.标签,
    ...(指令.图标 ? { 图标: 指令.图标 } : {}),
    分组: 指令.分组,
    执行: () => 交给助手(指令, 取选区()),
  }))
}
