// 引文命令的域级实现：插入引文、插入书目、刷新域、取消链接。
//
// 与旧实现的关键区别：所有操作读写的是域（域代码 + 缓存文字），
// 不是写死的 [n] 文字。因此换样式、删引文、刷新时编号与书目都能重排，
// 导出的 docx 也能被 Word 与 Zotero 识别为可刷新的引文域。
import { 创建引文引擎 } from './engine'
import {
  刷新文档域,
  生成引文域Html,
  生成书目域Html,
  收集引文域,
  收集书目域,
  读取引文簇,
  新建引文簇,
  取消链接,
} from './documentModel'
import { 取内置样式, 默认语言 } from './styles'
import type { Csl条目, 引文簇引用, 引文偏好, 引文样式 } from './types'

/** 引文操作所需的编辑区上下文，与 EditorCommand 的 CommandContext 解耦以便单测 */
export interface 引文上下文 {
  /** 编辑区根元素 */
  根: HTMLElement
  /** 当前文档的文献库，键为条目 id */
  条目: Record<string, Csl条目>
  /** 文档级引文偏好 */
  偏好: 引文偏好
  /** 在光标处插入 HTML 片段，并同步写进编辑区根元素 */
  插入内容: (html: string) => void
  /** 输出中文提示 */
  notify: (文本: string) => void
}

/** 取当前生效的样式对象，样式标识失效时回退默认样式 */
export function 当前样式(偏好: 引文偏好): 引文样式 {
  return 取内置样式(偏好.样式标识)
}

/** 当前生效的语言：样式有默认语言时以样式为准，避免国标样式配英文语言排错 */
export function 当前语言(偏好: 引文偏好): string {
  const 样式 = 当前样式(偏好)
  return 样式.语言 || 偏好.语言 || 默认语言
}

/** 取当前样式下单个簇的可见文字；排版失败时给出占位，随后的整体刷新会纠正 */
function 预览文字(上下文: 引文上下文, 簇: 引文簇引用): string {
  try {
    const 引擎 = 创建引文引擎({ 样式: 当前样式(上下文.偏好), 语言: 当前语言(上下文.偏好), 条目: 上下文.条目 })
    return 引擎.预览(簇)
  } catch {
    return '[…]'
  }
}

/**
 * 插入引文：生成引文域并立即刷新全文档，编号与书目随之重排。
 * 返回实际插入的簇标识，供界面高亮或后续编辑定位符。
 */
export function 插入引文(上下文: 引文上下文, 条目id: string[]): string {
  const 有效 = 条目id.filter((id) => 上下文.条目[id])
  if (有效.length === 0) throw new Error('所选文献不在当前文档文献库中，请先加入文献库')
  const 现有 = 读取引文簇(上下文.根).簇
  const 簇 = 新建引文簇(现有, 有效.map((id) => ({ id })))
  上下文.插入内容(生成引文域Html(簇, 预览文字(上下文, 簇)))
  刷新文档域(上下文.根, { 样式: 当前样式(上下文.偏好), 语言: 当前语言(上下文.偏好), 条目: 上下文.条目 })
  上下文.notify(`已插入引文，当前文档共 ${读取引文簇(上下文.根).簇.length} 处引文`)
  return 簇.citationID
}

/** 插入参考文献表；已存在时改为按当前引文重新生成，不生成重复表 */
export function 插入书目(上下文: 引文上下文): number {
  const 现有 = 刷新文档域(上下文.根, {
    样式: 当前样式(上下文.偏好),
    语言: 当前语言(上下文.偏好),
    条目: 上下文.条目,
  })
  if (收集引文域(上下文.根).length === 0) throw new Error('文档中还没有引文，无法生成参考文献表')
  const 已有表 = 收集书目域(上下文.根).length > 0
  上下文.插入内容(已有表 ? '' : `${生成书目域Html(现有.渲染.书目)}<p><br></p>`)
  const 结果 = 刷新文档域(上下文.根, {
    样式: 当前样式(上下文.偏好),
    语言: 当前语言(上下文.偏好),
    条目: 上下文.条目,
  })
  上下文.notify(已有表
    ? `参考文献表已存在，已按当前引文重新生成，共 ${结果.渲染.书目.length} 条`
    : `已插入参考文献表，共 ${结果.渲染.书目.length} 条`)
  return 结果.渲染.书目.length
}

/** 刷新全部域：换样式后调用，引文与书目一起重排 */
export function 刷新域(上下文: 引文上下文): { 引文数: number; 书目数: number } {
  const 结果 = 刷新文档域(上下文.根, {
    样式: 当前样式(上下文.偏好),
    语言: 当前语言(上下文.偏好),
    条目: 上下文.条目,
  })
  if (结果.异常.length > 0) {
    上下文.notify(`有 ${结果.异常.length} 处引文域无法解析，已保留原样：${结果.异常[0].原因}`)
  } else {
    上下文.notify(`已刷新 ${结果.引文数} 处引文、${结果.书目数} 个参考文献表`)
  }
  return { 引文数: 结果.引文数, 书目数: 结果.书目数 }
}

/**
 * 取消链接：删除域代码，全部变纯文本。
 * 与 Zotero 语义一致，不可逆；执行前由界面负责二次确认并提示另存副本。
 */
export function 执行取消链接(上下文: 引文上下文): number {
  const 数量 = 取消链接(上下文.根)
  if (数量 === 0) {
    上下文.notify('文档中没有可取消链接的引文域')
    return 0
  }
  上下文.notify(`已取消 ${数量} 处引文的链接，引文与参考文献表已变为纯文本`)
  return 数量
}
