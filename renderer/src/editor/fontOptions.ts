/** 把字号取值换算为磅值，支持中文号数与纯数字两种写法 */
export function 解析字号(取值: string): number {
  const 命中 = 中文字号表.find((项) => 项.名称 === 取值)
  if (命中 !== undefined) {
    return 命中.磅值
  }
  const 数值 = Number.parseFloat(取值)
  return Number.isFinite(数值) && 数值 > 0 ? 数值 : 12
}

/** execCommand('fontSize') 仅接受 1 至 7 档，此处把磅值映射到档位 */
export function 磅值到档位(磅值: number): string {
  if (磅值 <= 8) return '1'
  if (磅值 <= 10) return '2'
  if (磅值 <= 12) return '3'
  if (磅值 <= 14) return '4'
  if (磅值 <= 18) return '5'
  if (磅值 <= 24) return '6'
  return '7'
}
