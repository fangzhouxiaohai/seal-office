import { describe, it, expect } from 'vitest'
import { 转换简繁, 转换简繁带统计 } from './langConvert'

describe('简繁转换', () => {
  it('简体转繁体', () => {
    expect(转换简繁('这个问题我们会讨论', '繁')).toBe('這個問題我們會討論')
  })

  it('繁体转简体', () => {
    expect(转换简繁('這個問題我們會討論', '简')).toBe('这个问题我们会讨论')
  })

  it('转换文档常用词句', () => {
    expect(转换简繁('会议记录与文件归档', '繁')).toBe('會議記錄與文件歸檔')
    expect(转换简繁('会议记录与文件归档', '简')).toBe('会议记录与文件归档')
  })

  it('未收录字符保持不变', () => {
    expect(转换简繁('abc 123 ，。', '繁')).toBe('abc 123 ，。')
  })

  it('繁体字符再次转繁体不产生变化', () => {
    expect(转换简繁('這個問題', '繁')).toBe('這個問題')
  })

  it('空字符串返回空字符串', () => {
    expect(转换简繁('', '繁')).toBe('')
    expect(转换简繁('', '简')).toBe('')
  })

  it('转换后可由反向转换还原', () => {
    const 原文 = '这个软件的问题我们会处理'
    const 繁体 = 转换简繁(原文, '繁')
    expect(转换简繁(繁体, '简')).toBe(原文)
  })

  it('带统计的转换返回替换字数', () => {
    const 结果 = 转换简繁带统计('这个问题', '繁')
    expect(结果.文本).toBe('這個問題')
    expect(结果.转换数).toBe(4)
  })

  it('带统计的转换在无变化时返回零', () => {
    const 结果 = 转换简繁带统计('已经完成', '简')
    expect(结果.转换数).toBe(0)
  })
})
