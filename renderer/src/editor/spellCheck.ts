// 基础拼写检查：检测连续重复汉字与中文语境下的半角标点。
// 不依赖外部词典，属于确定性可判定的检查项，不编造检查结果。

export interface 拼写问题 {
  类型: '重复字符' | '半角标点'
  /** 命中位置在文本中的起始下标 */
  位置: number
  /** 命中的原文片段 */
  片段: string
  建议: string
}

const 中文标点建议: Record<string, string> = {
  ',': '，',
  ';': '；',
  ':': '：',
  '!': '！',
  '?': '？',
}

/**
 * 仅这些虚词的连续重复才判定为输入错误。
 * 若对所有汉字重复都报警，会把「天天」「刚刚」「看看」等正常叠词误判为错误。
 */
const 疑似重复的虚词 = new Set([
  '的', '了', '是', '在', '和', '就', '也', '都', '很', '并',
  '而', '但', '或', '与', '我', '你', '他', '她', '它', '们',
  '这', '那', '有', '被', '把', '给', '让', '从', '对', '为',
])

export function 检查文本(文本: string): 拼写问题[] {
  if (文本.length === 0) {
    return []
  }

  const 问题列表: 拼写问题[] = []
  let 命中: RegExpExecArray | null

  const 重复字符 = /([\u4e00-\u9fff])\1/g
  while ((命中 = 重复字符.exec(文本)) !== null) {
    if (!疑似重复的虚词.has(命中[1])) {
      continue
    }
    问题列表.push({
      类型: '重复字符',
      位置: 命中.index,
      片段: 命中[0],
      建议: `疑似重复输入「${命中[1]}」，请确认是否需要删除其一`,
    })
  }

  // 仅当半角标点紧跟在汉字之后时才判定，避免误伤英文内容
  const 半角标点 = /[\u4e00-\u9fff]([,;:!?])/g
  while ((命中 = 半角标点.exec(文本)) !== null) {
    const 标点 = 命中[1]
    问题列表.push({
      类型: '半角标点',
      位置: 命中.index + 1,
      片段: 标点,
      建议: `中文语境建议改用全角标点「${中文标点建议[标点] ?? 标点}」`,
    })
  }

  return 问题列表.sort((甲, 乙) => 甲.位置 - 乙.位置)
}
