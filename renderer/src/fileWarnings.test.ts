import { beforeEach, describe, expect, it } from 'vitest'
import {
  保真风险警告, 处于受保护查看, 存在内容风险, 内容风险警告, 警告级别, 需要转换确认,
  应提示保存保真风险, 重置保存保真提示, 拆分警告文本, 引用域缓存提示,
} from './fileWarnings'

describe('导入警告分级', () => {
  it('目录域、颜色近似、数字格式预览与视图设置属于保真风险', () => {
    for (const 项 of [
      '域代码未完整导入，已保留可读取的缓存结果',
      '部分颜色按近似值导入',
      '部分主题色或透明颜色未导入',
      '数字格式中的颜色或区域语言仅保留代码，预览可能不同',
      '部分数字格式不能准确预览，保存时保留原始格式代码',
      '部分工作表视图设置未导入',
      '页脚中的域或制表符未完整导入',
      引用域缓存提示,
    ]) expect(警告级别(项)).toBe('保真')
  })

  it('图片、图形、批注、修订、数据透视表等确实丢内容的项属于内容风险', () => {
    for (const 项 of ['图片未导入', '图形未导入', '批注未导入', '修订信息未导入', '数据透视表未导入', '外部数据连接未导入', '图片未导入：图片资源缺失', '文档内容为空']) {
      expect(警告级别(项)).toBe('内容')
    }
  })

  it('未登记的新警告默认按内容风险处理，避免误放行', () => {
    expect(警告级别('将来新增的未知对象未导入')).toBe('内容')
  })

  it('页眉、页脚、脚注、尾注前缀按内层警告分级', () => {
    expect(警告级别('页眉：段落间距未完整导入')).toBe('保真')
    expect(警告级别('脚注：图片未导入')).toBe('内容')
  })

  it('保真风险白名单与内容风险没有交集，并能拆分列表', () => {
    const 列表 = ['图片未导入', '部分颜色按近似值导入', '域代码未完整导入，已保留可读取的缓存结果']
    expect(内容风险警告(列表)).toEqual(['图片未导入'])
    expect(保真风险警告(列表)).toEqual(['部分颜色按近似值导入', '域代码未完整导入，已保留可读取的缓存结果'])
    expect(存在内容风险(列表)).toBe(true)
    expect(存在内容风险(列表.slice(1))).toBe(false)
    expect(需要转换确认(列表.slice(1))).toBe(false)
  })
})

describe('有损导入的受保护查看状态', () => {
  it('仅内容风险在原路径时只读，另存副本后可编辑；保真风险不进入受保护查看', () => {
    expect(处于受保护查看('C:\\资料\\报表.xls', 'c:/资料/报表.xls', ['网页样式未导入'])).toBe(true)
    expect(处于受保护查看('C:\\资料\\报表.xls', 'C:\\资料\\报表.slxls', ['网页样式未导入'])).toBe(false)
    expect(处于受保护查看('C:\\资料\\报表.xls', 'C:\\资料\\报表.xls', [])).toBe(false)
    expect(处于受保护查看('C:\\资料\\手册.docx', 'C:\\资料\\手册.docx', ['域代码未完整导入，已保留可读取的缓存结果'])).toBe(false)
    expect(处于受保护查看('C:\\资料\\成绩.xlsx', 'C:\\资料\\成绩.xlsx', ['部分颜色按近似值导入', '部分工作表视图设置未导入'])).toBe(false)
  })
})

describe('保存时的保真风险提示', () => {
  beforeEach(() => 重置保存保真提示())

  it('同一文档覆盖保存来源文件时只提示一次，只列出保真项', () => {
    const 警告 = ['部分颜色按近似值导入', '数字格式中的颜色或区域语言仅保留代码，预览可能不同']
    expect(应提示保存保真风险('文档1', 'C:\\资料\\成绩.xlsx', 'c:/资料/成绩.xlsx', 警告)).toEqual(警告)
    expect(应提示保存保真风险('文档1', 'C:\\资料\\成绩.xlsx', 'C:\\资料\\成绩.xlsx', 警告)).toBeNull()
    expect(应提示保存保真风险('文档2', 'C:\\资料\\其他.xlsx', 'C:\\资料\\其他.xlsx', 警告)).toEqual(警告)
  })

  it('另存到其他路径、专属格式或没有保真项时不提示', () => {
    expect(应提示保存保真风险('文档1', 'C:\\资料\\成绩.xlsx', 'C:\\资料\\副本.xlsx', ['部分颜色按近似值导入'])).toBeNull()
    expect(应提示保存保真风险('文档1', 'C:\\资料\\成绩.xlsx', 'C:\\资料\\成绩.slxls', ['部分颜色按近似值导入'])).toBeNull()
    expect(应提示保存保真风险('文档1', 'C:\\资料\\成绩.xlsx', 'C:\\资料\\成绩.xlsx', [])).toBeNull()
  })
})

describe('警告文本拆分', () => {
  it('按中文冒号与分号拆成可单独翻译的片段，保留分隔符', () => {
    expect(拆分警告文本('页眉：图片未导入')).toEqual(['页眉', '：', '图片未导入'])
    expect(拆分警告文本('图片未导入')).toEqual(['图片未导入'])
    expect(拆分警告文本('高级源结构无法安全保留：部件缺失；请保留原文件')).toEqual(['高级源结构无法安全保留', '：', '部件缺失', '；', '请保留原文件'])
  })
})
