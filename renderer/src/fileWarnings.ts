/** 页眉、页脚、脚注、尾注中的警告带有“部位：”前缀，按内层警告分级 */
const 部位前缀 = /^(?:页眉|页脚|脚注|尾注)：/

export type 警告等级 = '保真' | '内容'

export function 警告级别(警告: string): 警告等级 {
  const 内层 = 警告.replace(部位前缀, '')
  return 保真风险白名单.has(警告) || 保真风险白名单.has(内层) ? '保真' : '内容'
}

export function 内容风险警告(警告: readonly string[] | undefined): string[] {
  return [...new Set(警告 ?? [])].filter((项) => 警告级别(项) === '内容')
}

export function 保真风险警告(警告: readonly string[] | undefined): string[] {
  return [...new Set(警告 ?? [])].filter((项) => 警告级别(项) === '保真')
}

export function 存在内容风险(警告: readonly string[] | undefined): boolean {
  return 内容风险警告(警告).length > 0
}

/** 兼容旧调用：只有内容风险才需要在打开时询问 */
export function 需要转换确认(警告: readonly string[]): boolean {
  return 存在内容风险(警告)
}

const 规范路径 = (路径: string) => 路径.replace(/\\/g, '/').toLowerCase()
const 专属格式 = /\.(sldoc|slxls|slppt|spdf|sealdoc|sealsheet|sealshow)$/i

/** 仍在来源路径上且存在内容风险时处于受保护查看（仅查看），保真风险不再锁定文件 */
export function 处于受保护查看(来源路径: string | undefined, 当前路径: string | null | undefined, 警告: readonly string[] | undefined): boolean {
  if (!来源路径 || !当前路径 || !存在内容风险(警告)) return false
  return 规范路径(来源路径) === 规范路径(当前路径)
}

/** 同一会话内已提示过保真风险的文档，避免每次保存都弹窗 */
const 已提示保真文档 = new Set<string>()

/**
 * 覆盖保存来源文件时，返回需要提示的保真风险列表；同一文档同一会话只返回一次。
 * 另存到其他路径或保存为海豹专属格式时不提示（专属格式完整保存当前内容）。
 */
export function 应提示保存保真风险(文档标识: string, 来源路径: string | undefined, 保存路径: string | null | undefined, 警告: readonly string[] | undefined): string[] | null {
  if (!来源路径 || !保存路径 || 规范路径(来源路径) !== 规范路径(保存路径) || 专属格式.test(保存路径)) return null
  const 列表 = 保真风险警告(警告)
  if (!列表.length || 已提示保真文档.has(文档标识)) return null
  已提示保真文档.add(文档标识)
  return 列表
}

/** 测试与重新登录时清空会话提示记录 */
export function 重置保存保真提示(): void {
  已提示保真文档.clear()
}

/**
 * 把警告拆成“部位前缀 / 分隔符 / 正文”片段。界面按片段渲染为独立文本节点，
 * 语言切换时每个片段都能精确命中英文映射，而不需要为每种组合各写一条。
 */
export function 拆分警告文本(警告: string): string[] {
  return 警告.split(/([：；])/).filter((项) => 项 !== '')
}
