/** 扫描主进程编解码器中以字面量写入的告警文案 */
function 收集静态告警(): string[] {
  const 文件: string[] = []
  const 遍历 = (目录: string) => {
    for (const 条目 of readdirSync(目录, { withFileTypes: true })) {
      const 路径 = join(目录, 条目.name)
      if (条目.isDirectory()) { if (条目.name !== '__fixtures__') 遍历(路径) }
      else if (条目.name.endsWith('.js') && !条目.name.includes('.test.')) 文件.push(路径)
    }
  }
  遍历(源码目录)
  const 结果 = new Set<string>()
  for (const 路径 of 文件) {
    const 源码 = readFileSync(路径, 'utf8')
    for (const 匹配 of 源码.matchAll(/警告\??\.(?:add|push)\(\s*'([^'\n]+)'\s*\)/g)) 结果.add(匹配[1])
    for (const 匹配 of 源码.matchAll(/\{\s*警告:\s*'([^'\n]+)'\s*\}/g)) 结果.add(匹配[1])
    for (const 匹配 of 源码.matchAll(/(?:const|let)\s+[㐀-鿿\w]*告警\s*=\s*'([^'\n]+)'/g)) 结果.add(匹配[1])
  }
  // docxImages.js 抛出的图片错误会原样进入告警
  for (const 匹配 of readFileSync(join(源码目录, 'docxImages.js'), 'utf8').matchAll(/throw new Error\('((?:图片|外部)[^'\n]+)'\)/g)) 结果.add(匹配[1])
  return [...结果]
}

