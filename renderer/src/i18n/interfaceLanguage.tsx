export function 翻译界面文本(原文: string, 语言: 界面语言): string {
  if (语言 !== 'en-US' || !/[\u3400-\u9fff]/u.test(原文)) return 原文
  const 匹配 = 原文.match(/^(\s*)(.*?)(\s*)$/s)
  const 前缀 = 匹配?.[1] ?? ''
  const 正文 = 匹配?.[2] ?? 原文
  const 后缀 = 匹配?.[3] ?? ''
  const 精确 = 英文界面[正文]
  if (精确 !== undefined) return `${前缀}${精确}${后缀}`
  for (const [规则, 转换] of 动态翻译) {
    const 命中 = 正文.match(规则)
    if (命中) return `${前缀}${转换(...命中)}${后缀}`
  }
  return 原文
}

