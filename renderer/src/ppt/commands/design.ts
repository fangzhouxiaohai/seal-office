function 应用字体(上下文: 演示命令上下文, 设置: { 标题字体?: string; 正文字体?: string }): void {
  const 名称 = 设置.标题字体 ?? 设置.正文字体
  if (!名称) {
    上下文.notify('请选择字体')
    return
  }
  try {
    const 结果 = 统一字体(上下文.文稿, 设置)
    上下文.更新文稿(结果.文稿)
    上下文.notify(`已应用字体「${名称}」到 ${结果.应用数量} 个文本框${结果.跳过显式字体 ? `，跳过 ${结果.跳过显式字体} 个显式设置字体的文本框` : ''}`)
  } catch (错误) {
    上下文.notify(错误 instanceof Error ? 错误.message : '统一字体失败')
  }
}

function 更新页脚(上下文: 演示命令上下文, 覆盖: Parameters<typeof 设置页脚>[1], 提示: string): void {
  const 文稿 = 上下文.文稿
  const 单页 = 文稿.幻灯片列表.some((页) => 页.页脚 !== undefined)
  const 基线 = 文稿.页脚设置 ?? (单页 ? 读取有效页脚(文稿, 文稿.幻灯片列表[0], 0) ?? {} : {})
  上下文.更新文稿(设置页脚(文稿, { ...基线, ...(覆盖 ?? {}) }, '全部'))
  上下文.notify(提示)
}

function 切换页脚开关(上下文: 演示命令上下文, 键: '显示日期' | '显示页码', 名称: string): void {
  const 文稿 = 上下文.文稿
  const 当前 = 文稿.页脚设置?.[键] ?? false
  更新页脚(上下文, { [键]: !当前 } as never, `已${当前 ? '关闭' : '开启'}${名称}`)
}

function 应用尺寸(上下文: 演示命令上下文, 尺寸: { 宽: number; 高: number }, 方式: '缩放内容' | '保留坐标'): void {
  try {
    上下文.更新文稿(应用页面尺寸(上下文.文稿, 尺寸, 方式))
    上下文.notify(`页面尺寸已改为 ${尺寸.宽}×${尺寸.高}（${方式}），可单次撤销还原`)
  } catch (错误) {
    上下文.notify(错误 instanceof Error ? 错误.message : '页面尺寸设置失败')
  }
}

function 美化(上下文: 演示命令上下文, 仅当前页: boolean): void {
  const 当前 = 读取当前幻灯片(上下文.文稿)
  if (仅当前页 && 当前 === null) return
  try {
    const 结果 = 本机美化(上下文.文稿, 仅当前页 && 当前 ? { 页标识: 当前.id } : {})
    上下文.更新文稿(结果.文稿)
    上下文.notify(结果.调整列表.length
      ? `本机美化已应用 ${结果.调整列表.length} 处对齐与排版调整（不含 AI 建议），可单次撤销还原`
      : '本机美化未发现需要调整的对齐与排版')
  } catch (错误) {
    上下文.notify(错误 instanceof Error ? 错误.message : '本机美化失败')
  }
}
