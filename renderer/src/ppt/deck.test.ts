import { describe, it, expect } from 'vitest'
import {
  添加幻灯片,
  添加文本框,
  创建幻灯片,
  创建文本框,
  创建演示文稿,
  删除幻灯片,
  删除文本框,
  切换幻灯片,
  复制幻灯片,
  应用版式,
  更新幻灯片,
  更新文本框,
  版式初始文本框,
  约束位置,
  读取当前幻灯片,
  画布宽,
  画布高,
  默认背景色,
} from './deck'

describe('演示文稿创建', () => {
  it('默认包含一张标题幻灯片且当前索引为 0', () => {
    const 文稿 = 创建演示文稿()
    expect(文稿.幻灯片列表).toHaveLength(1)
    expect(文稿.当前索引).toBe(0)
    expect(文稿.name).toBe('未命名演示.pptx')
  })

  it('读取当前幻灯片', () => {
    const 文稿 = 创建演示文稿()
    expect(读取当前幻灯片(文稿)?.id).toBe(文稿.幻灯片列表[0].id)
  })

  it('无幻灯片时读取当前返回 null', () => {
    const 文稿 = { ...创建演示文稿(), 幻灯片列表: [] }
    expect(读取当前幻灯片(文稿)).toBeNull()
  })
})

describe('幻灯片版式', () => {
  it('标题幻灯片只有标题框', () => {
    expect(版式初始文本框('标题幻灯片')).toHaveLength(1)
  })

  it('标题和内容有标题框与正文框', () => {
    expect(版式初始文本框('标题和内容')).toHaveLength(2)
  })

  it('空白版式没有文本框', () => {
    expect(版式初始文本框('空白')).toEqual([])
  })

  it('应用版式会重置文本框', () => {
    let 文稿 = 创建演示文稿()
    const 标识 = 文稿.幻灯片列表[0].id
    文稿 = 应用版式(文稿, 标识, '标题和内容')
    expect(读取当前幻灯片(文稿)?.文本框列表).toHaveLength(2)
    文稿 = 应用版式(文稿, 标识, '空白')
    expect(读取当前幻灯片(文稿)?.文本框列表).toHaveLength(0)
  })

  it('新建幻灯片默认背景为白色', () => {
    expect(创建幻灯片().背景色).toBe(默认背景色)
  })
})

describe('幻灯片操作', () => {
  it('添加幻灯片插入到当前之后并切换过去', () => {
    const 文稿 = 添加幻灯片(创建演示文稿())
    expect(文稿.幻灯片列表).toHaveLength(2)
    expect(文稿.当前索引).toBe(1)
  })

  it('复制幻灯片插入到其后且文本框为新标识', () => {
    let 文稿 = 创建演示文稿()
    const 原标识 = 文稿.幻灯片列表[0].id
    文稿 = 复制幻灯片(文稿, 原标识)
    expect(文稿.幻灯片列表).toHaveLength(2)
    expect(文稿.幻灯片列表[1].title).toContain('副本')
    expect(文稿.幻灯片列表[1].id).not.toBe(原标识)
    expect(文稿.幻灯片列表[1].文本框列表[0].id).not.toBe(
      文稿.幻灯片列表[0].文本框列表[0].id
    )
  })

  it('删除幻灯片后当前索引不越界', () => {
    let 文稿 = 添加幻灯片(创建演示文稿())
    文稿 = 删除幻灯片(文稿, 文稿.幻灯片列表[1].id)
    expect(文稿.幻灯片列表).toHaveLength(1)
    expect(文稿.当前索引).toBe(0)
  })

  it('仅剩一张时删除无效且返回原对象', () => {
    const 文稿 = 创建演示文稿()
    expect(删除幻灯片(文稿, 文稿.幻灯片列表[0].id)).toBe(文稿)
  })

  it('删除不存在的标识返回原对象', () => {
    const 文稿 = 创建演示文稿()
    expect(删除幻灯片(文稿, '不存在')).toBe(文稿)
  })

  it('切换幻灯片在越界时保持不变', () => {
    const 文稿 = 创建演示文稿()
    expect(切换幻灯片(文稿, 5)).toBe(文稿)
    expect(切换幻灯片(文稿, -1)).toBe(文稿)
  })

  it('更新幻灯片字段', () => {
    const 文稿 = 创建演示文稿()
    const 新文稿 = 更新幻灯片(文稿, 文稿.幻灯片列表[0].id, { background: undefined, 背景色: '#EEF3FF' } as never)
    expect(读取当前幻灯片(新文稿)?.背景色).toBe('#EEF3FF')
  })
})

describe('文本框操作', () => {
  it('创建文本框带默认格式', () => {
    const 框 = 创建文本框(10, 20, 300, 100, '内容')
    expect(框.text).toBe('内容')
    expect(框.加粗).toBe(false)
    expect(框.对齐).toBe('left')
    expect(框.字号).toBe(24)
  })

  it('添加与更新文本框', () => {
    const 幻灯片 = 创建幻灯片('空白')
    const 框 = 创建文本框(0, 0, 200, 80, '文本')
    const 添加后 = 添加文本框(幻灯片, 框)
    expect(添加后.文本框列表).toHaveLength(1)
    const 更新后 = 更新文本框(添加后, 框.id, { 加粗: true, 字号: 32 })
    expect(更新后.文本框列表[0].加粗).toBe(true)
    expect(更新后.文本框列表[0].字号).toBe(32)
  })

  it('删除文本框', () => {
    const 框 = 创建文本框(0, 0, 200, 80, '文本')
    const 幻灯片 = 添加文本框(创建幻灯片('空白'), 框)
    expect(删除文本框(幻灯片, 框.id).文本框列表).toHaveLength(0)
  })

  it('更新不存在的文本框不改变内容', () => {
    const 幻灯片 = 创建幻灯片('标题和内容')
    expect(更新文本框(幻灯片, '不存在', { 加粗: true })).toEqual(幻灯片)
  })
})

describe('画布边界约束', () => {
  it('位置在范围内时保持不变', () => {
    expect(约束位置(100, 100, 200, 100)).toEqual({ x: 100, y: 100 })
  })

  it('超出右下边界时被拉回', () => {
    const 结果 = 约束位置(900, 500, 200, 100)
    expect(结果.x).toBe(画布宽 - 200)
    expect(结果.y).toBe(画布高 - 100)
  })

  it('负坐标被归零', () => {
    expect(约束位置(-50, -20, 200, 100)).toEqual({ x: 0, y: 0 })
  })

  it('文本框大于画布时位置归零', () => {
    expect(约束位置(50, 50, 画布宽 + 100, 画布高 + 100)).toEqual({ x: 0, y: 0 })
  })
})

describe('不可变性', () => {
  it('添加幻灯片不修改原文稿', () => {
    const 文稿 = 创建演示文稿()
    添加幻灯片(文稿)
    expect(文稿.幻灯片列表).toHaveLength(1)
  })

  it('更新文本框不修改原幻灯片', () => {
    const 幻灯片 = 创建幻灯片('标题和内容')
    // 标题框初始即为加粗，此处用正文框验证
    const 正文框 = 幻灯片.文本框列表[1]
    expect(正文框.加粗).toBe(false)
    更新文本框(幻灯片, 正文框.id, { 加粗: true })
    expect(幻灯片.文本框列表[1].加粗).toBe(false)
  })
})
