import { describe, expect, it } from 'vitest'
import { 创建演示文稿, 创建幻灯片 } from '../deck'
import { 收集智能条目, 应用条目集合, 应用条目文本, type 智能条目 } from './aiTargets'

function 造稿() {
  const 文稿 = 创建演示文稿('智能目标')
  const 第二页 = 创建幻灯片('标题和内容', '第二页')
  第二页.文本框列表[0].text = '第二页标题'
  第二页.备注 = '第二页备注'
  第二页.对象列表 = [
    { id: '图形甲', 类型: '图形', x: 0, y: 0, width: 100, height: 60, 形状: { 种类: '矩形', 文本: '图形文字', 填充: '#FFFFFF', 线条: '#000000', 线宽: 1, 颜色: '#000000', 字号: 18, 加粗: false } },
    { id: '表格甲', 类型: '表格', x: 0, y: 100, width: 200, height: 100, 表格: { 单元格: [[{ 文本: '单元格甲', 背景: '#FFFFFF', 颜色: '#000000', 字号: 12, 加粗: false, 对齐: 'left' }, { 文本: '', 背景: '#FFFFFF', 颜色: '#000000', 字号: 12, 加粗: false, 对齐: 'left' }]], 行高: [50], 列宽: [100, 100], 合并: [] } },
  ]
  文稿.幻灯片列表.push(第二页)
  return 文稿
}

describe('演示智能条目收集', () => {
  it('当前页只收集当前页条目，跳过空文本', () => {
    const 文稿 = 造稿()
    const 条目 = 收集智能条目(文稿, '当前页', 0)
    expect(条目.every((项) => 项.页码 === 1)).toBe(true)
    expect(条目.map((项) => 项.种类)).toContain('文本')
    expect(条目.some((项) => 项.原文.trim() === '')).toBe(false)
  })

  it('全文收集文本、图形、表格单元格与备注，并带稳定标识', () => {
    const 文稿 = 造稿()
    const 条目 = 收集智能条目(文稿, '全文', 0)
    expect(条目.map((项) => 项.种类)).toEqual(expect.arrayContaining(['文本', '图形', '表格单元格', '备注']))
    expect(条目.find((项) => 项.种类 === '图形')?.对象标识).toBe('图形甲')
    expect(条目.find((项) => 项.种类 === '表格单元格')?.对象标识).toBe('表格甲#0-0')
    expect(条目.find((项) => 项.种类 === '备注')?.对象标识).toBe(文稿.幻灯片列表[1].id + '::备注')
    expect(条目.find((项) => 项.种类 === '表格单元格')?.单元格).toEqual({ 行: 0, 列: 0 })
  })

  it('选区范围只收集被选中的对象', () => {
    const 条目 = 收集智能条目(造稿(), '选区', 1, ['图形甲'])
    expect(条目).toHaveLength(1)
    expect(条目[0].对象标识).toBe('图形甲')
  })
})

describe('智能条目应用与版本核对', () => {
  it('原文变化时阻止覆盖，提示具体页面与内容', () => {
    const 文稿 = 造稿()
    const 条目: 智能条目 = { 对象标识: '图形甲', 原文: '已过期的原文', 来源: '第 2 页图形', 页码: 2, 种类: '图形', 对象标识路径: '图形甲' }
    expect(() => 应用条目文本(文稿.幻灯片列表[1], 条目, '新文本')).toThrow('图形的原文已变化')
  })

  it('文本、图形、表格与备注都能按原文核对后替换', () => {
    const 文稿 = 造稿()
    const 条目 = 收集智能条目(文稿, '全文', 1)
    const 文本条目 = 条目.find((项) => 项.种类 === '文本' && 项.页码 === 2)!
    const 图形条目 = 条目.find((项) => 项.种类 === '图形')!
    const 表格条目 = 条目.find((项) => 项.种类 === '表格单元格')!
    const 备注条目 = 条目.find((项) => 项.种类 === '备注')!
    const 结果 = 应用条目集合(文稿, [
      { 条目: 文本条目, 新文本: '标题已翻译' },
      { 条目: 图形条目, 新文本: 'Shape text' },
      { 条目: 表格条目, 新文本: 'Cell text' },
      { 条目: 备注条目, 新文本: 'Speaker notes' },
    ])
    const 新页 = 结果.幻灯片列表[1]
    expect(新页.文本框列表.find((框) => 框.id === 文本条目.文本框标识)?.text).toBe('标题已翻译')
    expect(新页.对象列表?.find((项) => 项.id === '图形甲')?.形状?.文本).toBe('Shape text')
    expect(新页.对象列表?.find((项) => 项.id === '表格甲')?.表格?.单元格[0][0].文本).toBe('Cell text')
    expect(新页.备注).toBe('Speaker notes')
    expect(文稿.幻灯片列表[1].备注).toBe('第二页备注')
  })

  it('批量应用中任一条目版本不符则整体拒绝，不产生半份修改', () => {
    const 文稿 = 造稿()
    const 条目 = 收集智能条目(文稿, '全文', 1)
    const 文本条目 = 条目.find((项) => 项.种类 === '文本')!
    const 过期: 智能条目 = { ...条目.find((项) => 项.种类 === '图形')!, 原文: '旧图形文字' }
    expect(() => 应用条目集合(文稿, [{ 条目: 文本条目, 新文本: 'A' }, { 条目: 过期, 新文本: 'B' }]))
      .toThrow('图形的原文已变化')
  })
})
