// 演示智能功能的编辑目标收集：把页面/对象转换成带稳定标识的可翻译、可校对条目。
import type { 演示文稿, 幻灯片 } from '../deck'

export interface 智能条目 {
  对象标识: string
  原文: string
  来源: string
  页码: number
  种类: '文本' | '图形' | '表格单元格' | '备注'
  文本框标识?: string
  对象标识路径?: string
  单元格?: { 行: number; 列: number }
}

export type 智能范围 = '选区' | '当前页' | '全文'

/** 收集可处理条目；空文本不产生条目。 */
export function 收集智能条目(文稿: 演示文稿, 范围: 智能范围, 当前索引: number, 选中: string[] = []): 智能条目[] {
  const 页面 = 文稿.幻灯片列表.map((页, 索引) => ({ 页, 索引 }))
    .filter(({ 索引 }) => 范围 === '全文' ? true : 索引 === 当前索引)
  const 条目: 智能条目[] = []
  for (const { 页, 索引 } of 页面) {
    for (const 框 of 页.文本框列表) {
      if (!框.text.trim()) continue
      if (范围 === '选区' && !选中.includes(框.id)) continue
      条目.push({ 对象标识: 框.id, 原文: 框.text, 来源: `第 ${索引 + 1} 页文本`, 页码: 索引 + 1, 种类: '文本', 文本框标识: 框.id })
    }
    for (const 对象 of 页.对象列表 ?? []) {
      const 文本 = 对象.形状?.文本 ?? ''
      if (对象.类型 === '图形' && 文本.trim()) {
        if (范围 === '选区' && !选中.includes(对象.id)) continue
        条目.push({ 对象标识: 对象.id, 原文: 文本, 来源: `第 ${索引 + 1} 页图形`, 页码: 索引 + 1, 种类: '图形', 对象标识路径: 对象.id })
      }
      if (对象.类型 === '表格' && 对象.表格) {
        if (范围 === '选区' && !选中.includes(对象.id)) continue
        对象.表格.单元格.forEach((行, 行号) => 行.forEach((单元, 列号) => {
          if (!单元.文本?.trim()) return
          条目.push({
            对象标识: `${对象.id}#${行号}-${列号}`, 原文: 单元.文本, 来源: `第 ${索引 + 1} 页表格 ${行号 + 1}行${列号 + 1}列`,
            页码: 索引 + 1, 种类: '表格单元格', 对象标识路径: 对象.id, 单元格: { 行: 行号, 列: 列号 },
          })
        }))
      }
    }
    if (页.备注?.trim()) {
      if (范围 !== '选区') 条目.push({ 对象标识: `${页.id}::备注`, 原文: 页.备注, 来源: `第 ${索引 + 1} 页备注`, 页码: 索引 + 1, 种类: '备注' })
    }
  }
  return 条目
}

/** 应用一条文本替换；原文与当前内容不一致时抛出真实原因。 */
export function 应用条目文本(页: 幻灯片, 条目: 智能条目, 新文本: string): 幻灯片 {
  if (条目.种类 === '备注') {
    if ((页.备注 ?? '') !== 条目.原文) throw new Error(`第 ${条目.页码} 页备注的原文已变化，已阻止覆盖`)
    return { ...页, 备注: 新文本 }
  }
  if (条目.种类 === '文本') {
    const 框 = 页.文本框列表.find((项) => 项.id === 条目.文本框标识)
    if (!框) throw new Error(`第 ${条目.页码} 页找不到指定文本框`)
    if (框.text !== 条目.原文) throw new Error(`第 ${条目.页码} 页「${条目.原文.slice(0, 12)}」的原文已变化，已阻止覆盖`)
    return { ...页, 文本框列表: 页.文本框列表.map((项) => 项.id === 框.id ? { ...项, text: 新文本 } : 项) }
  }
  const 对象 = (页.对象列表 ?? []).find((项) => 项.id === 条目.对象标识路径)
  if (!对象) throw new Error(`第 ${条目.页码} 页找不到指定对象`)
  if (条目.种类 === '图形') {
    if ((对象.形状?.文本 ?? '') !== 条目.原文) throw new Error(`第 ${条目.页码} 页图形的原文已变化，已阻止覆盖`)
    return { ...页, 对象列表: (页.对象列表 ?? []).map((项) => 项.id === 对象.id ? { ...项, 形状: { ...项.形状!, 文本: 新文本 } } : 项) }
  }
  if (!条目.单元格 || !对象.表格) throw new Error('表格条目信息不完整')
  const 单元 = 对象.表格.单元格[条目.单元格.行]?.[条目.单元格.列]
  if (!单元) throw new Error(`第 ${条目.页码} 页表格单元格不存在`)
  if (单元.文本 !== 条目.原文) throw new Error(`第 ${条目.页码} 页表格单元格的原文已变化，已阻止覆盖`)
  const 单元格 = 对象.表格.单元格.map((行, 行号) => 行.map((项, 列号) => 行号 === 条目.单元格!.行 && 列号 === 条目.单元格!.列 ? { ...项, 文本: 新文本 } : 项))
  return { ...页, 对象列表: (页.对象列表 ?? []).map((项) => 项.id === 对象.id ? { ...项, 表格: { ...项.表格!, 单元格 } } : 项) }
}

/** 批量应用；任一条目版本不符即整体拒绝，避免产生半份修改。 */
export function 应用条目集合(文稿: 演示文稿, 修改: Array<{ 条目: 智能条目; 新文本: string }>): 演示文稿 {
  let 候选 = 文稿
  for (const 项 of 修改) {
    const 下标 = 项.条目.页码 - 1
    if (下标 < 0 || 下标 >= 候选.幻灯片列表.length) throw new Error(`第 ${项.条目.页码} 页不存在`)
    const 新页 = 应用条目文本(候选.幻灯片列表[下标], 项.条目, 项.新文本)
    候选 = { ...候选, 幻灯片列表: 候选.幻灯片列表.map((页, 索引) => 索引 === 下标 ? 新页 : 页) }
  }
  return 候选
}
