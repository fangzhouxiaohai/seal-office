import { expect, it } from 'vitest'
import { 创建幻灯片, 创建文本框 } from '../deck'
import { 创建图表, 读取图表显示, 设置图表动态, 图表步数, 校验图表数据 } from './elements'
import { 校验动画 } from './animations'

function 双系列图表() {
  const 对象 = 创建图表('柱状图')
  对象.图表 = { ...对象.图表!, 分类: ['一', '二', '三'], 系列: [{ id: 'series-0', 名称: '甲', 数值: [1, 2, 3], 颜色: '#2B6CF6' }, { id: 'series-1', 名称: '乙', 数值: [4, 5, 6], 颜色: '#718096' }] }
  校验图表数据(对象)
  return 对象
}

it('图表动态设置校验步进方式与每步时长，并保留可编辑数据', () => {
  const 对象 = 双系列图表()
  const 更新 = 设置图表动态(对象, { 步进: '按系列', 每步毫秒: 800 })
  expect(更新.图表!.动态).toEqual({ 步进: '按系列', 每步毫秒: 800 })
  expect(更新.图表!.系列[1].数值).toEqual([4, 5, 6])
  expect(() => 校验图表数据(更新)).not.toThrow()
  expect(() => 设置图表动态(对象, { 步进: '按图表' as never, 每步毫秒: 800 })).toThrow('步进')
  for (const 每步毫秒 of [99, 60001, 800.5, NaN]) expect(() => 设置图表动态(对象, { 步进: '按系列', 每步毫秒 })).toThrow('每步')
  expect(设置图表动态(更新, undefined).图表!.动态).toBeUndefined()
})

it('未设置动态的图表步数为零并始终按最终状态显示', () => {
  const 对象 = 双系列图表()
  expect(图表步数(对象.图表!)).toBe(0)
  expect(读取图表显示(对象.图表!, 0)).toBeUndefined()
  expect(读取图表显示(对象.图表!, 5)).toBeUndefined()
})

it('三种步进方式的总步数按系列、分类或两者乘积计算', () => {
  const 对象 = 双系列图表()
  expect(图表步数(设置图表动态(对象, { 步进: '按系列', 每步毫秒: 500 }).图表!)).toBe(2)
  expect(图表步数(设置图表动态(对象, { 步进: '按分类', 每步毫秒: 500 }).图表!)).toBe(3)
  expect(图表步数(设置图表动态(对象, { 步进: '按系列与数据点', 每步毫秒: 500 }).图表!)).toBe(6)
})

it('按系列播放逐条显示完整系列', () => {
  const 图 = 设置图表动态(双系列图表(), { 步进: '按系列', 每步毫秒: 500 }).图表!
  expect(读取图表显示(图, 0)).toEqual({ 点数: [] })
  expect(读取图表显示(图, 1)).toEqual({ 点数: [3] })
  expect(读取图表显示(图, 2)).toEqual({ 点数: [3, 3] })
  expect(读取图表显示(图, 9)).toEqual({ 点数: [3, 3] })
})

it('按分类播放保留全部系列并逐项增加数据点', () => {
  const 图 = 设置图表动态(双系列图表(), { 步进: '按分类', 每步毫秒: 500 }).图表!
  expect(读取图表显示(图, 0)).toEqual({ 点数: [0, 0] })
  expect(读取图表显示(图, 2)).toEqual({ 点数: [2, 2] })
  expect(读取图表显示(图, 3)).toEqual({ 点数: [3, 3] })
})

it('按系列与数据点播放逐点推进，最后一步为完整图表', () => {
  const 图 = 设置图表动态(双系列图表(), { 步进: '按系列与数据点', 每步毫秒: 300 }).图表!
  expect(读取图表显示(图, 1)).toEqual({ 点数: [1] })
  expect(读取图表显示(图, 3)).toEqual({ 点数: [3] })
  expect(读取图表显示(图, 4)).toEqual({ 点数: [3, 1] })
  expect(读取图表显示(图, 6)).toEqual({ 点数: [3, 3] })
})

it('图表分步动画只能指向设置了动态的图表', () => {
  const 图 = 设置图表动态(双系列图表(), { 步进: '按系列', 每步毫秒: 500 })
  const 页 = 创建幻灯片()
  页.对象列表 = [图]
  页.动画序列 = [{ id: 'a1', 对象标识: 图.id, 效果: '图表分步', 触发: '单击', 持续毫秒: 1500 }]
  expect(() => 校验动画(页)).not.toThrow()
  const 无动态 = 双系列图表()
  const 页2 = 创建幻灯片()
  页2.对象列表 = [无动态]
  页2.动画序列 = [{ id: 'a1', 对象标识: 无动态.id, 效果: '图表分步', 触发: '单击', 持续毫秒: 1500 }]
  expect(() => 校验动画(页2)).toThrow('图表分步')
  const 页3 = 创建幻灯片()
  const 框 = 创建文本框(0, 0, 100, 50, '文字')
  页3.文本框列表 = [框]
  页3.动画序列 = [{ id: 'a1', 对象标识: 框.id, 效果: '图表分步', 触发: '单击', 持续毫秒: 1500 }]
  expect(() => 校验动画(页3)).toThrow('图表分步')
})
