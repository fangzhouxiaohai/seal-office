import { expect, it } from 'vitest'
import { 添加幻灯片, 创建演示文稿, 删除幻灯片, 更新幻灯片 } from '../deck'
import {
  添加批注, 回复批注, 修改批注内容, 设置批注解决, 删除批注, 删除页面批注,
  读取页面批注, 批注导航, 批注统计, 批注对象失效, 校验批注列表, 默认批注作者,
} from './comments'

const 建稿 = () => {
  const 文稿 = 创建演示文稿()
  文稿.幻灯片列表.push(...添加幻灯片(文稿).幻灯片列表.slice(1))
  return 文稿
}

it('批注按页面与对象记录，作者与时间可追溯', () => {
  const 文稿 = 建稿(), 页 = 文稿.幻灯片列表[0], 框 = 页.文本框列表[0]
  const 第一条 = 添加批注(文稿, { 页标识: 页.id, 对象标识: 框.id, 内容: '标题需要更短', 作者: '张三', 时间: '2026-10-06T08:00:00.000Z' })
  const 第二条 = 添加批注(第一条.文稿, { 页标识: 页.id, 内容: '整页配色偏暗', 时间: '2026-10-06T08:05:00.000Z' })
  expect(第一条.批注).toMatchObject({ 页标识: 页.id, 对象标识: 框.id, 作者: '张三', 内容: '标题需要更短', 时间: '2026-10-06T08:00:00.000Z' })
  expect(第二条.批注.作者).toBe(默认批注作者)
  expect(读取页面批注(第二条.文稿, 页.id).map(项 => 项.内容)).toEqual(['标题需要更短', '整页配色偏暗'])
  expect(读取页面批注(第二条.文稿, 文稿.幻灯片列表[1].id)).toEqual([])
})

it('回复、解决与删除都保持线程完整并支持单次撤销语义', () => {
  const 文稿 = 建稿(), 页 = 文稿.幻灯片列表[0]
  const 基础 = 添加批注(文稿, { 页标识: 页.id, 内容: '请补充数据来源', 作者: '李四', 时间: '2026-10-06T09:00:00.000Z' })
  const 回复后 = 回复批注(基础.文稿, 基础.批注.id, '已补充脚注', '王五', '2026-10-06T09:30:00.000Z')
  const 线程 = 读取页面批注(回复后, 页.id)[0]
  expect(线程.回复).toEqual([{ id: expect.any(String), 作者: '王五', 内容: '已补充脚注', 时间: '2026-10-06T09:30:00.000Z' }])
  const 修改后 = 修改批注内容(回复后, 基础.批注.id, '请补充数据来源与口径')
  expect(读取页面批注(修改后, 页.id)[0].内容).toBe('请补充数据来源与口径')
  expect(读取页面批注(修改后, 页.id)[0].回复).toHaveLength(1)
  const 解决后 = 设置批注解决(修改后, 基础.批注.id, true)
  expect(读取页面批注(解决后, 页.id)[0].已解决).toBe(true)
  expect(批注统计(解决后)).toEqual({ 总数: 1, 未解决: 0, 已解决: 1 })
  const 删除后 = 删除批注(解决后, 基础.批注.id)
  expect(读取页面批注(删除后, 页.id)).toEqual([])
  expect(读取页面批注(回复后, 页.id)).toHaveLength(1)
})

it('删除页面连同该页批注一起移除，删除对象后批注标记为失效但不丢失', () => {
  const 文稿 = 建稿(), 首页 = 文稿.幻灯片列表[0], 次页 = 文稿.幻灯片列表[1]
  const 对象批注 = 添加批注(文稿, { 页标识: 首页.id, 对象标识: 首页.文本框列表[0].id, 内容: '首页对象批注' })
  const 带两页 = 添加批注(对象批注.文稿, { 页标识: 次页.id, 内容: '次页批注' }).文稿
  expect(批注对象失效(带两页, 读取页面批注(带两页, 首页.id)[0])).toBe(false)
  // 对象仍在但已不是批注目标时才算失效
  const 失效稿 = 更新幻灯片(带两页, 首页.id, { 文本框列表: 首页.文本框列表.filter(框 => 框.id !== 首页.文本框列表[0].id) })
  expect(批注对象失效(失效稿, 读取页面批注(失效稿, 首页.id)[0])).toBe(true)
  expect(读取页面批注(失效稿, 首页.id)).toHaveLength(1)
  const 删页后 = 删除页面批注(删除幻灯片(带两页, 次页.id), 次页.id)
  expect(读取页面批注(删页后, 次页.id)).toEqual([])
  expect(读取页面批注(删页后, 首页.id)).toHaveLength(1)
  expect(批注对象失效(删页后, 读取页面批注(删页后, 首页.id)[0])).toBe(false)
})

it('上一条与下一条按页面顺序跨页导航，末端返回空', () => {
  const 文稿 = 建稿(), 首页 = 文稿.幻灯片列表[0], 次页 = 文稿.幻灯片列表[1]
  const 目标 = 添加批注(添加批注(文稿, { 页标识: 首页.id, 内容: '一' }).文稿, { 页标识: 次页.id, 对象标识: 次页.文本框列表[1]?.id, 内容: '二' }).文稿
  expect(批注导航(目标, 首页.id, 1)).toEqual({ 页标识: 次页.id, 对象标识: 次页.文本框列表[1]?.id })
  expect(批注导航(目标, 次页.id, 1)).toBeNull()
  expect(批注导航(目标, 次页.id, -1)).toEqual({ 页标识: 首页.id, 对象标识: undefined })
  expect(批注导航(目标, 首页.id, -1)).toBeNull()
})

it('非法批注结构被拒绝，且不产生空白批注', () => {
  expect(() => 校验批注列表([{ id: '批注', 页标识: '页', 作者: '甲', 内容: '  ', 时间: '2026-10-06T00:00:00.000Z' }])).toThrow('批注内容无效')
  expect(() => 校验批注列表([{ id: '批注', 页标识: '', 作者: '甲', 内容: '内容', 时间: '2026-10-06T00:00:00.000Z' }])).toThrow('批注页面标识无效')
  expect(() => 校验批注列表([{ id: '批注', 页标识: '页', 作者: '', 内容: '内容', 时间: '2026-10-06T00:00:00.000Z' }])).toThrow('批注作者无效')
  expect(() => 校验批注列表([{ id: '批注', 页标识: '页', 作者: '甲', 内容: '内容', 时间: '昨天' }])).toThrow('批注时间无效')
  expect(() => 校验批注列表([{ id: '同', 页标识: '页', 作者: '甲', 内容: '内容', 时间: '2026-10-06T00:00:00.000Z' }, { id: '同', 页标识: '页', 作者: '甲', 内容: '内容', 时间: '2026-10-06T00:00:00.000Z' }])).toThrow('批注标识重复')
  expect(() => 添加批注(建稿(), { 页标识: '不存在的页', 内容: '内容' })).toThrow('批注页面不存在')
})

it('外部办公软件写出的无时区时间可以导入，非法时间仍被拒绝', () => {
  expect(() => 校验批注列表([{ id: '批注', 页标识: '页', 作者: '甲', 内容: '内容', 时间: '2026-10-06T08:00:00.000' }])).not.toThrow()
  expect(() => 校验批注列表([{ id: '批注', 页标识: '页', 作者: '甲', 内容: '内容', 时间: '2026-10-06T08:00:00+08:00' }])).not.toThrow()
  expect(() => 校验批注列表([{ id: '批注', 页标识: '页', 作者: '甲', 内容: '内容', 时间: '2026/10/06 08:00' }])).toThrow('批注时间无效')
})

