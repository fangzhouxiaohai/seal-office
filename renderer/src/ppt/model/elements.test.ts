import { describe, it, expect } from 'vitest'
import * as 元素 from './elements'
import { 修改对象, 解除组合 } from './objectOperations'
import { 创建幻灯片, 创建演示文稿, 复制幻灯片 } from '../deck'
import { HistoryStack } from '../../editor/history'

describe('任务三原生元素', () => {
  it('语义图增加节点和连线并拒绝无效引用', () => {
    let 页 = { ...创建幻灯片('空白'), 对象列表: 元素.创建语义图('流程') }
    const 组 = 页.对象列表.find(项 => 项.类型 === '组合')!
    const 原节点 = 页.对象列表.find(项 => 项.形状?.文本 === '完成')!
    页 = 元素.添加语义节点(页,组.id) as typeof 页
    const 新节点 = 页.对象列表.find(项 => 项.形状?.文本 === '新节点')!
    页 = 元素.添加语义连线(页,组.id,原节点.id,新节点.id) as typeof 页
    expect(页.对象列表.find(项 => 项.连接?.终点.对象 === 新节点.id)).toBeDefined()
    expect(() => 元素.添加语义连线(页,组.id,原节点.id,'不存在')).toThrow(/节点/)
  })
  it('复制语义图重映射节点引用且修改不影响原页', () => {
    const 文稿 = 创建演示文稿()
    文稿.幻灯片列表[0].对象列表 = 元素.创建语义图('流程')
    const 副本 = 复制幻灯片(文稿, 文稿.幻灯片列表[0].id).幻灯片列表[1]
    for (const 线 of 副本.对象列表!.filter(项 => 项.连接)) {
      expect(副本.对象列表!.some(项 => 项.id === 线.连接!.起点.对象)).toBe(true)
      expect(副本.对象列表!.some(项 => 项.id === 线.连接!.终点.对象)).toBe(true)
    }
  })
  it('图形旋转和几何修改跨撤销保持', () => {
    const 页 = { ...创建幻灯片('空白'), 对象列表: [元素.创建图形('矩形')] }
    const 历史 = new HistoryStack<typeof 页>()
    历史.record(页)
    const 新 = 修改对象(页, [页.对象列表[0].id], { 旋转: 37, x: 123 })
    expect(新.对象列表![0].旋转).toBe(37)
    expect(页.对象列表[0].旋转).toBeUndefined()
    历史.record(新 as typeof 页)
    expect(历史.undo()?.对象列表[0].x).toBe(页.对象列表[0].x)
  })
  it('修改单元格不改变其他格式，行列增删和合并可逆', () => {
    let 表 = 元素.创建表格(3, 3)
    表 = 元素.修改单元格(表, 1, 1, { 文本: '季度收入', 背景: '#123456', 加粗: true })
    表 = 元素.修改单元格(表, 0, 0, { 文本: '年度汇总' })
    expect(表.表格!.单元格[1][1]).toMatchObject({ 背景: '#123456', 加粗: true })
    表 = 元素.合并单元格(表, 0, 0, 1, 2)
    expect(表.表格!.合并).toEqual([{ 行: 0, 列: 0, 行数: 1, 列数: 2 }])
    expect(() => 元素.合并单元格(表, 0, 1, 2, 1)).toThrow(/重叠/)
    表 = 元素.取消单元格合并(表, 0, 0)
    表 = 元素.调整表格结构(表, '行', 1, '插入')
    expect(表.表格!.单元格[2][1].背景).toBe('#123456')
    表 = 元素.调整表格结构(表, '行', 1, '删除')
    expect(表.表格!.单元格).toHaveLength(3)
    表 = 元素.调整表格结构(表, '列', 1, '插入')
    expect(表.表格!.单元格[1][2].文本).toBe('季度收入')
  })
  it.each(['流程','层级','循环','脑图'] as const)('%s 节点移动更新连接点，解除组合保留位置', 类型 => {
    const 页 = { ...创建幻灯片('空白'), 对象列表: 元素.创建语义图(类型) }
    const 节点 = 页.对象列表.find(项 => 项.形状?.文本 === '开始')!
    const 移动 = 修改对象(页, [节点.id], { x: 节点.x + 71, 旋转: 30 })
    const 连接 = 移动.对象列表!.find(项 => 项.连接?.起点.对象 === 节点.id)!
    expect(连接.连接!.起点位置).toEqual(元素.计算连接点(移动.对象列表!.find(项 => 项.id === 节点.id)!, 连接.连接!.起点.边))
    const 解组 = 解除组合(移动, [页.对象列表.find(项 => 项.类型 === '组合')!.id])
    expect(解组.对象列表!.find(项 => 项.id === 节点.id)).toEqual(移动.对象列表!.find(项 => 项.id === 节点.id))
  })
})
