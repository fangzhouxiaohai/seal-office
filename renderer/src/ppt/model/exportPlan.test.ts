import { describe, expect, it } from 'vitest'
import { 创建演示文稿, 添加幻灯片 } from '../deck'
import { 生成导出文件名, 生成多页目录名, 校验导出选项, 规划导出页, 默认导出选项 } from './exportPlan'

function 造三页() {
  let 文稿 = 创建演示文稿()
  文稿 = 添加幻灯片(文稿)
  文稿 = 添加幻灯片(文稿)
  return 文稿
}

describe('导出页面规划', () => {
  it('全部页默认跳过隐藏页', () => {
    const 文稿 = 造三页()
    文稿.幻灯片列表[1].隐藏 = true
    const 结果 = 规划导出页(文稿, 默认导出选项)
    expect(结果.map(项 => 项.序号)).toEqual([0, 2])
  })

  it('显式包含隐藏页时导出全部页', () => {
    const 文稿 = 造三页()
    文稿.幻灯片列表[1].隐藏 = true
    expect(规划导出页(文稿, { ...默认导出选项, 含隐藏页: true }).map(项 => 项.序号)).toEqual([0, 1, 2])
  })

  it('当前页范围只导出当前页，当前页隐藏时给出真实原因', () => {
    const 文稿 = 造三页()
    文稿.当前索引 = 2
    expect(规划导出页(文稿, { ...默认导出选项, 范围: '当前页' })).toHaveLength(1)
    文稿.幻灯片列表[2].隐藏 = true
    expect(() => 规划导出页(文稿, { ...默认导出选项, 范围: '当前页' })).toThrow('当前页已隐藏')
  })

  it('选定页按页面标识引用，未知标识与空选择都被拒绝', () => {
    const 文稿 = 造三页()
    const 目标 = 文稿.幻灯片列表[2].id
    expect(规划导出页(文稿, { ...默认导出选项, 范围: '选定页', 选定页: [目标] }).map(项 => 项.序号)).toEqual([2])
    expect(() => 规划导出页(文稿, { ...默认导出选项, 范围: '选定页', 选定页: [] })).toThrow('请选择要导出的页面')
    expect(() => 规划导出页(文稿, { ...默认导出选项, 范围: '选定页', 选定页: ['不存在'] })).toThrow('选定页面不存在')
  })

  it('没有可导出页面时拒绝执行', () => {
    const 文稿 = 造三页()
    文稿.幻灯片列表.forEach(页 => { 页.隐藏 = true })
    expect(() => 规划导出页(文稿, 默认导出选项)).toThrow('没有可导出的页面')
  })

  it('零页文稿导出时给出真实原因', () => {
    const 文稿 = { ...创建演示文稿(), 幻灯片列表: [] }
    expect(() => 规划导出页(文稿, 默认导出选项)).toThrow('没有可导出的页面')
  })
})

describe('导出选项校验', () => {
  it('分辨率与质量越界被拒绝', () => {
    expect(() => 校验导出选项({ ...默认导出选项, 分辨率倍数: 0.5 })).toThrow('分辨率')
    expect(() => 校验导出选项({ ...默认导出选项, 分辨率倍数: 5 })).toThrow('分辨率')
    expect(() => 校验导出选项({ ...默认导出选项, JPEG质量: 0 })).toThrow('画质')
    expect(() => 校验导出选项({ ...默认导出选项, JPEG质量: 1.5 })).toThrow('画质')
  })

  it('讲义张数只允许 1、2、3、4、6、9', () => {
    expect(() => 校验导出选项({ ...默认导出选项, 格式: 'PDF', 讲义每页张数: 5 as never })).toThrow('讲义')
    expect(() => 校验导出选项({ ...默认导出选项, 格式: 'PNG', 讲义每页张数: 6 })).toThrow('讲义')
    for (const 张数 of [1, 2, 3, 4, 6, 9]) {
      expect(() => 校验导出选项({ ...默认导出选项, 格式: 'PDF', 讲义每页张数: 张数 as never })).not.toThrow()
    }
  })

  it('备注输出只用于 PDF', () => {
    expect(() => 校验导出选项({ ...默认导出选项, 格式: '图片型PPTX', 输出备注: true })).toThrow('备注')
    expect(() => 校验导出选项({ ...默认导出选项, 格式: 'PDF', 输出备注: true })).not.toThrow()
  })
})

describe('导出命名', () => {
  it('单页文件带页码，多页文件使用独立目录', () => {
    expect(生成导出文件名('季度汇报.pptx', 'PNG', 3)).toBe('季度汇报-第3页.png')
    expect(生成导出文件名('季度汇报.pptx', 'JPEG', 1)).toBe('季度汇报-第1页.jpg')
    expect(生成导出文件名('季度汇报.pptx', 'PDF')).toBe('季度汇报.pdf')
    expect(生成导出文件名('季度汇报.pptx', '扫描件PDF')).toBe('季度汇报-扫描件.pdf')
    expect(生成导出文件名('季度汇报.pptx', '图片型PPTX')).toBe('季度汇报-图片版.pptx')
    expect(生成多页目录名('季度汇报.pptx', 'PNG')).toBe('季度汇报-图片')
  })

  it('空名称回落默认值', () => {
    expect(生成导出文件名('   ', 'PDF')).toBe('演示文稿.pdf')
  })
})
