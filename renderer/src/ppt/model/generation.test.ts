import { describe, expect, it } from 'vitest'
import { 创建演示文稿, 读取当前幻灯片 } from '../deck'
import {
  页面版本表, 生成页面转幻灯片, 应用提纲生成, 应用单页生成, 应用美化建议, 构建生成图形, 插入生成对象,
} from './generation'

const 页面 = [
  { 页标识: 'p1', 标题: '季度目标', 正文: '开场说明', 版式: '标题幻灯片' as const, 要点: [] },
  { 页标识: 'p2', 标题: '关键举措', 正文: '围绕两条主线', 版式: '标题和内容' as const, 要点: ['渠道扩展', '成本优化'] },
]

describe('生成候选落地为可编辑文稿', () => {
  it('生成的页面转成带标题与要点的可编辑幻灯片', () => {
    const 页 = 生成页面转幻灯片(页面[1])
    expect(页.版式).toBe('标题和内容')
    const 文本 = 页.文本框列表.map((框) => 框.text)
    expect(文本).toContain('关键举措')
    expect(文本.join('\n')).toContain('渠道扩展')
    expect(页.文本框列表.every((框) => 框.id.length > 0)).toBe(true)
  })

  it('按提纲插入到指定位置并保留原有页面', () => {
    const 文稿 = 创建演示文稿()
    文稿.幻灯片列表 = [生成页面转幻灯片(页面[0])]
    const 结果 = 应用提纲生成(文稿, 页面, { 插入位置: 1 })
    expect(结果.幻灯片列表).toHaveLength(3)
    expect(结果.幻灯片列表[1].title).toBe('季度目标')
    expect(结果.幻灯片列表[2].title).toBe('关键举措')
    expect(结果.当前索引).toBe(1)
    expect(文稿.幻灯片列表).toHaveLength(1)
  })

  it('单页生成插入到当前页之后，版本不符时拒绝应用', () => {
    const 文稿 = 创建演示文稿()
    const 版本表 = 页面版本表(文稿)
    const 页面候选 = { 页标识: 'p1', 标题: '封面', 正文: '副标题', 版式: '标题幻灯片' as const, 要点: [] }
    const 插入 = 应用单页生成(文稿, 页面候选, { 版本表 })
    expect(插入.幻灯片列表).toHaveLength(2)
    expect(插入.当前索引).toBe(1)
    const 已改动 = { ...文稿, 幻灯片列表: 文稿.幻灯片列表.map((页) => ({ ...页, title: '已被修改' })) }
    expect(() => 应用单页生成(已改动, 页面候选, { 版本表 })).toThrow('文稿已变化')
  })

  it('美化建议按版本核对后应用对齐、字号、背景与版式，并可撤销（返回新对象）', () => {
    const 文稿 = 创建演示文稿()
    文稿.幻灯片列表 = [生成页面转幻灯片(页面[0]), 生成页面转幻灯片(页面[1])]
    const 版本表 = 页面版本表(文稿)
    const 建议 = [
      { 页标识: 文稿.幻灯片列表[0].id, 对齐: '居中' as const, 字号建议: 32, 要点上限: 4, 背景建议: '浅色' as const, 版式建议: '标题幻灯片' as const, 说明: '突出标题' },
      { 页标识: 文稿.幻灯片列表[1].id, 对齐: '左对齐' as const, 字号建议: 20, 要点上限: 3, 背景建议: '深色' as const, 版式建议: '标题和内容' as const },
    ]
    const 结果 = 应用美化建议(文稿, 建议, 版本表)
    expect(结果.幻灯片列表[0].文本框列表.every((框) => 框.对齐 === 'center')).toBe(true)
    expect(结果.幻灯片列表[0].文本框列表[0].字号).toBe(32)
    expect(结果.幻灯片列表[1].背景色).not.toBe(文稿.幻灯片列表[1].背景色)
    // 原文稿不被修改，便于单次撤销还原
    expect(文稿.幻灯片列表[0].文本框列表[0].字号).toBe(40)
  })

  it('美化建议引用不存在的页面或版本变化时拒绝应用', () => {
    const 文稿 = 创建演示文稿()
    const 版本表 = 页面版本表(文稿)
    expect(() => 应用美化建议(文稿, [{ 页标识: '不存在的页', 对齐: '居中', 字号建议: 24, 要点上限: 4, 背景建议: '浅色', 版式建议: '空白' }], 版本表)).toThrow('页面已不存在')
    expect(() => 应用美化建议(文稿, [{ 页标识: 文稿.幻灯片列表[0].id, 对齐: '居中', 字号建议: 24, 要点上限: 4, 背景建议: '浅色', 版式建议: '空白' }], {})).toThrow('文稿已变化')
  })

  it('智能图形生成可编辑的语义组合，节点文本与连线关系保留', () => {
    const 对象 = 构建生成图形('流程', [{ 标识: 'n1', 文本: '开始' }, { 标识: 'n2', 文本: '处理' }], [{ 起点: 'n1', 终点: 'n2', 文本: '是' }])
    const 组合 = 对象.find((项) => 项.类型 === '组合')
    expect(组合).toBeTruthy()
    expect(组合!.子对象标识).toHaveLength(3)
    const 节点 = 对象.filter((项) => 项.类型 === '图形' && 项.形状 && !项.连接)
    expect(节点.map((项) => 项.形状!.文本)).toEqual(['开始', '处理'])
    const 连线 = 对象.filter((项) => 项.连接)
    expect(连线).toHaveLength(1)
    expect(连线[0].连接!.起点.对象).toBe(节点[0].id)
    expect(连线[0].连接!.终点.对象).toBe(节点[1].id)
    expect(连线[0].形状!.文本).toBe('是')
  })

  it('图形对象插入到指定页面并保留原有对象', () => {
    const 页 = 创建幻灯片页()
    const 结果 = 插入生成对象(页, 构建生成图形('脑图', [{ 标识: 'n1', 文本: '中心' }], []))
    expect(结果.对象列表!.length).toBe((页.对象列表?.length ?? 0) + 2)
    expect(结果.对象列表!.some((项) => 项.类型 === '组合')).toBe(true)
  })

  it('非法候选拒绝落地并说明原因', () => {
    const 文稿 = 创建演示文稿()
    expect(() => 应用提纲生成(文稿, [], { 插入位置: 0 })).toThrow('没有可插入')
    expect(() => 应用提纲生成(文稿, 页面, { 插入位置: 99 })).toThrow('插入位置')
    expect(() => 生成页面转幻灯片({ ...页面[0], 标题: '' })).toThrow('标题')
    expect(() => 构建生成图形('流程', [{ 标识: 'n1', 文本: 'a' }, { 标识: 'n1', 文本: 'b' }], [])).toThrow('重复')
  })
})

function 创建幻灯片页() {
  const 文稿 = 创建演示文稿()
  return 读取当前幻灯片(文稿)!
}
