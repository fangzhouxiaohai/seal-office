import { describe, expect, it } from 'vitest'
import { 创建演示文稿 } from '../deck'
import {
  默认讲义设置,
  默认备注设置,
  校验讲义设置,
  校验备注设置,
  读取讲义占位符,
  讲义网格,
  规划讲义页,
} from './handout'

describe('讲义与备注母版设置', () => {
  it('默认设置符合 WPS 常用讲义排版', () => {
    expect(默认讲义设置).toMatchObject({ 每页张数: 6, 显示页码: true, 显示日期: false, 页眉: '', 页脚: '' })
    expect(默认备注设置).toMatchObject({ 排版: '幻灯片加备注', 显示页码: true, 显示日期: false })
  })

  it('张数、页眉页脚长度与备注排版按真实原因校验', () => {
    expect(() => 校验讲义设置({ ...默认讲义设置, 每页张数: 5 as unknown as 6 })).toThrow('每页张数')
    expect(() => 校验讲义设置({ ...默认讲义设置, 页眉: 'x'.repeat(121) })).toThrow('页眉')
    expect(() => 校验讲义设置({ ...默认讲义设置, 页脚: 'x'.repeat(121) })).toThrow('页脚')
    expect(() => 校验备注设置({ ...默认备注设置, 排版: '随便' as unknown as '仅备注' })).toThrow('备注排版')
    expect(() => 校验讲义设置(默认讲义设置)).not.toThrow()
    for (const 张数 of [1, 2, 3, 4, 6, 9]) expect(() => 校验讲义设置({ ...默认讲义设置, 每页张数: 张数 as 6 })).not.toThrow()
  })

  it('页眉页脚支持日期与页码占位符，替换后不再是占位符', () => {
    const 文本 = 读取讲义占位符('第 <页码> 页　<日期>', 3, new Date('2026-10-06T08:00:00Z'))
    expect(文本).toBe('第 3 页　2026-10-06')
    expect(读取讲义占位符('没有占位符', 2, new Date('2026-10-06T08:00:00Z'))).toBe('没有占位符')
    expect(读取讲义占位符('', 1, new Date('2026-10-06T08:00:00Z'))).toBe('')
  })

  it('讲义网格覆盖 1、2、3、4、6、9 张', () => {
    expect(讲义网格(1)).toEqual({ 列数: 1, 行数: 1 })
    expect(讲义网格(2)).toEqual({ 列数: 1, 行数: 2 })
    expect(讲义网格(3)).toEqual({ 列数: 1, 行数: 3 })
    expect(讲义网格(4)).toEqual({ 列数: 2, 行数: 2 })
    expect(讲义网格(6)).toEqual({ 列数: 2, 行数: 3 })
    expect(讲义网格(9)).toEqual({ 列数: 3, 行数: 3 })
  })

  it('按张数分页，最后一页不足也成页，且保持页面顺序', () => {
    const 文稿 = 创建演示文稿()
    文稿.幻灯片列表 = Array.from({ length: 7 }, (_, i) => ({ ...文稿.幻灯片列表[0], id: `页${i + 1}`, title: `页${i + 1}` }))
    const 页列表 = 规划讲义页(文稿, { ...默认讲义设置, 每页张数: 3 })
    expect(页列表.map(页 => 页.map(项 => 项.页.id))).toEqual([['页1', '页2', '页3'], ['页4', '页5', '页6'], ['页7']])
    const 九张 = 规划讲义页(文稿, { ...默认讲义设置, 每页张数: 9 })
    expect(九张).toHaveLength(1)
    expect(九张[0]).toHaveLength(7)
  })

  it('隐藏页不出现在讲义中，全部隐藏时给出真实原因', () => {
    const 文稿 = 创建演示文稿()
    文稿.幻灯片列表 = [
      { ...文稿.幻灯片列表[0], id: '甲' },
      { ...文稿.幻灯片列表[0], id: '乙', 隐藏: true },
    ]
    const 页列表 = 规划讲义页(文稿, { ...默认讲义设置, 每页张数: 1 })
    expect(页列表.flat().map(项 => 项.页.id)).toEqual(['甲'])
    const 全部隐藏 = { ...文稿, 幻灯片列表: 文稿.幻灯片列表.map(页 => ({ ...页, 隐藏: true })) }
    expect(() => 规划讲义页(全部隐藏, 默认讲义设置)).toThrow('没有可输出的页面')
  })
})
