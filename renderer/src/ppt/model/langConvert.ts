const 最长匹配 = (文本: string, 起点: number, 表: Record<string, string>): [string, string] | null => {
  for (let 长度 = 4; 长度 >= 2; 长度--) {
    if (起点 + 长度 > 文本.length) continue
    const 键 = 文本.slice(起点, 起点 + 长度)
    if (Object.prototype.hasOwnProperty.call(表, 键)) return [键, 表[键]]
  }
  return null
}

/** 词组级转换：先按最长词组匹配，未命中时回退单字表。 */
export function 转换简繁词组(文本: string, 方向: 转换方向): 转换结果 {
  const 词组表 = 方向 === '繁' ? 简到繁词组表 : 繁到简词组表
  const 单字表 = 方向 === '繁' ? 简到繁单字表 : 繁到简单字表
  const 片段: 转换片段[] = []
  let 转换数 = 0
  const 追加 = (内容: string, 改变: boolean) => {
    if (内容.length === 0) return
    const 上一层 = 片段[片段.length - 1]
    if (上一层 && 上一层.改变 === 改变) 上一层.文本 += 内容
    else 片段.push({ 文本: 内容, 改变 })
  }
  let 位置 = 0
  while (位置 < 文本.length) {
    const 匹配 = 最长匹配(文本, 位置, 词组表)
    if (匹配) {
      const 改变 = 匹配[1] !== 匹配[0]
      if (改变) 转换数 += 1
      追加(匹配[1], 改变)
      位置 += 匹配[0].length
      continue
    }
    const 字符 = 文本[位置]
    const 目标 = 单字表[字符] ?? 字符
    if (目标 !== 字符) 转换数 += 1
    追加(目标, 目标 !== 字符)
    位置 += 1
  }
  return { 文本: 片段.map(项 => 项.文本).join(''), 片段, 转换数 }
}

/** 只取转换后的文本。 */
export function 转换文本(文本: string, 方向: 转换方向): string {
  return 转换简繁词组(文本, 方向).文本
}

/** 生成差异片段（以译文为准）；长度一致时逐字比较，否则按公共前后缀对齐。 */export function 差异片段(原文: string, 译文: string): 转换片段[] {
  if (原文 === 译文) return 原文.length === 0 ? [] : [{ 文本: 译文, 改变: false }]
  if (原文.length === 译文.length) {
    const 片段: 转换片段[] = []
    for (let i = 0; i < 译文.length; i++) {
      const 改变 = 原文[i] !== 译文[i]
      const 上一层 = 片段[片段.length - 1]
      if (上一层 && 上一层.改变 === 改变) 上一层.文本 += 译文[i]
      else 片段.push({ 文本: 译文[i], 改变 })
    }
    return 片段
  }
  let 前缀 = 0
  while (前缀 < 原文.length && 前缀 < 译文.length && 原文[前缀] === 译文[前缀]) 前缀++
  let 后缀 = 0
  while (后缀 < 原文.length - 前缀 && 后缀 < 译文.length - 前缀 && 原文[原文.length - 1 - 后缀] === 译文[译文.length - 1 - 后缀]) 后缀++
  const 结果: 转换片段[] = []
  if (前缀 > 0) 结果.push({ 文本: 译文.slice(0, 前缀), 改变: false })
  const 中间 = 译文.slice(前缀, 译文.length - 后缀)
  if (中间.length > 0) 结果.push({ 文本: 中间, 改变: true })
  if (后缀 > 0) 结果.push({ 文本: 译文.slice(译文.length - 后缀), 改变: false })
  return 结果
}

/**
 * 转换文本框：先按整段文本做词组匹配，再按原有片段边界回填，保留每个片段的格式。
 * 所有映射都保持字符数不变，长度不一致时拒绝改写，避免破坏片段结构。
 */
export function 转换文本框(框: 文本框, 方向: 转换方向): 文本框 {
  const 译文 = 转换简繁词组(框.text ?? '', 方向).文本
  if (译文 === 框.text) return 框
  if (译文.length !== (框.text ?? '').length) throw new Error('转换结果长度与原文不一致，已阻止改写')
  const 片段列表 = 框.片段列表
  if (!片段列表 || 片段列表.length === 0) return { ...框, text: 译文 }
  let 位置 = 0
  const 新片段 = 片段列表.map(片段 => {
    const 新文本 = 译文.slice(位置, 位置 + 片段.文本.length)
    位置 += 片段.文本.length
    return { ...片段, 文本: 新文本 }
  })
  return { ...框, text: 译文, 片段列表: 新片段 }
}

/** 转换整页的全部文本框，保留段落与对象格式。 */
export function 转换幻灯片(页: 幻灯片, 方向: 转换方向): 幻灯片 {
  return { ...页, 文本框列表: 页.文本框列表.map(框 => 转换文本框(框, 方向)) }
}
