import { describe, expect, it } from 'vitest'
import { 创建演示文稿, 创建文本框, type 演示文稿 } from '../deck'
import { 内置主题列表, 默认主题标识 } from './themes'
import {
  默认母版标识,
  创建母版,
  创建默认母版,
  保存母版列表,
  套用版式,
  应用母版,
  恢复继承,
  按版式创建幻灯片,
  新增版式,
  校验母版列表,
  查找版式,
  标记占位符覆盖,
  编辑占位符,
  解除继承,
  解析页面背景,
  解析页面继承,
  同步占位符,
  删除版式,
} from './masters'

const 默认主题 = 内置主题列表.find((项) => 项.标识 === 默认主题标识)!

describe('母版、版式与占位符', () => {
  it('默认母版包含标题幻灯片、标题和内容与空白版式', () => {
    const 母版 = 创建默认母版()
    expect(母版.标识).toBe(默认母版标识)
    expect(母版.版式列表.map((项) => 项.名称)).toEqual(['标题幻灯片', '标题和内容', '空白'])
    const 标题版式 = 母版.版式列表[0]
    expect(标题版式.占位符列表.map((项) => 项.类型)).toEqual(['标题'])
    expect(母版.版式列表[1].占位符列表.map((项) => 项.类型)).toEqual(['标题', '正文'])
    expect(母版.版式列表[2].占位符列表).toEqual([])
  })

  it('按版式创建幻灯片生成占位符文本框并携带主题引用', () => {
    const 母版 = 创建默认母版()
    const 版式 = 母版.版式列表[1]
    const 页 = 按版式创建幻灯片(版式, 默认主题, '新页')

    expect(页.版式).toBe('标题和内容')
    expect(页.版式标识).toBe(版式.标识)
    expect(页.母版标识).toBe(默认母版标识)
    expect(页.文本框列表).toHaveLength(2)
    const 标题 = 页.文本框列表[0]
    expect(标题.占位符).toBe('标题')
    expect(标题.占位符标识).toBe(版式.占位符列表[0].标识)
    expect(标题.占位符继承).toBe(true)
    expect(标题.颜色引用).toBe('文本1')
    expect(标题.颜色).toBe(默认主题.配色.文本1)
    expect(标题.字体).toBe(默认主题.字体.标题)
    expect(标题.x).toBe(版式.占位符列表[0].x)
    expect(标题.width).toBe(版式.占位符列表[0].width)
  })

  it('解析页面背景按单页、版式、母版、主题顺序生效', () => {
    const 母版 = 创建默认母版()
    母版.背景填充 = { 类型: '纯色', 颜色: '#111111' }
    const 版式 = 母版.版式列表[1]
    版式.背景填充 = { 类型: '纯色', 颜色: '#222222' }
    const 页 = 按版式创建幻灯片(版式, 默认主题, '页')
    const 文稿: 演示文稿 = { ...创建演示文稿(), 主题: 默认主题, 母版列表: [母版], 幻灯片列表: [页] }

    expect(解析页面背景(文稿, 页)).toEqual({ 类型: '纯色', 颜色: '#222222' })

    const 覆盖页 = { ...页, 背景填充: { 类型: '纯色' as const, 颜色: '#333333' } }
    expect(解析页面背景(文稿, 覆盖页)).toEqual({ 类型: '纯色', 颜色: '#333333' })

    版式.背景填充 = undefined
    expect(解析页面背景(文稿, 页)).toEqual({ 类型: '纯色', 颜色: '#111111' })

    母版.背景填充 = undefined
    文稿.主题 = { ...默认主题, 背景: { 类型: '渐变', 起始色: '#FFFFFF', 结束色: '#EEEEEE', 角度: 45 } }
    expect(解析页面背景(文稿, 页)).toEqual({ 类型: '渐变', 起始色: '#FFFFFF', 结束色: '#EEEEEE', 角度: 45 })

    文稿.主题 = { ...默认主题, 背景: undefined }
    expect(解析页面背景(文稿, 页)).toEqual({ 类型: '纯色', 颜色: 页.背景色 })
  })

  it('继承解析返回母版配色覆盖与版式占位符', () => {
    const 母版 = 创建默认母版()
    母版.配色 = { 强调1: '#123123' }
    const 版式 = 母版.版式列表[0]
    const 页 = 按版式创建幻灯片(版式, 默认主题, '页')
    页.母版标识 = 母版.标识
    const 文稿: 演示文稿 = { ...创建演示文稿(), 主题: 默认主题, 母版列表: [母版], 幻灯片列表: [页] }

    const 继承 = 解析页面继承(文稿, 页)

    expect(继承.母版?.标识).toBe(母版.标识)
    expect(继承.版式?.标识).toBe(版式.标识)
    expect(继承.配色.强调1).toBe('#123123')
    expect(继承.配色.文本1).toBe(默认主题.配色.文本1)
    expect(继承.占位符列表).toBe(版式.占位符列表)
  })

  it('同步占位符只更新未解除继承的文本框', () => {
    const 母版 = 创建默认母版()
    const 版式 = 母版.版式列表[1]
    const 页 = 按版式创建幻灯片(版式, 默认主题, '页')
    // 第二个占位符已被单页覆盖，不再跟随版式
    const 覆盖页 = 标记占位符覆盖(页, 页.文本框列表[1].id)
    const 文稿: 演示文稿 = { ...创建演示文稿(), 主题: 默认主题, 母版列表: [母版], 幻灯片列表: [覆盖页] }

    const 编辑后 = 编辑占位符([母版], 母版.标识, 版式.标识, { ...版式.占位符列表[0], y: 200 })
    const 结果 = 同步占位符({ ...文稿, 母版列表: 编辑后 }, 页.id)

    expect(结果.更新数量).toBe(1)
    expect(结果.文稿.幻灯片列表[0].文本框列表[0].y).toBe(200)
    expect(结果.文稿.幻灯片列表[0].文本框列表[1].x).toBe(版式.占位符列表[1].x)
    expect(结果.文稿.幻灯片列表[0].文本框列表[1].占位符继承).toBe(false)
  })

  it('解除继承固化当前继承值并停止跟随版式变化', () => {
    const 母版 = 创建默认母版()
    母版.背景填充 = { 类型: '纯色', 颜色: '#ABCDEF' }
    const 版式 = 母版.版式列表[1]
    const 页 = 按版式创建幻灯片(版式, 默认主题, '页')
    const 文稿: 演示文稿 = { ...创建演示文稿(), 主题: 默认主题, 母版列表: [母版], 幻灯片列表: [页] }

    const 解除 = 解除继承(文稿, 页.id)
    expect(解除.幻灯片列表[0].背景继承).toBe(false)
    expect(解除.幻灯片列表[0].背景填充).toEqual({ 类型: '纯色', 颜色: '#ABCDEF' })
    expect(解除.幻灯片列表[0].文本框列表.every((框) => 框.占位符继承 === false)).toBe(true)

    const 改版式 = 编辑占位符(解除.母版列表!, 母版.标识, 版式.标识, { ...版式.占位符列表[0], y: 400 })
    const 再同步 = 同步占位符({ ...解除, 母版列表: 改版式 }, 页.id)
    expect(再同步.更新数量).toBe(0)
    expect(再同步.文稿.幻灯片列表[0].文本框列表[0].y).toBe(版式.占位符列表[0].y)

    const 恢复 = 恢复继承(再同步.文稿, 页.id)
    expect(恢复.幻灯片列表[0].背景继承).toBeUndefined()
    expect(恢复.幻灯片列表[0].背景填充).toBeUndefined()
    expect(恢复.幻灯片列表[0].文本框列表[0].占位符继承).toBe(true)
    const 恢复同步 = 同步占位符(恢复, 页.id)
    expect(恢复同步.文稿.幻灯片列表[0].文本框列表[0].y).toBe(400)
  })

  it('新增与编辑版式，删除被引用版式被拒绝', () => {
    const 母版 = 创建默认母版()
    const 新增 = 新增版式([母版], 母版.标识, '图文混排')
    expect(新增[0].版式列表.map((项) => 项.名称)).toContain('图文混排')
    const 新版式 = 新增[0].版式列表[新增[0].版式列表.length - 1]
    expect(新版式.占位符列表.length).toBeGreaterThan(0)

    const 编辑后 = 编辑占位符(新增, 母版.标识, 新版式.标识, { ...新版式.占位符列表[0], 字号: 36 })
    expect(查找版式(编辑后, 新版式.标识)?.版式.占位符列表[0].字号).toBe(36)

    expect(() => 删除版式(编辑后, 母版.标识, 新版式.标识, [新版式.标识])).toThrow(/引用/)
    const 删除后 = 删除版式(编辑后, 母版.标识, 新版式.标识)
    expect(查找版式(删除后, 新版式.标识)).toBeNull()
  })

  it('套用版式保留单页覆盖、备注与对象', () => {
    const 母版 = 创建默认母版()
    const 标题版式 = 母版.版式列表[0]
    const 内容版式 = 母版.版式列表[1]
    const 页 = 按版式创建幻灯片(标题版式, 默认主题, '页')
    页.备注 = '保留备注'
    页.对象列表 = [{ id: '图片一', 类型: '图片', x: 10, y: 10, width: 20, height: 20, 资源标识: '指纹一' }]
    页.背景填充 = { 类型: '纯色', 颜色: '#F0F0F0' }
    const 移动后 = { ...页, 文本框列表: [{ ...页.文本框列表[0], x: 321, 占位符继承: false }] }
    const 文稿: 演示文稿 = { ...创建演示文稿(), 主题: 默认主题, 母版列表: [母版], 幻灯片列表: [移动后] }

    const 结果 = 套用版式(文稿, 页.id, 内容版式.标识)

    const 新页 = 结果.幻灯片列表[0]
    expect(新页.版式标识).toBe(内容版式.标识)
    expect(新页.备注).toBe('保留备注')
    expect(新页.对象列表).toEqual(页.对象列表)
    expect(新页.背景填充).toEqual({ 类型: '纯色', 颜色: '#F0F0F0' })
    // 已被用户移动的标题保留覆盖位置
    expect(新页.文本框列表[0].x).toBe(321)
    // 版式中缺少的正文占位符被补齐
    expect(新页.文本框列表).toHaveLength(2)
    expect(新页.文本框列表[1].占位符标识).toBe(内容版式.占位符列表[1].标识)
  })

  it('应用母版更新页面并保留显式颜色', () => {
    const 母版 = 创建默认母版()
    const 版式 = 母版.版式列表[1]
    const 页 = 按版式创建幻灯片(版式, 默认主题, '页')
    页.文本框列表 = [...页.文本框列表, 创建文本框(700, 470, 200, 40, '显式黑', 14)]
    页.文本框列表[2].颜色 = '#000000'
    const 文稿: 演示文稿 = { ...创建演示文稿(), 主题: 默认主题, 母版列表: [母版], 幻灯片列表: [页] }

    const 新母版 = { ...创建母版('新母版', 母版.标识), 版式列表: [{ ...版式, 背景填充: { 类型: '纯色' as const, 颜色: '#101820' } }] }
    const 结果 = 应用母版(文稿, 新母版)

    expect(结果.母版列表?.[0].版式列表[0].背景填充).toEqual({ 类型: '纯色', 颜色: '#101820' })
    expect(解析页面背景(结果, 结果.幻灯片列表[0])).toEqual({ 类型: '纯色', 颜色: '#101820' })
    expect(结果.幻灯片列表[0].文本框列表[0].颜色).toBe(默认主题.配色.文本1)
    expect(结果.幻灯片列表[0].文本框列表[2].颜色).toBe('#000000')
    expect(结果.幻灯片列表[0].文本框列表[2].text).toBe('显式黑')
  })

  it('保存母版列表会复制输入并校验字段', () => {
    const 母版 = 创建默认母版()
    const 输入 = [母版]
    const 保存 = 保存母版列表(输入)
    expect(保存).toEqual(输入)
    expect(保存).not.toBe(输入)
    expect(保存[0]).not.toBe(母版)
    expect(() => 校验母版列表([{ 标识: '', 名称: 'x', 版式列表: [] }])).toThrow(/母版/)
    expect(() => 校验母版列表([{ 标识: 'a', 名称: 'x', 版式列表: [{ 标识: 'b', 名称: 'y', 占位符列表: [{ 标识: 'c', 类型: '错误', x: 0, y: 0, width: 1, height: 1, 字号: 12, 对齐: 'left' }] }] }])).toThrow(/占位符/)
  })
})
