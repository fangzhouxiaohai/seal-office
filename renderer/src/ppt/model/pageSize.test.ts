import { describe, expect, it } from 'vitest'
import { 创建演示文稿 } from '../deck'
import { 默认页面尺寸, 像素转点, 读取页面尺寸, 校验页面尺寸 } from './pageSize'

describe('页面尺寸', () => {
  it('缺少页面尺寸字段时回退到 960×540', () => {
    const 文稿 = 创建演示文稿()
    expect(读取页面尺寸(文稿)).toEqual(默认页面尺寸)
  })

  it('读取 16:9 与 4:3 页面尺寸', () => {
    expect(读取页面尺寸({ 页面尺寸: { 宽: 960, 高: 540 } })).toEqual({ 宽: 960, 高: 540 })
    expect(读取页面尺寸({ 页面尺寸: { 宽: 720, 高: 540 } })).toEqual({ 宽: 720, 高: 540 })
  })

  it('方向与尺寸不一致时按方向纠正宽高', () => {
    expect(读取页面尺寸({ 页面尺寸: { 宽: 540, 高: 960, 方向: '横向' } })).toEqual({ 宽: 960, 高: 540, 方向: '横向' })
    expect(读取页面尺寸({ 页面尺寸: { 宽: 960, 高: 540, 方向: '纵向' } })).toEqual({ 宽: 540, 高: 960, 方向: '纵向' })
  })

  it('非法尺寸给出真实原因', () => {
    expect(() => 校验页面尺寸({ 宽: 0, 高: 540 })).toThrow('页面宽度无效')
    expect(() => 校验页面尺寸({ 宽: 960, 高: Number.NaN })).toThrow('页面高度无效')
    expect(() => 校验页面尺寸({ 宽: 960, 高: 540, 方向: '斜向' as never })).toThrow('页面方向无效')
    expect(() => 读取页面尺寸({ 页面尺寸: { 宽: 20000, 高: 540 } })).toThrow('页面尺寸超出支持范围')
  })

  it('画布像素与 PDF 点按 72dpi 一一对应', () => {
    expect(像素转点(960)).toBe(960)
    expect(像素转点(540)).toBe(540)
    expect(像素转点(720.5)).toBe(720.5)
  })
})
