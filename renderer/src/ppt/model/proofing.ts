// 本机排版检查：可解释规则，逐条给出位置与建议，不调用模型，也不冒充智能校对。
import type { 文本框, 演示文稿 } from '../deck'

export const 类型清单 = ['重复词', '常见错字', '标点', '空白', '格式', '文字溢出', '缺失资源', '链接'] as const
export type 检查类型 = typeof 类型清单[number]

export interface 检查项 {
  id: string
  类型: 检查类型
  页标识: string
  对象标识?: string
  起始?: number
  长度?: number
  原文: string
  /** 逐字替换文本；空字符串表示删除命中范围 */
  建议: string
  说明: string
}

/** 只修正能确定结果的类型；溢出、缺失资源与链接只报告，不自动改写。 */
export function 可自动修正(项: 检查项): boolean {
  return ['重复词', '常见错字', '标点', '空白'].includes(项.类型)
}

const 常见错字表: Array<[string, string]> = [
  ['按装', '安装'], ['部份', '部分'], ['以经', '已经'], ['做为', '作为'],
  ['记算', '计算'], ['签定', '签订'], ['需知', '须知'], ['既使', '即使'],
  ['凑和', '凑合'], ['陷井', '陷阱'], ['松驰', '松弛'], ['侯选', '候选'],
]

const 半角标点表: Array<[string, string]> = [[',', '，'], ['.', '。'], [';', '；'], [':', '：'], ['?', '？'], ['!', '！'], ['(', '（'], [')', '）']]

const 检查项标识 = (项: Omit<检查项, 'id'>): string =>
  ['检查', 项.页标识, 项.对象标识 ?? '页', 项.类型, 项.起始 ?? -1, 项.原文].join('|')

const 字符宽度 = (字符: string, 字号: number): number =>
  /[\u3000-\u9fff\uff00-\uffef]/.test(字符) ? 字号 : 字号 * 0.55

/** 估算文本排版尺寸，用于溢出提示；不修改文稿。 */
export function 估算文本尺寸(文本: string, 字号: number): { 宽: number; 高: number } {
  const 行列表 = 文本.split('\n')
  const 行宽 = 行列表.map(行 => [...行].reduce((累计, 字符) => 累计 + 字符宽度(字符, 字号), 0))
  return { 宽: Math.max(0, ...行宽), 高: 行列表.length * 字号 * 1.4 }
}

function 文本检查(页标识: string, 框: 文本框, 忽略: Set<string>): 检查项[] {
  const 结果: 检查项[] = []
  const 文本 = 框.text ?? ''
  const 加入 = (项: Omit<检查项, 'id'>) => {
    const 完整 = { ...项, id: 检查项标识(项) }
    if (!忽略.has(完整.id)) 结果.push(完整)
  }
  // 重复词：紧接重复的两到四字词组，命中后一次，删除即可修正
  for (const 匹配 of 文本.matchAll(/(.{2,4})\1/g)) {
    const 词组 = 匹配[1], 起始 = (匹配.index ?? 0) + 词组.length
    加入({ 类型: '重复词', 页标识, 对象标识: 框.id, 起始, 长度: 词组.length, 原文: 词组, 建议: '', 说明: `“${词组}”紧接重复，建议删除后一次` })
  }
  for (const [错, 对] of 常见错字表) {
    for (const 匹配 of 文本.matchAll(new RegExp(错, 'g'))) {
      加入({ 类型: '常见错字', 页标识, 对象标识: 框.id, 起始: 匹配.index ?? 0, 长度: 错.length, 原文: 错, 建议: 对, 说明: `“${错}”应为“${对}”` })
    }
  }
  // 连续标点：同一标点连续出现时只保留一个
  for (const 匹配 of 文本.matchAll(/([，。！？；：、,.;:!?])\1+/g)) {
    加入({ 类型: '标点', 页标识, 对象标识: 框.id, 起始: (匹配.index ?? 0) + 1, 长度: (匹配[0]?.length ?? 2) - 1, 原文: 匹配[0].slice(1), 建议: '', 说明: '标点连续重复，建议只保留一个' })
  }
  // 中文旁的半角标点：前后出现中日韩字符时才提示，避免误伤英文与数字
  for (const 匹配 of 文本.matchAll(/[\u3000-\u9fff]([,.;:!?()])/g)) {
    const 半角 = 匹配[1], 中文 = 半角标点表.find(([原]) => 原 === 半角)?.[1]
    if (!中文) continue
    const 起始 = (匹配.index ?? 0) + 1
    加入({ 类型: '标点', 页标识, 对象标识: 框.id, 起始, 长度: 1, 原文: 半角, 建议: 中文, 说明: `中文内容中的“${半角}”建议使用全角“${中文}”` })
  }
  const 首空白 = 文本.match(/^\s+/)?.[0]
  if (首空白) 加入({ 类型: '空白', 页标识, 对象标识: 框.id, 起始: 0, 长度: 首空白.length, 原文: 首空白, 建议: '', 说明: '文本开头有多余空白' })
  const 尾空白 = 文本.match(/\s+$/)?.[0]
  if (尾空白) 加入({ 类型: '空白', 页标识, 对象标识: 框.id, 起始: 文本.length - 尾空白.length, 长度: 尾空白.length, 原文: 尾空白, 建议: '', 说明: '文本结尾有多余空白' })
  for (const 匹配 of 文本.matchAll(/ {2,}/g)) {
    加入({ 类型: '空白', 页标识, 对象标识: 框.id, 起始: (匹配.index ?? 0) + 1, 长度: 匹配[0].length - 1, 原文: ' '.repeat(匹配[0].length - 1), 建议: '', 说明: '存在连续空格' })
  }
  if (框.字号 < 12) 加入({ 类型: '格式', 页标识, 对象标识: 框.id, 原文: String(框.字号), 建议: '12', 说明: `字号 ${框.字号} 小于 12，投影时可能看不清` })
  else if (框.字号 > 96) 加入({ 类型: '格式', 页标识, 对象标识: 框.id, 原文: String(框.字号), 建议: '96', 说明: `字号 ${框.字号} 超过 96，可能超出页面` })
  const 尺寸 = 估算文本尺寸(文本, 框.字号)
  if (文本.length > 0 && (尺寸.宽 > 框.width + 1 || 尺寸.高 > 框.height + 1)) {
    加入({ 类型: '文字溢出', 页标识, 对象标识: 框.id, 原文: 文本.slice(0, 24), 建议: '', 说明: `估算排版约 ${Math.round(尺寸.宽)}×${Math.round(尺寸.高)}，超出文本框 ${Math.round(框.width)}×${Math.round(框.height)}` })
  }
  for (const 匹配 of 文本.matchAll(/(?:javascript|data|vbscript):[^\s]*/gi)) {
    加入({ 类型: '链接', 页标识, 对象标识: 框.id, 起始: 匹配.index ?? 0, 长度: 匹配[0].length, 原文: 匹配[0], 建议: '', 说明: '链接协议不安全，放映时不会执行；请改用 http 或 https' })
  }
  return 结果
}

/** 执行本机排版检查；忽略集合用于跳过用户已确认的项目。 */
export function 执行本机检查(文稿: 演示文稿, 选项: { 忽略?: Set<string> } = {}): 检查项[] {
  const 忽略 = 选项.忽略 ?? new Set<string>()
  const 结果: 检查项[] = []
  for (const 页 of 文稿.幻灯片列表) {
    for (const 框 of 页.文本框列表) 结果.push(...文本检查(页.id, 框, 忽略))
    for (const 对象 of 页.对象列表 ?? []) {
      const 需要资源 = (对象.类型 === '图片' || 对象.类型 === '媒体') && 对象.资源标识
      if (需要资源 && !Object.prototype.hasOwnProperty.call(文稿.资源索引 ?? {}, 对象.资源标识!)) {
        const 项: Omit<检查项, 'id'> = { 类型: '缺失资源', 页标识: 页.id, 对象标识: 对象.id, 原文: 对象.资源标识 ?? '', 建议: '', 说明: '对象引用的资源不在文稿资源索引中，保存或导出前需要重新插入' }
        if (!忽略.has(检查项标识(项))) 结果.push({ ...项, id: 检查项标识(项) })
      }
    }
  }
  return 结果
}

/** 记录忽略项；只影响检查结果，不写入正文。 */
export function 忽略检查项(集合: Set<string>, 项: 检查项): Set<string> {
  const 结果 = new Set(集合)
  结果.add(项.id)
  return 结果
}

/** 在片段列表中替换字符区间，保留其余片段格式；无片段列表时按整框样式处理。 */
export function 替换文本区间(框: 文本框, 起始: number, 长度: number, 替换: string): 文本框 {
  const 原文 = 框.text ?? ''
  if (!Number.isInteger(起始) || 起始 < 0 || 起始 > 原文.length || !Number.isInteger(长度) || 长度 < 0 || 起始 + 长度 > 原文.length) {
    throw new Error('修正范围超出文本内容')
  }
  const 结束 = 起始 + 长度
  const 新文本 = 原文.slice(0, 起始) + 替换 + 原文.slice(结束)
  const 片段列表 = 框.片段列表
  if (!片段列表 || 片段列表.length === 0) return { ...框, text: 新文本 }
  const 结果: NonNullable<文本框['片段列表']> = []
  let 位置 = 0, 已插入 = false
  for (const 片段 of 片段列表) {
    const 片段起始 = 位置, 片段结束 = 位置 + 片段.文本.length
    位置 = 片段结束
    if (片段结束 <= 起始 || 片段起始 >= 结束) { if (片段.文本.length > 0) 结果.push({ ...片段 }); continue }
    const 前段 = 片段.文本.slice(0, Math.max(0, 起始 - 片段起始))
    const 后段 = 片段.文本.slice(Math.max(0, 结束 - 片段起始))
    if (前段) 结果.push({ ...片段, 文本: 前段 })
    if (!已插入 && 替换) { 结果.push({ ...片段, 文本: 替换 }); 已插入 = true }
    if (后段) 结果.push({ ...片段, 文本: 后段 })
  }
  if (替换 && !已插入) 结果.push({ 文本: 替换 })
  const 合并: NonNullable<文本框['片段列表']> = []
  for (const 片段 of 结果) {
    const 上一段 = 合并[合并.length - 1]
    if (上一段 && 上一段.加粗 === 片段.加粗 && 上一段.斜体 === 片段.斜体 && 上一段.下划线 === 片段.下划线 && 上一段.颜色 === 片段.颜色) 上一段.文本 += 片段.文本
    else 合并.push({ ...片段 })
  }
  return { ...框, text: 合并.map(片段 => 片段.文本).join(''), 片段列表: 合并 }
}

/** 应用一条检查项；类型不支持自动改写时明确拒绝，不做猜测性修改。 */
export function 应用检查修正(文稿: 演示文稿, 项: 检查项): 演示文稿 {
  if (!可自动修正(项)) throw new Error(`“${项.类型}”不能自动修正，请手动处理`)
  if (项.对象标识 === undefined) throw new Error('该检查项没有可修正的文本框')
  const 页 = 文稿.幻灯片列表.find(候选 => 候选.id === 项.页标识)
  if (!页) throw new Error('检查项对应的页面已不存在')
  const 目标 = 页.文本框列表.find(框 => 框.id === 项.对象标识)
  if (!目标) throw new Error('检查项对应的文本框已不存在')
  const 修正后 = 项.类型 === '格式'
    ? { ...目标, 字号: Number(项.建议) }
    : 替换文本区间(目标, 项.起始 ?? 0, 项.长度 ?? 项.原文.length, 项.建议)
  return {
    ...文稿,
    幻灯片列表: 文稿.幻灯片列表.map(候选 => (候选.id === 页.id
      ? { ...候选, 文本框列表: 候选.文本框列表.map(框 => (框.id === 目标.id ? 修正后 : 框)) }
      : 候选)),
  }
}
