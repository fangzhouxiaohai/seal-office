import { describe, expect, it } from 'vitest'
import { 创建演示文稿 } from '../deck'
import { 收集演示资源标识, 校验演示备份资源, 迁移演示文稿 } from './migrations'

const 附件类型 = 'application/vnd.openxmlformats-officedocument.oleObject'
const 图示类型 = 'application/vnd.seal.diagram+json'
const 附件标识 = 'a'.repeat(64)
const 图示标识 = 'b'.repeat(64)

const 带附件与图示的文稿 = () => {
  const 文稿 = 创建演示文稿('附件核验')
  文稿.资源索引 = {
    [附件标识]: { 指纹: 附件标识, 类型: 附件类型, 字节数: 4 },
    [图示标识]: { 指纹: 图示标识, 类型: 图示类型, 字节数: 6 },
  }
  文稿.幻灯片列表[0].对象列表 = [
    { id: '附件对象', 类型: '附件', x: 10, y: 10, width: 60, height: 40, 附件: { 文件名: '报表.xlsx', 显示名称: '报表', 资源标识: 附件标识, 字节数: 4 } },
    { id: '图示对象', 类型: '图示', x: 100, y: 10, width: 200, height: 120, 图示: { 显示文本: '流程', 资源标识: 图示标识, 关系: [] } },
  ]
  return 文稿
}

const 条目 = (标识: string, 类型: string, 数据: string) => ({ 标识, 类型, 数据 })

describe('复审：附件与图示的资源引用必须纳入备份与校验', () => {
  it('收集资源标识包含附件与图示引用的字节', () => {
    const 引用 = 收集演示资源标识(带附件与图示的文稿())
    expect(new Set(引用)).toEqual(new Set([附件标识, 图示标识]))
  })

  it('删除附件对象后不再引用其字节，备份校验不会要求该条目', () => {
    const 文稿 = 带附件与图示的文稿()
    文稿.幻灯片列表[0].对象列表 = (文稿.幻灯片列表[0].对象列表 ?? []).filter(对象 => 对象.类型 !== '附件')
    const 引用 = 收集演示资源标识(文稿)
    expect(引用).not.toContain(附件标识)
    校验演示备份资源([文稿], [条目(图示标识, 图示类型, 'YWJjZGVm')])
  })

  it('备份缺少附件字节时按真实原因拒绝加载', () => {
    const 文稿 = 带附件与图示的文稿()
    expect(() => 校验演示备份资源([文稿], [条目(图示标识, 图示类型, 'YWJjZGVm')]))
      .toThrow(new RegExp(`缺少演示资源字节：${附件标识}`))
  })

  it('备份条目字节数与索引不一致时拒绝加载', () => {
    const 文稿 = 带附件与图示的文稿()
    expect(() => 校验演示备份资源([文稿], [条目(附件标识, 附件类型, 'YWJj'), 条目(图示标识, 图示类型, 'YWJjZGVm')]))
      .toThrow(/字节数不一致/)
  })

  it('备份含未被引用的多余条目时拒绝加载，避免静默夹带', () => {
    const 文稿 = 带附件与图示的文稿()
    expect(() => 校验演示备份资源([文稿], [
      条目(附件标识, 附件类型, 'YWJjZA=='),
      条目(图示标识, 图示类型, 'YWJjZGVm'),
      条目('c'.repeat(64), 附件类型, 'YWJjZA=='),
    ])).toThrow(/未被文稿引用/)
  })

  it('附件对象声明字节数与索引不一致时模型校验拒绝', () => {
    const 文稿 = 带附件与图示的文稿()
    文稿.幻灯片列表[0].对象列表![0].附件 = { 文件名: '报表.xlsx', 显示名称: '报表', 资源标识: 附件标识, 字节数: 99 }
    expect(() => 迁移演示文稿(文稿)).toThrow(/附件数据或资源无效/)
  })
})
