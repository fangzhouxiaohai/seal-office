import { expect, it } from 'vitest'
import { 创建演示文稿, 创建幻灯片, 删除幻灯片, type 演示文稿 } from '../deck'
import { 修复自定义放映引用, 校验自定义放映, 校验放映设置, 计算放映序列, 读取放映设置, 默认放映设置, 创建自定义放映, type 放映设置 } from './show'

function 三页文稿(): 演示文稿 {
  const 文稿 = 创建演示文稿()
  文稿.幻灯片列表 = [创建幻灯片('标题幻灯片', '甲'), 创建幻灯片('标题和内容', '乙'), 创建幻灯片('空白', '丙')]
  文稿.幻灯片列表[1].隐藏 = true
  return 文稿
}

it('默认放映设置为全部页面、使用计时', () => {
  expect(默认放映设置()).toEqual({ 范围: { 类型: '全部' }, 换片方式: '使用计时' })
  expect(读取放映设置(创建演示文稿())).toEqual(默认放映设置())
})

it('全部范围跳过隐藏页，自定义放映按标识顺序并显式包含隐藏页', () => {
  const 文稿 = 三页文稿()
  expect(计算放映序列(文稿)).toEqual([0, 2])
  const 甲 = 创建自定义放映(文稿, '含隐藏页', [文稿.幻灯片列表[0].id, 文稿.幻灯片列表[1].id])
  const 新稿 = { ...文稿, 自定义放映: [甲] }
  expect(计算放映序列(新稿, { 范围: { 类型: '自定义放映', 放映标识: 甲.id }, 换片方式: '使用计时' })).toEqual([0, 1])
})

it('页码范围按 1 起含两端，并跳过隐藏页', () => {
  const 文稿 = 三页文稿()
  const 设置: 放映设置 = { 范围: { 类型: '页码范围', 起始: 1, 结束: 3 }, 换片方式: '使用计时' }
  expect(计算放映序列(文稿, 设置)).toEqual([0, 2])
})

it('全部隐藏、序列为空、自定义放映不存在都拒绝进入放映并说明原因', () => {
  const 全隐藏 = 三页文稿()
  全隐藏.幻灯片列表.forEach(页 => { 页.隐藏 = true })
  expect(() => 计算放映序列(全隐藏)).toThrow('没有可放映')
  const 文稿 = 三页文稿()
  文稿.自定义放映 = [{ id: '空放映', 名称: '空', 页面标识列表: [] }]
  expect(() => 计算放映序列(文稿, { 范围: { 类型: '自定义放映', 放映标识: '空放映' }, 换片方式: '使用计时' })).toThrow('自定义放映')
  expect(() => 计算放映序列(文稿, { 范围: { 类型: '自定义放映', 放映标识: '不存在' }, 换片方式: '使用计时' })).toThrow('不存在')
  expect(() => 计算放映序列(文稿, { 范围: { 类型: '页码范围', 起始: 2, 结束: 1 }, 换片方式: '使用计时' })).toThrow('页码')
})

it('删除页面后修复自定义放映与所选范围引用，未变化时返回同一对象', () => {
  const 文稿 = 三页文稿()
  const [甲页, 乙页, 丙页] = 文稿.幻灯片列表
  const 放映甲 = { id: '放映甲', 名称: '甲', 页面标识列表: [甲页.id, 乙页.id, 丙页.id] }
  const 放映乙 = { id: '放映乙', 名称: '乙', 页面标识列表: [乙页.id] }
  const 带放映: 演示文稿 = { ...文稿, 自定义放映: [放映甲, 放映乙], 放映设置: { 范围: { 类型: '自定义放映', 放映标识: '放映乙' }, 换片方式: '手动' } }
  expect(修复自定义放映引用(带放映)).toBe(带放映)
  const 删除后 = 删除幻灯片(带放映, 乙页.id)
  expect(删除后.自定义放映).toEqual([{ ...放映甲, 页面标识列表: [甲页.id, 丙页.id] }])
  expect(删除后.放映设置).toEqual({ 范围: { 类型: '全部' }, 换片方式: '手动' })
})

it('校验拒绝重复标识、重复页面引用与无效范围', () => {
  const 文稿 = 三页文稿()
  const 页面 = new Set(文稿.幻灯片列表.map(页 => 页.id))
  expect(() => 校验自定义放映([{ id: 'a', 名称: '', 页面标识列表: [] }], 页面)).toThrow('名称')
  expect(() => 校验自定义放映([{ id: 'a', 名称: '甲', 页面标识列表: [] }, { id: 'a', 名称: '乙', 页面标识列表: [] }], 页面)).toThrow('重复')
  expect(() => 校验自定义放映([{ id: 'a', 名称: '甲', 页面标识列表: [文稿.幻灯片列表[0].id, 文稿.幻灯片列表[0].id] }], 页面)).toThrow('重复')
  expect(() => 校验自定义放映([{ id: 'a', 名称: '甲', 页面标识列表: ['不存在'] }], 页面)).toThrow('页面')
  expect(() => 校验放映设置({ 范围: { 类型: '自定义放映' }, 换片方式: '使用计时' })).toThrow('自定义放映')
  expect(() => 校验放映设置({ 范围: { 类型: '全部' }, 换片方式: '自动' })).toThrow('换片方式')
  expect(() => 校验放映设置({ 范围: { 类型: '页码范围', 起始: 0, 结束: 1 }, 换片方式: '手动' })).toThrow('页码')
})
