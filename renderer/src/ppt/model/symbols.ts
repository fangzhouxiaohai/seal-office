export function 搜索符号(关键词: string, 分类?: string): 符号项[] {
  const 词 = (关键词 ?? '').trim().toLowerCase()
  return 符号分类表
    .filter((项) => !分类 || 分类 === '全部' || 项.名称 === 分类)
    .flatMap((项) => 项.符号)
    .filter((项) => !词 || 项.字符.toLowerCase().includes(词) || 项.名称.toLowerCase().includes(词))
}

export function 统计符号数量(): number {
  return 符号分类表.reduce((总数, 项) => 总数 + 项.符号.length, 0)
}
