    const 文稿: 演示文稿 = { ...创建演示文稿(), 主题: 旧主题, 幻灯片列表: [页] }

    const 结果 = 应用主题(文稿, 新主题)

    expect(结果.主题?.标识).toBe('海豹-锐蓝')
    expect(结果.幻灯片列表[0].文本框列表[0].颜色).toBe(新主题.配色.文本1)
    expect(结果.幻灯片列表[0].文本框列表[0].颜色引用).toBe('文本1')
    // 计划 3.2 段末：主题选择不得覆盖用户显式设置的黑色标题
    expect(结果.幻灯片列表[0].文本框列表[1].颜色).toBe('#000000')
    expect(结果.幻灯片列表[0].文本框列表[1].颜色引用).toBeUndefined()
    expect(结果.幻灯片列表[0].文本框列表[2].颜色).toBe('#C00000')
