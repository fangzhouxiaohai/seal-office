import { expect, it } from 'vitest'
import { 创建演示文稿, 创建幻灯片 } from '../deck'
import { 构造演讲者快照 } from './presenterSnapshot'

function 文稿() {
  const 结果 = 创建演示文稿()
  结果.幻灯片列表 = [创建幻灯片('标题幻灯片', '甲'), 创建幻灯片('标题和内容', '乙'), 创建幻灯片('空白', '丙')]
  结果.幻灯片列表[1].备注 = '讲解要点'
  return 结果
}

const 状态 = (索引: number) => ({ 索引, 阶段: '等待' as const, 暂停: false, 活动动画: [], 完成动画: [], 页代次: 1 })

it('按放映顺序给出页码、总页数与下一页标题', () => {
  const 快照 = 构造演讲者快照({ 文稿: 文稿(), 状态: 状态(2), 顺序: [0, 2], 已用毫秒: 5000, 运行中: true })
  expect(快照).toEqual({
    页码: 2, 总页数: 2, 标题: '丙', 备注: '', 下一页标题: null,
    暂停: false, 阶段: '等待', 已用毫秒: 5000, 运行中: true,
  })
})

it('末页下一页为 null，缺少备注时返回空串而不是占位文字', () => {
  const 快照 = 构造演讲者快照({ 文稿: 文稿(), 状态: 状态(1), 顺序: [0, 1, 2], 已用毫秒: -10, 运行中: false })
  expect(快照.下一页标题).toBe('丙')
  expect(快照.备注).toBe('讲解要点')
  expect(快照.已用毫秒).toBe(0)
})

it('索引不在放映顺序中时页码回退为 1，且不猜测下一页', () => {
  const 快照 = 构造演讲者快照({ 文稿: 文稿(), 状态: 状态(1), 顺序: [0, 2], 已用毫秒: 0, 运行中: false })
  expect(快照.页码).toBe(1)
  expect(快照.下一页标题).toBeNull()
})
