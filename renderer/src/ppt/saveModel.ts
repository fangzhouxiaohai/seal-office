// 演示文稿的保存模型：把编辑器模型整理成 pptxCodec 能写入的结构。
// 保存与另存为、以及关闭前的“保存后退出”共用这一份映射，避免多处各写一遍导致字段漂移。
import type { 演示文稿 } from './deck'
import type { 演示资源条目 } from '../ipc/bridge'

/** 富格式保存：位置、字号、颜色、加粗、斜体、对齐、背景色随文件保存，重新打开时由 pptxCodec 还原 */
export function 构建演示保存模型(文稿: 演示文稿, 资源条目: 演示资源条目[]) {
  const 幻灯片模型 = 文稿.幻灯片列表.map((幻灯片) => ({
    id: 幻灯片.id,
    背景色: 幻灯片.背景色,
    过渡效果: 幻灯片.过渡效果,
    动画: 幻灯片.动画,
    切换: 幻灯片.切换, 换片: 幻灯片.换片, 隐藏: 幻灯片.隐藏, 动画序列: 幻灯片.动画序列, 音效: 幻灯片.音效,
    对象列表: 幻灯片.对象列表,
    备注: 幻灯片.备注,
    背景填充: 幻灯片.背景填充,
    背景继承: 幻灯片.背景继承,
    母版标识: 幻灯片.母版标识,
    版式标识: 幻灯片.版式标识,
    主题标识: 幻灯片.主题标识,
    页脚: 幻灯片.页脚,
    文本框: 幻灯片.文本框列表.map((框) => ({
      id: 框.id,
      x: 框.x,
      y: 框.y,
      width: 框.width,
      height: 框.height,
      text: 框.text,
      字号: 框.字号,
      字体: 框.字体,
      加粗: 框.加粗,
      斜体: 框.斜体,
      下划线: 框.下划线,
      颜色: 框.颜色,
      对齐: 框.对齐,
      颜色引用: 框.颜色引用,
      字体引用: 框.字体引用,
      占位符: 框.占位符,
      占位符标识: 框.占位符标识,
      占位符继承: 框.占位符继承,
      片段: (框.片段列表 ?? []).map((片段) => ({
        文本: 片段.文本,
        加粗: 片段.加粗 === true,
        斜体: 片段.斜体 === true,
        下划线: 片段.下划线 === true,
        颜色: 片段.颜色,
      })),
    })),
  }))
  return {
    循环放映: 文稿.循环放映,
    主题: 文稿.主题,
    母版列表: 文稿.母版列表,
    页面尺寸: 文稿.页面尺寸,
    页脚设置: 文稿.页脚设置,
    幻灯片: 幻灯片模型,
    资源条目,
  }
}
