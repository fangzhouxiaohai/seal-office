import type { 文本框, 文本片段 } from './deck'

/** 将 textarea 草稿合入模型；保留未改动文字的字符格式，避免旧片段覆盖新正文。 */
export function 合并文字草稿(框: 文本框, 文本: string): 文本框 {
  if (框.text === 文本) return 框
  if (!框.片段列表?.length) return { ...框, text: 文本 }
  // 先连接原片段再按码点读取，连已有片段恰好落在代理对中间的情况也不会输出孤立代理。
  const 原文 = 框.片段列表.map(片段 => 片段.文本).join('')
  let 片段索引 = 0, 片段起点 = 0, 原偏移 = 0
  const 原字符 = Array.from(原文).map(字符 => {
    while (片段索引 < 框.片段列表!.length - 1 && 原偏移 >= 片段起点 + 框.片段列表![片段索引].文本.length) {
      片段起点 += 框.片段列表![片段索引++].文本.length
    }
    原偏移 += 字符.length
    return { ...框.片段列表![片段索引], 文本: 字符 }
  })
  const 新文字 = Array.from(文本)
  let 前缀 = 0, 后缀 = 0
  while (前缀 < 原字符.length && 前缀 < 新文字.length && 原字符[前缀].文本 === 新文字[前缀]) 前缀++
  while (后缀 < 原字符.length - 前缀 && 后缀 < 新文字.length - 前缀 && 原字符[原字符.length - 1 - 后缀].文本 === 新文字[新文字.length - 1 - 后缀]) 后缀++
  const 样式: 文本片段 = 原字符[Math.max(0, 前缀 - 1)] ?? { 文本: '', 加粗: 框.加粗, 斜体: 框.斜体, 下划线: 框.下划线, 颜色: 框.颜色 }
  const 新字符 = 新文字.slice(前缀, 新文字.length - 后缀).map(字符 => ({ ...样式, 文本: 字符 }))
  const 合并: 文本片段[] = []
  for (const 片段 of [...原字符.slice(0, 前缀), ...新字符, ...(后缀 ? 原字符.slice(-后缀) : [])]) {
    const 上个 = 合并[合并.length - 1]
    if (上个 && 上个.加粗 === 片段.加粗 && 上个.斜体 === 片段.斜体 && 上个.下划线 === 片段.下划线 && 上个.颜色 === 片段.颜色) 上个.文本 += 片段.文本
    else 合并.push({ ...片段 })
  }
  return { ...框, text: 文本, 片段列表: 合并 }
}
