import { describe, expect, it } from 'vitest'
import { 检测文档四角, 透视校正, 增强图像, 缩放尺寸, 整图四角, 求解单应矩阵, 应用单应, 校正输出尺寸, type 像素图, type 点 } from './imageProcessing'

/** 构造深色背景上一张歪斜白纸，纸面四角已知 */
function 合成图(宽: number, 高: number, 角: 点[], 背景 = 30, 纸 = 235): 像素图 {
  const 数据 = new Uint8ClampedArray(宽 * 高 * 4)
  const 在内 = (x: number, y: number) => {
    let 内 = false
    for (let i = 0, j = 角.length - 1; i < 角.length; j = i++) {
      const [a, b] = [角[i], 角[j]]
      if ((a.y > y) !== (b.y > y) && x < (b.x - a.x) * (y - a.y) / (b.y - a.y) + a.x) 内 = !内
    }
    return 内
  }
  for (let y = 0; y < 高; y++) for (let x = 0; x < 宽; x++) {
    const 值 = 在内(x + 0.5, y + 0.5) ? 纸 : 背景, 偏移 = (y * 宽 + x) * 4
    数据[偏移] = 数据[偏移 + 1] = 数据[偏移 + 2] = 值; 数据[偏移 + 3] = 255
  }
  return { 宽, 高, 数据 }
}

const 距离 = (甲: 点, 乙: 点) => Math.hypot(甲.x - 乙.x, 甲.y - 乙.y)

describe('文档四角检测', () => {
  it('在深色背景上的歪斜白纸中找到四角，误差不超过图像长边的 2%', () => {
    const 真实: 点[] = [{ x: 70, y: 40 }, { x: 330, y: 70 }, { x: 300, y: 270 }, { x: 40, y: 230 }]
    const 图 = 合成图(400, 300, 真实)
    const 结果 = 检测文档四角(图)
    expect(结果.已检测).toBe(true)
    结果.四角.forEach((角, 序号) => expect(距离(角, 真实[序号]), `第 ${序号 + 1} 角`).toBeLessThanOrEqual(400 * 0.02))
  })

  it('四角按 左上、右上、右下、左下 顺序返回，与输入纸张方向无关', () => {
    const 真实: 点[] = [{ x: 120, y: 30 }, { x: 360, y: 120 }, { x: 260, y: 280 }, { x: 30, y: 180 }]
    const 结果 = 检测文档四角(合成图(400, 300, 真实))
    expect(结果.已检测).toBe(true)
    结果.四角.forEach((角, 序号) => expect(距离(角, 真实[序号])).toBeLessThanOrEqual(8))
  })

  it('找不到明显文档边缘时退回整图四角，不硬猜', () => {
    const 平图 = 合成图(200, 100, [{ x: -1, y: -1 }, { x: 201, y: -1 }, { x: 201, y: 101 }, { x: -1, y: 101 }])
    const 结果 = 检测文档四角(平图)
    expect(结果.已检测).toBe(false)
    expect(结果.四角).toEqual(整图四角(200, 100))
  })
})

describe('透视校正', () => {
  it('单应矩阵把四个源点精确映射到目标点', () => {
    const 源: 点[] = [{ x: 70, y: 40 }, { x: 330, y: 70 }, { x: 300, y: 270 }, { x: 40, y: 230 }]
    const 目标: 点[] = [{ x: 0, y: 0 }, { x: 259, y: 0 }, { x: 259, y: 199 }, { x: 0, y: 199 }]
    const 矩阵 = 求解单应矩阵(目标, 源)
    目标.forEach((点, 序号) => expect(距离(应用单应(矩阵, 点), 源[序号])).toBeLessThan(1e-6))
  })

  it('输出尺寸取对边长度的较大值，校正后纸面填满输出且背景不混入', () => {
    const 角: 点[] = [{ x: 70, y: 40 }, { x: 330, y: 70 }, { x: 300, y: 270 }, { x: 40, y: 230 }]
    expect(校正输出尺寸(角)).toEqual({ 宽: Math.round(Math.max(距离(角[0], 角[1]), 距离(角[3], 角[2]))), 高: Math.round(Math.max(距离(角[0], 角[3]), 距离(角[1], 角[2]))) })
    const 输出 = 透视校正(合成图(400, 300, 角), 角)
    expect({ 宽: 输出.宽, 高: 输出.高 }).toEqual(校正输出尺寸(角))
    // 去掉 3 像素边框后全部是纸面亮度，说明四边已拉直且没有背景。
    let 最暗 = 255
    for (let y = 3; y < 输出.高 - 3; y++) for (let x = 3; x < 输出.宽 - 3; x++) 最暗 = Math.min(最暗, 输出.数据[(y * 输出.宽 + x) * 4])
    expect(最暗).toBeGreaterThan(200)
  })

  it('校正输出同样受 2400 像素长边限制', () => {
    const 角: 点[] = [{ x: 0, y: 0 }, { x: 5000, y: 0 }, { x: 5000, y: 3000 }, { x: 0, y: 3000 }]
    const 尺寸 = 校正输出尺寸(角)
    expect(Math.max(尺寸.宽, 尺寸.高)).toBe(2400)
    expect(尺寸.高).toBe(1440)
  })
})

describe('尺寸控制与增强', () => {
  it('大图先按最长边不超过 2400 等比缩放，小图不放大', () => {
    expect(缩放尺寸(4000, 3000)).toEqual({ 宽: 2400, 高: 1800, 比例: 0.6 })
    expect(缩放尺寸(3000, 4000)).toEqual({ 宽: 1800, 高: 2400, 比例: 0.6 })
    expect(缩放尺寸(1200, 800)).toEqual({ 宽: 1200, 高: 800, 比例: 1 })
  })

  it('灰度与黑白档输出无彩色像素，黑白档只有纯黑纯白；彩色档保留色相', () => {
    const 图: 像素图 = { 宽: 40, 高: 40, 数据: new Uint8ClampedArray(40 * 40 * 4) }
    for (let 序号 = 0; 序号 < 40 * 40; 序号++) {
      const x = 序号 % 40, 文字 = x >= 10 && x < 14
      图.数据.set(文字 ? [20, 20, 60, 255] : [230, 200, 160, 255], 序号 * 4)
    }
    const 灰 = 增强图像(图, '灰度'), 黑白 = 增强图像(图, '黑白'), 彩 = 增强图像(图, '彩色')
    for (let 偏移 = 0; 偏移 < 灰.数据.length; 偏移 += 4) {
      expect(灰.数据[偏移]).toBe(灰.数据[偏移 + 1]); expect(灰.数据[偏移 + 1]).toBe(灰.数据[偏移 + 2])
      expect([0, 255]).toContain(黑白.数据[偏移])
    }
    // 去阴影后纸面接近白色，文字保持深色。
    expect(黑白.数据[(20 * 40 + 30) * 4]).toBe(255)
    expect(黑白.数据[(20 * 40 + 11) * 4]).toBe(0)
    const 纸 = (20 * 40 + 30) * 4
    expect(彩.数据[纸]).toBeGreaterThan(彩.数据[纸 + 2])
    expect(彩.数据[纸]).toBeGreaterThanOrEqual(230)
  })
})
