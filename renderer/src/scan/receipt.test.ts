import { describe, expect, it } from 'vitest'
import { 解析数字, 生成异常清单, 置信度阈值 } from './validation'
import { 推荐模板, 解析单据文本 } from './receiptParse'
import { 取识别模板 } from './templates'

const 送货单 = 取识别模板('delivery-note')!
const 磅单 = 取识别模板('weighbridge')!

describe('数字解析', () => {
  it('兼容货币符号、千分位、全角数字与单位，非数字返回空', () => {
    expect(解析数字('¥42,000.00')).toBe(42000)
    expect(解析数字('４２００元')).toBe(4200)
    expect(解析数字('35.60 吨')).toBe(35.6)
    expect(解析数字('-12.5')).toBe(-12.5)
    expect(解析数字('13%')).toBe(13)
    expect(解析数字('[无法辨认]')).toBeNull()
    expect(解析数字('')).toBeNull()
    expect(解析数字('十二')).toBeNull()
  })
})

describe('单据文本解析', () => {
  const 文本 = [
    '某某钢材有限公司 送货单',
    '单号：SH20261101    日期：2026-11-01',
    '| 品名 | 规格 | 数量 | 单位 | 单价 | 金额 |',
    '| --- | --- | --- | --- | --- | --- |',
    '| 螺纹钢 | Φ12 | 10 | 吨 | 4200 | 42000 |',
    '| 线材 | Φ8 | 2 | 吨 | 4100 | 8300 |',
    '合计：50300',
  ].join('\n')

  it('按模板把 OCR 文本解析为表头字段与明细行，行列对应', () => {
    const 结果 = 解析单据文本(文本, 送货单, '送货单1.jpg')
    expect(结果.表头.值).toMatchObject({ 单号: 'SH20261101', 日期: '2026-11-01', 合计: '50300' })
    expect(结果.明细.map(行 => 行.值)).toEqual([
      { 品名: '螺纹钢', 规格: 'Φ12', 数量: '10', 单位: '吨', 单价: '4200', 金额: '42000' },
      { 品名: '线材', 规格: 'Φ8', 数量: '2', 单位: '吨', 单价: '4100', 金额: '8300' },
    ])
    expect(结果.模板匹配).toBe(true)
  })

  it('空格分隔的表格同样能按表头对齐', () => {
    const 结果 = 解析单据文本('品名 规格 数量 单位 单价 金额\n螺纹钢 Φ12 10 吨 4200 42000', 送货单, 'a.jpg')
    expect(结果.明细[0].值).toMatchObject({ 品名: '螺纹钢', 数量: '10', 金额: '42000' })
  })

  it('列数与表头不一致或含 [无法辨认] 的单元格置信度低于阈值', () => {
    const 结果 = 解析单据文本('| 品名 | 数量 | 单价 | 金额 |\n| 线材 | [无法辨认] | 4100 | 8200 |\n| 圆钢 | 3 | 4000 |', 送货单, 'a.jpg')
    expect(结果.明细[0].置信度.数量).toBeLessThan(置信度阈值)
    expect(结果.明细[0].置信度.品名).toBeGreaterThanOrEqual(置信度阈值)
    expect(Object.values(结果.明细[1].置信度).every(值 => 值 < 置信度阈值)).toBe(true)
  })

  it('所选模板与文本不符时标记模板不匹配，不输出似是而非的行', () => {
    const 结果 = 解析单据文本(文本, 磅单, 'a.jpg')
    expect(结果.模板匹配).toBe(false)
    expect(结果.明细).toEqual([])
    const 清单 = 生成异常清单(结果, 磅单)
    expect(清单).toHaveLength(1)
    expect(清单[0]).toMatchObject({ 类型: '模板不匹配', 级别: '错误' })
  })

  it('根据字段命中数推荐最可能的单据模板', () => {
    expect(推荐模板(文本)?.标识).toBe('delivery-note')
    expect(推荐模板('车牌号：苏A12345\n毛重：35.6\n皮重：15.2\n净重：20.4')?.标识).toBe('weighbridge')
    expect(推荐模板('今天天气不错')).toBeNull()
  })
})

describe('异常清单', () => {
  it('数量×单价≠金额 时生成数字不符的硬错误，合计与各行之和一致时不报', () => {
    const 清单 = 生成异常清单(解析单据文本([
      '单号：SH1 日期：2026-11-01',
      '| 品名 | 规格 | 数量 | 单位 | 单价 | 金额 |',
      '| 螺纹钢 | Φ12 | 10 | 吨 | 4200 | 42000 |',
      '| 线材 | Φ8 | 2 | 吨 | 4100 | 8300 |',
      '合计：50300',
    ].join('\n'), 送货单, 'a.jpg'), 送货单)
    const 不符 = 清单.filter(项 => 项.类型 === '数字不符')
    expect(不符).toHaveLength(1)
    expect(不符[0]).toMatchObject({ 级别: '错误', 行: 2, 字段: ['数量', '单价', '金额'], 来源: 'a.jpg' })
    expect(不符[0].说明).toBe('数量 × 单价 = 8200，与金额 8300 不符')
  })

  it('合计与各行金额之和相差超过 0.01 时报错，容差内不报', () => {
    const 生成 = (合计: string) => 生成异常清单(解析单据文本(`单号：1 日期：2026-01-01\n| 品名 | 数量 | 单价 | 金额 |\n| A | 3 | 0.1 | 0.3 |\n| B | 1 | 0.2 | 0.2 |\n合计：${合计}`, 送货单, 'a.jpg'), 送货单).filter(项 => 项.类型 === '数字不符')
    expect(生成('0.5')).toEqual([])
    expect(生成('0.505')).toEqual([])
    const 错误 = 生成('0.6')
    expect(错误).toHaveLength(1)
    expect(错误[0]).toMatchObject({ 行: null, 字段: ['金额', '合计'] })
    expect(错误[0].说明).toBe('各行金额之和为 0.5，与合计 0.6 不符')
  })

  it('磅单校验 毛重−皮重=净重', () => {
    const 正确 = 生成异常清单(解析单据文本('车牌号：苏A12345\n货名：煤炭\n毛重：35.60 吨\n皮重：15.20 吨\n净重：20.40 吨\n过磅时间：2026-11-02 08:30', 磅单, 'b.jpg'), 磅单)
    expect(正确).toEqual([])
    const 错误 = 生成异常清单(解析单据文本('车牌号：苏A12345\n货名：煤炭\n毛重：35.60\n皮重：15.20\n净重：21.40\n过磅时间：2026-11-02 08:30', 磅单, 'b.jpg'), 磅单)
    expect(错误.map(项 => 项.说明)).toEqual(['毛重 − 皮重 = 20.4，与净重 21.4 不符'])
  })

  it('必填字段缺失与低置信度字段分别列为必填缺失、字段模糊（待确认）', () => {
    const 清单 = 生成异常清单(解析单据文本('| 品名 | 数量 | 单价 | 金额 |\n| 线材 | [无法辨认] | 4100 | 8200 |', 送货单, 'c.jpg'), 送货单)
    expect(清单.filter(项 => 项.类型 === '必填缺失').map(项 => 项.说明)).toEqual(['缺少必填字段：单号', '缺少必填字段：日期'])
    const 模糊 = 清单.filter(项 => 项.类型 === '字段模糊')
    expect(模糊).toHaveLength(1)
    expect(模糊[0]).toMatchObject({ 级别: '待确认', 行: 1, 字段: ['数量'] })
    expect(模糊[0].说明).toBe('数量识别不清，请对照原图确认')
    // 数量不可读时不能拿它算乘积，避免把不可读误报成数字不符。
    expect(清单.some(项 => 项.类型 === '数字不符')).toBe(false)
  })

  it('数字字段不是有效数字时标为待确认', () => {
    const 清单 = 生成异常清单(解析单据文本('单号：1 日期：2026-01-01\n| 品名 | 数量 | 单价 | 金额 |\n| 线材 | 两 | 4100 | 8200 |', 送货单, 'c.jpg'), 送货单)
    expect(清单.find(项 => 项.类型 === '字段模糊')?.说明).toBe('数量不是有效数字，请对照原图确认')
  })
})

describe('试卷与证件识别', () => {
  it('试卷按题号拆分为题目行，题干续行合并到上一题', async () => {
    const { 解析识别文本 } = await import('./receiptParse')
    const 试卷 = 取识别模板('exam')!
    const 结果 = 解析识别文本('科目：数学 班级：三年二班\n一、选择题\n1. 下列各数中最大的是\nA. 1 B. 2\n2、计算 3+4=\n（3）填空', 试卷, 'p.jpg')
    expect(结果.表头.值).toMatchObject({ 科目: '数学', 班级: '三年二班' })
    expect(结果.明细.map(行 => 行.值)).toEqual([
      { 题号: '一', 题目: '选择题' },
      { 题号: '1', 题目: '下列各数中最大的是\nA. 1 B. 2' },
      { 题号: '2', 题目: '计算 3+4=' },
      { 题号: '3', 题目: '填空' },
    ])
    expect(结果.模板匹配).toBe(true)
  })

  it('证件只抽取表头字段，必填缺失进入异常清单', async () => {
    const { 解析识别文本 } = await import('./receiptParse')
    const 身份证 = 取识别模板('id-card')!
    const 结果 = 解析识别文本('姓名：张三\n性别：男 民族：汉\n住址：某省某市某路 1 号', 身份证, 'id.jpg')
    expect(结果.表头.值).toMatchObject({ 姓名: '张三', 性别: '男', 民族: '汉' })
    expect(生成异常清单(结果, 身份证).map(项 => 项.说明)).toEqual(['缺少必填字段：公民身份号码'])
  })
})
