// 识别模板：扫描工具箱（证件 / 试卷 / 票据）与单据转表格共用的唯一数据源。
// 只放纯数据，不依赖界面与运行环境；字段英文名与 surfaceEnglish271Scan 中的映射保持一致，
// 由 templates.test.ts 校验，避免中英两套名称漂移。

export type 识别模板分类 = '证件' | '试卷' | '单据'
export type 字段类型 = '文本' | '数字' | '日期'

export interface 识别字段 {
  /** 结构化数据中的键，同时作为工作表列名 */
  键: string
  名称: string
  英文名: string
  类型: 字段类型
  必填: boolean
  /** OCR 文本中可能出现的写法，用于定位字段 */
  别名: string[]
}

export type 校验规则 =
  | { 类型: '乘积'; 字段: [string, string, string] } // 字段[0] × 字段[1] ≈ 字段[2]（逐行）
  | { 类型: '差值'; 字段: [string, string, string] } // 字段[0] − 字段[1] ≈ 字段[2]（表头）
  | { 类型: '合计'; 字段: [string, string] } // Σ 明细[字段[0]] ≈ 表头[字段[1]]

export interface 识别模板 {
  标识: string
  分类: 识别模板分类
  行业: string
  名称: string
  英文名: string
  表头字段: 识别字段[]
  明细字段: 识别字段[]
  校验规则: 校验规则[]
}

const 字段 = (键: string, 英文名: string, 类型: 字段类型 = '文本', 必填 = false, 别名: string[] = []): 识别字段 =>
  ({ 键, 名称: 键, 英文名, 类型, 必填, 别名: [键, ...别名] })

