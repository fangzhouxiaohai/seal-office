/** 扫描工具箱可选的全部模板；票据直接引用单据模板对象，不另复制。 */
export const 扫描模板列表: 识别模板[] = [...证件模板列表, 试卷模板, ...单据模板列表]
export const 识别模板列表: 识别模板[] = 扫描模板列表

export function 取识别模板(标识: string): 识别模板 | null {
  return 识别模板列表.find(模板 => 模板.标识 === 标识) ?? null
}

export function 模板全部字段(模板: 识别模板): 识别字段[] {
  return [...模板.表头字段, ...模板.明细字段]
}
