// 识别结果校验：数字校验、低置信度标记与必填缺失，统一生成异常清单。
// 纯函数，扫描工具箱（票据）与单据转表格共用。
import type { 识别模板, 识别字段 } from './templates'

/** 数字比对容差：数量 × 单价、合计、差值统一按 0.01 判断 */
export const 数字容差 = 0.01
/** 低于该值的字段列为“字段模糊，待确认” */
export const 置信度阈值 = 0.6

export interface 解析行 {
  值: Record<string, string>
  /** 0–1；OCR 服务不返回逐字置信度，由文本特征推断（不可辨认标记、列数错位等） */
  置信度: Record<string, number>
}

export interface 单据解析结果 {
  来源: string
  模板标识: string
  表头: 解析行
  明细: 解析行[]
  /** 识别文本中命中的模板字段过少时为 false，此时不输出明细，避免生成似是而非的表格 */
  模板匹配: boolean
  原文: string
}

export type 异常类型 = '字段模糊' | '数字不符' | '必填缺失' | '模板不匹配'
export interface 异常项 {
  类型: 异常类型
  级别: '错误' | '待确认'
  来源: string
  /** 明细行号（从 1 开始）；表头字段或整单问题为 null */
  行: number | null
  字段: string[]
  说明: string
}

const 全角映射 = (文本: string) => 文本.replace(/[０-９]/g, 字 => String.fromCharCode(字.charCodeAt(0) - 0xFF10 + 48))
  .replace(/[．。]/g, '.').replace(/[，,]/g, '').replace(/[－−—]/g, '-').replace(/＋/g, '+')

/** 解析单据上的数字：容忍货币符号、千分位、全角数字、尾随单位与百分号；不是单个数字时返回 null */
export function 解析数字(文本: string | undefined): number | null {
  if (!文本) return null
  const 规范 = 全角映射(文本).replace(/\s+/g, '')
  const 命中 = 规范.match(/^[^\d+\-.]*([+-]?(?:\d+\.?\d*|\.\d+))[^\d]*$/)
  if (!命中) return null
  const 值 = Number(命中[1])
  return Number.isFinite(值) ? 值 : null
}

export const 格式化数字 = (值: number) => String(Number(值.toFixed(2)))
const 相等 = (左: number, 右: number) => Math.abs(左 - 右) <= 数字容差 + 1e-9

function 字段名(模板: 识别模板, 键: string): string {
  return [...模板.表头字段, ...模板.明细字段].find(字段 => 字段.键 === 键)?.名称 ?? 键
}

/** 可参与计算的数字：低置信度或不可解析的值不参与，避免把识别不清误报成数字不符 */
function 可信数字(行: 解析行, 键: string): number | null {
  if ((行.置信度[键] ?? 1) < 置信度阈值) return null
  return 解析数字(行.值[键])
}

function 检查字段(模板: 识别模板, 字段列表: 识别字段[], 行: 解析行, 行号: number | null, 来源: string, 存在列?: Set<string>): 异常项[] {
  const 结果: 异常项[] = []
  for (const 字段 of 字段列表) {
    if (存在列 && !存在列.has(字段.键)) continue
    const 值 = (行.值[字段.键] ?? '').trim(), 置信度 = 行.置信度[字段.键] ?? 1
    if (置信度 < 置信度阈值) {
      结果.push({ 类型: '字段模糊', 级别: '待确认', 来源, 行: 行号, 字段: [字段.键], 说明: `${字段.名称}识别不清，请对照原图确认` })
    } else if (!值) {
      if (字段.必填) 结果.push({ 类型: '必填缺失', 级别: '错误', 来源, 行: 行号, 字段: [字段.键], 说明: `缺少必填字段：${字段.名称}` })
    } else if (字段.类型 === '数字' && 解析数字(值) === null) {
      结果.push({ 类型: '字段模糊', 级别: '待确认', 来源, 行: 行号, 字段: [字段.键], 说明: `${字段.名称}不是有效数字，请对照原图确认` })
    }
  }
  void 模板
  return 结果
}

/** 按模板生成异常清单：模板不匹配时只报这一项，不再逐字段输出 */
export function 生成异常清单(结果: 单据解析结果, 模板: 识别模板): 异常项[] {
  const 来源 = 结果.来源
  if (!结果.模板匹配) {
    return [{ 类型: '模板不匹配', 级别: '错误', 来源, 行: null, 字段: [], 说明: `识别内容与所选模板“${模板.名称}”不符，请更换单据类型后重新识别` }]
  }
  const 清单: 异常项[] = []
  // 表头：未出现的必填字段直接列为缺失。
  清单.push(...检查字段(模板, 模板.表头字段, 结果.表头, null, 来源))
  // 明细：表格中没有该列且为必填时整列缺失；有该列时逐格检查。
  const 存在列 = new Set(结果.明细.flatMap(行 => Object.keys(行.值)))
  if (结果.明细.length) {
    for (const 字段 of 模板.明细字段) if (字段.必填 && !存在列.has(字段.键)) 清单.push({ 类型: '必填缺失', 级别: '错误', 来源, 行: null, 字段: [字段.键], 说明: `缺少必填字段：${字段.名称}` })
    结果.明细.forEach((行, 序号) => 清单.push(...检查字段(模板, 模板.明细字段, 行, 序号 + 1, 来源, 存在列)))
  } else if (模板.明细字段.length) {
    清单.push({ 类型: '必填缺失', 级别: '错误', 来源, 行: null, 字段: [], 说明: '未识别到明细行，请对照原图补录' })
  }
  for (const 规则 of 模板.校验规则) {
    if (规则.类型 === '乘积') {
      const [甲, 乙, 积] = 规则.字段
      结果.明细.forEach((行, 序号) => {
        const 左 = 可信数字(行, 甲), 右 = 可信数字(行, 乙), 实际 = 可信数字(行, 积)
        if (左 === null || 右 === null || 实际 === null || 相等(左 * 右, 实际)) return
        清单.push({ 类型: '数字不符', 级别: '错误', 来源, 行: 序号 + 1, 字段: [甲, 乙, 积], 说明: `${字段名(模板, 甲)} × ${字段名(模板, 乙)} = ${格式化数字(左 * 右)}，与${字段名(模板, 积)} ${格式化数字(实际)} 不符` })
      })
    } else if (规则.类型 === '差值') {
      const [甲, 乙, 差] = 规则.字段
      const 左 = 可信数字(结果.表头, 甲), 右 = 可信数字(结果.表头, 乙), 实际 = 可信数字(结果.表头, 差)
      if (左 !== null && 右 !== null && 实际 !== null && !相等(左 - 右, 实际)) {
        清单.push({ 类型: '数字不符', 级别: '错误', 来源, 行: null, 字段: [甲, 乙, 差], 说明: `${字段名(模板, 甲)} − ${字段名(模板, 乙)} = ${格式化数字(左 - 右)}，与${字段名(模板, 差)} ${格式化数字(实际)} 不符` })
      }
    } else {
      const [列, 总] = 规则.字段
      const 合计 = 可信数字(结果.表头, 总)
      if (合计 === null || !结果.明细.length) continue
      const 各行 = 结果.明细.map(行 => 可信数字(行, 列))
      if (各行.some(值 => 值 === null)) continue
      const 和 = (各行 as number[]).reduce((累计, 值) => 累计 + 值, 0)
      if (!相等(和, 合计)) 清单.push({ 类型: '数字不符', 级别: '错误', 来源, 行: null, 字段: [列, 总], 说明: `各行${字段名(模板, 列)}之和为 ${格式化数字(和)}，与${字段名(模板, 总)} ${格式化数字(合计)} 不符` })
    }
  }
  return 清单
}

/** 某格是否在异常清单中，用于表格高亮 */
export function 异常定位(清单: 异常项[], 来源: string, 行: number | null, 键: string): 异常项 | undefined {
  return 清单.find(项 => 项.来源 === 来源 && 项.行 === 行 && 项.字段.includes(键))
}
