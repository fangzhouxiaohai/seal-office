import { describe, it, expect } from 'vitest'
import { 求值公式, type 取值函数 } from './formula'

/** 以固定表格构造取值函数，键为地址 */
const 构造取值 = (表格: Record<string, string | number>): 取值函数 => (地址: string) =>
  表格[地址] ?? 0

const 表格 = {
  A1: 10,
  A2: 20,
  A3: 30,
  B1: 5,
  B2: 15,
  B3: 25,
  C1: '文本',
}

const 取值 = 构造取值(表格)

describe('公式求值：基础运算', () => {
  it('数字直接返回', () => {
    expect(求值公式('=42', 取值).值).toBe(42)
  })

  it('加减乘除', () => {
    expect(求值公式('=1+2', 取值).值).toBe(3)
    expect(求值公式('=10-4', 取值).值).toBe(6)
    expect(求值公式('=3*4', 取值).值).toBe(12)
    expect(求值公式('=12/4', 取值).值).toBe(3)
  })

  it('乘除优先于加减', () => {
    expect(求值公式('=1+2*3', 取值).值).toBe(7)
    expect(求值公式('=(1+2)*3', 取值).值).toBe(9)
  })

  it('支持乘方', () => {
    expect(求值公式('=2^3', 取值).值).toBe(8)
  })

  it('支持一元负号', () => {
    expect(求值公式('=-5+3', 取值).值).toBe(-2)
  })
})

describe('公式求值：引用与区域', () => {
  it('单元格引用取值', () => {
    expect(求值公式('=A1', 取值).值).toBe(10)
    expect(求值公式('=A1+B1', 取值).值).toBe(15)
  })

  it('引用空单元格按零参与运算', () => {
    expect(求值公式('=Z99+5', 取值).值).toBe(5)
  })

  it('区域引用在函数中展开', () => {
    expect(求值公式('=SUM(A1:A3)', 取值).值).toBe(60)
    expect(求值公式('=SUM(A1:B2)', 取值).值).toBe(50)
  })
})

describe('公式求值：函数', () => {
  it('SUM 求和', () => {
    expect(求值公式('=SUM(A1,B1,5)', 取值).值).toBe(20)
  })

  it('AVERAGE 求平均', () => {
    expect(求值公式('=AVERAGE(A1:A3)', 取值).值).toBe(20)
  })

  it('MAX 与 MIN 求极值', () => {
    expect(求值公式('=MAX(A1:A3)', 取值).值).toBe(30)
    expect(求值公式('=MIN(A1:B1)', 取值).值).toBe(5)
  })

  it('COUNT 统计数值个数，COUNTA 统计非空个数', () => {
    expect(求值公式('=COUNT(A1:C1)', 取值).值).toBe(2)
    expect(求值公式('=COUNTA(A1:C1)', 取值).值).toBe(3)
  })

  it('IF 按条件返回分支', () => {
    expect(求值公式('=IF(A1>5,"大","小")', 取值).值).toBe('大')
    expect(求值公式('=IF(A1>50,"大","小")', 取值).值).toBe('小')
  })

  it('IF 惰性求值：未选分支含错误时仍返回正确分支', () => {
    // 条件为真，选中第二个分支，未选分支的除零错误不应影响结果
    expect(求值公式('=IF(1>0,"对",1/0)', 取值).值).toBe('对')
    // 条件为假，选中第三个分支
    expect(求值公式('=IF(1<0,1/0,"错")', 取值).值).toBe('错')
  })

  it('IF 嵌套与区间引用保持正常工作', () => {
    expect(求值公式('=IF(A1>5,IF(A2>5,"双双大","仅A1大"),"均不大")', 取值).值).toBe('双双大')
    // 外层条件为假，命中第三个分支
    expect(求值公式('=IF(A1>50,IF(A2>5,"双双大","仅A1大"),"均不大")', 取值).值).toBe('均不大')
  })

  it('ROUND 四舍五入', () => {
    expect(求值公式('=ROUND(3.14159,2)', 取值).值).toBe(3.14)
  })

  it('ABS 取绝对值', () => {
    expect(求值公式('=ABS(0-A1)', 取值).值).toBe(10)
  })

  it('CONCAT 连接文本', () => {
    expect(求值公式('=CONCAT("合计",A1)', 取值).值).toBe('合计10')
  })

  it('函数名不区分大小写', () => {
    expect(求值公式('=sum(A1:A3)', 取值).值).toBe(60)
  })
})

describe('公式求值：错误处理', () => {
  it('除以零返回错误', () => {
    const 结果 = 求值公式('=1/0', 取值)
    expect(结果.错误).toBe(true)
    expect(结果.值).toBe('#错误')
  })

  it('未知函数返回错误', () => {
    const 结果 = 求值公式('=UNKNOWN(A1)', 取值)
    expect(结果.错误).toBe(true)
  })

  it('括号不匹配返回错误', () => {
    expect(求值公式('=(1+2', 取值).错误).toBe(true)
  })

  it('函数参数个数错误返回错误', () => {
    expect(求值公式('=ROUND(1)', 取值).错误).toBe(true)
  })

  it('循环引用返回错误', () => {
    const 循环取值: 取值函数 = () => '#循环'
    // 正在求值集合中已包含当前地址时判定为循环引用
    const 正在求值 = new Set<string>(['A1'])
    const 结果 = 求值公式('=A1+1', (地址) => 循环取值(地址), 正在求值, 'A1')
    expect(结果.错误).toBe(true)
  })

  it('非公式内容按文本返回', () => {
    const 结果 = 求值公式('普通文本', 取值)
    expect(结果.错误).toBe(false)
    expect(结果.值).toBe('普通文本')
  })

  it('空公式返回错误', () => {
    expect(求值公式('=', 取值).错误).toBe(true)
  })
})
