describe('单元格读写', () => {
  it('读取未写入的单元格返回空值', () => {
    const 表 = 创建工作表('Sheet1')
    const 单元 = 读取单元格(表, 'A1')
    expect(单元.原始值).toBe('')
    expect(单元.显示值).toBe('')
  })

  it('写入文本后显示值等于原始值', () => {
    const 表 = 写入单元格(创建工作表('Sheet1'), 'A1', '文本内容')
    expect(读取单元格(表, 'A1').显示值).toBe('文本内容')
  })

  it('写入数值后显示值等于原始值', () => {
    const 表 = 写入单元格(创建工作表('Sheet1'), 'A1', '42')
    expect(读取单元格(表, 'A1').显示值).toBe('42')
  })

  it('写入空值会移除该单元格', () => {
    const 表 = 写入单元格(创建工作表('Sheet1'), 'A1', '内容')
    const 清空后 = 写入单元格(表, 'A1', '')
    expect(清空后.单元格.A1).toBeUndefined()
  })

  it('清空单元格保留格式', () => {
    const 表 = 设置格式(创建工作表('Sheet1'), 'A1', { 加粗: true })
    const 带内容 = 写入单元格(表, 'A1', '内容')
    const 清空后 = 清空单元格(带内容, ['A1'])
    expect(读取单元格(清空后, 'A1').原始值).toBe('')
    expect(读取单元格(清空后, 'A1').格式.加粗).toBe(true)
  })
})

describe('公式重算', () => {
  it('写入公式后显示计算结果', () => {
    const 表 = 写入单元格(创建工作表('Sheet1'), 'A1', '=1+2')
    expect(读取单元格(表, 'A1').显示值).toBe('3')
  })

  it('公式引用其它单元格', () => {
    let 表 = 创建工作表('Sheet1')
    表 = 写入单元格(表, 'A1', '10')
    表 = 写入单元格(表, 'B1', '=A1*2')
    expect(读取单元格(表, 'B1').显示值).toBe('20')
  })

  it('公式链按依赖递归求值', () => {
    let 表 = 创建工作表('Sheet1')
    表 = 写入单元格(表, 'A1', '1')
    表 = 写入单元格(表, 'B1', '=A1+1')
    表 = 写入单元格(表, 'C1', '=B1+1')
    expect(读取单元格(表, 'C1').显示值).toBe('3')
  })

  it('修改被引用单元格后引用方同步更新', () => {
    let 表 = 创建工作表('Sheet1')
    表 = 写入单元格(表, 'A1', '10')
    表 = 写入单元格(表, 'B1', '=A1+5')
    expect(读取单元格(表, 'B1').显示值).toBe('15')
    表 = 写入单元格(表, 'A1', '100')
    expect(读取单元格(表, 'B1').显示值).toBe('105')
  })

  it('SUM 函数对区域求和', () => {
    let 表 = 创建工作表('Sheet1')
    表 = 写入单元格(表, 'A1', '1')
    表 = 写入单元格(表, 'A2', '2')
    表 = 写入单元格(表, 'A3', '3')
    表 = 写入单元格(表, 'B1', '=SUM(A1:A3)')
    expect(读取单元格(表, 'B1').显示值).toBe('6')
  })

  it('循环引用显示错误而非静默取值', () => {
    let 表 = 创建工作表('Sheet1')
    表 = 写入单元格(表, 'A1', '=B1')
    表 = 写入单元格(表, 'B1', '=A1')
    const 显示 = 读取单元格(表, 'A1').显示值
    expect(['#错误', '#循环']).toContain(显示)
  })

  it('跨单元格循环引用在重算时正确检测不栈溢出', () => {
    const 表 = 重算工作表({
      ...创建工作表('Sheet1'),
      单元格: {
        A1: { 原始值: '=B1', 显示值: '', 格式: {} },
        B1: { 原始值: '=A1', 显示值: '', 格式: {} },
      },
    })
    const 显示A = 读取单元格(表, 'A1').显示值
    const 显示B = 读取单元格(表, 'B1').显示值
    expect(['#错误', '#循环']).toContain(显示A)
    expect(['#错误', '#循环']).toContain(显示B)
  })

  it('单向引用不存在的单元格返回空值', () => {
    const 表 = 重算工作表({
      ...创建工作表('Sheet1'),
      单元格: {
        A1: { 原始值: '=Z99', 显示值: '', 格式: {} },
      },
    })
    expect(读取单元格(表, 'A1').显示值).toBe('')
  })

  it('公式错误时显示 #错误', () => {
    const 表 = 写入单元格(创建工作表('Sheet1'), 'A1', '=1/0')
    expect(读取单元格(表, 'A1').显示值).toBe('#错误')
  })

  it('重算不修改原始值', () => {
    const 表 = 写入单元格(创建工作表('Sheet1'), 'A1', '=1+2')
    expect(读取单元格(表, 'A1').原始值).toBe('=1+2')
  })
})

describe('数字格式', () => {
  it('百分比格式影响显示值', () => {
    let 表 = 创建工作表('Sheet1')
    表 = 写入单元格(表, 'A1', '0.125')
    表 = 设置格式(表, 'A1', { 数字格式: '百分比' })
    expect(读取单元格(表, 'A1').显示值).toBe('12.50%')
  })

  it('货币格式影响显示值', () => {
    let 表 = 创建工作表('Sheet1')
    表 = 写入单元格(表, 'A1', '1234.5')
    表 = 设置格式(表, 'A1', { 数字格式: '货币' })
    expect(读取单元格(表, 'A1').显示值).toBe('¥1,234.50')
  })

  it('常规格式不改变显示值', () => {
    const 表 = 写入单元格(创建工作表('Sheet1'), 'A1', '1234.5')
    expect(读取单元格(表, 'A1').显示值).toBe('1234.5')
  })

  it('文本内容不受数字格式影响', () => {
    let 表 = 创建工作表('Sheet1')
    表 = 写入单元格(表, 'A1', '说明文字')
    表 = 设置格式(表, 'A1', { 数字格式: '货币' })
    expect(读取单元格(表, 'A1').显示值).toBe('说明文字')
  })
})

describe('格式设置', () => {
  it('按区域批量设置格式', () => {
    const 表 = 设置格式(创建工作表('Sheet1'), 'A1:B2', { 加粗: true })
    ;['A1', 'B1', 'A2', 'B2'].forEach((地址) => {
      expect(读取单元格(表, 地址).格式.加粗).toBe(true)
    })
  })

  it('非法区域不改变工作表', () => {
    const 原表 = 创建工作表('Sheet1')
    expect(设置格式(原表, '随便', { 加粗: true })).toBe(原表)
  })

  it('重复设置格式时后设置的值覆盖前值', () => {
    let 表 = 设置格式(创建工作表('Sheet1'), 'A1', { 加粗: true, 斜体: true })
    表 = 设置格式(表, 'A1', { 加粗: false })
    expect(读取单元格(表, 'A1').格式.加粗).toBe(false)
    expect(读取单元格(表, 'A1').格式.斜体).toBe(true)
  })
})

describe('合并单元格', () => {
  it('切换合并后记录区域', () => {
    const 表 = 切换合并(创建工作表('测试', 5, 5), 'A1:B2')
    expect(表.合并区域).toEqual(['A1:B2'])
  })

  it('对同一区域再次切换即取消合并', () => {
    const 合并后 = 切换合并(创建工作表('测试', 5, 5), 'A1:B2')
    expect(切换合并(合并后, 'A1:B2').合并区域).toEqual([])
  })

  it('单格区域不产生合并', () => {
    const 表 = 创建工作表('测试', 5, 5)
    expect(切换合并(表, 'A1')).toBe(表)
  })

  it('查询合并返回左上角标记与跨度', () => {
    const 表 = 切换合并(创建工作表('测试', 5, 5), 'A1:B2')
    expect(查询合并(表, { 行: 0, 列: 0 })).toEqual({ 是左上角: true, 跨度行: 2, 跨度列: 2 })
    expect(查询合并(表, { 行: 1, 列: 1 })?.是左上角).toBe(false)
    expect(查询合并(表, { 行: 3, 列: 3 })).toBeNull()
  })

  it('与既有合并重叠时移除重叠项', () => {
    const 甲 = 切换合并(创建工作表('测试', 5, 5), 'A1:B2')
    expect(切换合并(甲, 'B2:C3').合并区域).toEqual(['B2:C3'])
  })

  it('不相邻的合并区域可以共存', () => {
    const 甲 = 切换合并(创建工作表('测试', 5, 5), 'A1:B2')
    const 乙 = 切换合并(甲, 'D4:E5')
    expect(乙.合并区域).toEqual(['A1:B2', 'D4:E5'])
  })
})

describe('列宽与行高', () => {
  it('设置指定列的宽度', () => {
    const 表 = 设置列宽(创建工作表('测试', 5, 5), 2, 160)
    expect(表.列宽[2]).toBe(160)
    expect(表.列宽[0]).toBe(默认列宽)
  })

  it('列宽不低于下限', () => {
    const 表 = 设置列宽(创建工作表('测试', 5, 5), 0, 5)
    expect(表.列宽[0]).toBe(最小列宽)
  })

  it('越界列或非法宽度返回原工作表', () => {
    const 原表 = 创建工作表('测试', 5, 5)
    expect(设置列宽(原表, 9, 100)).toBe(原表)
    expect(设置列宽(原表, -1, 100)).toBe(原表)
    expect(设置列宽(原表, 0, Number.NaN)).toBe(原表)
  })

  it('设置行高且不低于下限', () => {
    const 表 = 设置行高(创建工作表('测试', 5, 5), 1, 60)
    expect(表.行高[1]).toBe(60)
    expect(设置行高(表, 1, 2).行高[1]).toBe(最小行高)
  })

  it('不修改原工作表的列宽数组', () => {
    const 原表 = 创建工作表('测试', 5, 5)
    设置列宽(原表, 0, 200)
    expect(原表.列宽[0]).toBe(默认列宽)
  })
})

