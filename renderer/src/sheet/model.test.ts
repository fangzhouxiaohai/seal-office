describe('插入行', () => {
  it('在指定行上方插入空行并下移后续行', () => {
    let 表 = 创建工作表('测试', 3, 2)
    表 = 写入单元格(表, 'A1', '首行')
    表 = 写入单元格(表, 'A2', '次行')
    表 = 写入单元格(表, 'A3', '末行')
    表 = 设置行高(表, 1, 60)
    const 新表 = 插入行(表, 1)
    expect(新表.行数).toBe(4)
    expect(新表.行高).toHaveLength(4)
    expect(新表.行高[1]).toBe(默认行高)
    expect(新表.行高[2]).toBe(60)
    expect(读取单元格(新表, 'A1').显示值).toBe('首行')
    expect(读取单元格(新表, 'A2').显示值).toBe('')
    expect(读取单元格(新表, 'A3').显示值).toBe('次行')
    expect(读取单元格(新表, 'A4').显示值).toBe('末行')
  })

  it('插入行不修改原工作表', () => {
    let 表 = 创建工作表('测试', 3, 2)
    表 = 写入单元格(表, 'A1', '数据')
    const 新表 = 插入行(表, 0)
    expect(表.行数).toBe(3)
    expect(读取单元格(表, 'A1').显示值).toBe('数据')
    expect(新表.行数).toBe(4)
  })

  it('插入点位于边界时仍可插入', () => {
    const 表 = 创建工作表('测试', 2, 2)
    const 新表 = 插入行(表, 2)
    expect(新表.行数).toBe(3)
  })

  it('合并区域在插入点下方时同步下移', () => {
    let 表 = 创建工作表('测试', 5, 5)
    表 = 切换合并(表, 'A3:B4')
    const 新表 = 插入行(表, 2)
    expect(新表.合并区域).toEqual(['A4:B5'])
  })
})

