import { describe, expect, it } from 'vitest'
import { 调整公式引用 } from './structureReferences'
import { 创建工作表, 写入单元格, 插入行, 删除行, 插入列, 删除列, 重算工作簿, 读取单元格 } from './model'
import { 导出为Xlsx } from './sheetExport'

const 行插入 = { 名称: '数据', 轴: '行' as const, 索引: 1, 删除: false }
describe('工作簿结构与公式引用', () => {
  it('插入行调整绝对和混合引用，扩大跨越插入点的范围，并保留文字与其他表', () => {
    expect(调整公式引用('=SUM(A1:$A$3,$B2,B$2)+"A2"+其他!A2+数据!A2', '数据', 行插入))
      .toBe('=SUM(A1:$A$4,$B3,B$3)+"A2"+其他!A2+数据!A3')
    expect(调整公式引用('=A2+数据!A2', '其他', 行插入)).toBe('=A2+数据!A3')
    expect(调整公式引用("='O''Brien'!$A$2+'O''Brien'!A1:A3", '其他', { ...行插入, 名称: "O'Brien" }))
      .toBe("='O''Brien'!$A$3+'O''Brien'!A1:A4")
  })

  it('删除范围端点收缩，删除独立引用变为 REF，列操作保持锚点符号', () => {
    const 删除 = { ...行插入, 删除: true }
    expect(调整公式引用('=A2+SUM(A2:A4,A1:A2,A1:A4,A2:A2)', '数据', 删除))
      .toBe('=#REF!+SUM(A2:A3,A1:A1,A1:A3,#REF!)')
    expect(调整公式引用('=$A$1:$C$2+B2+$C2', '数据', { ...行插入, 轴: '列' })).toBe('=$A$1:$D$2+C2+$D2')
    expect(调整公式引用('=XFD1', '数据', { ...行插入, 轴: '列', 索引: 0 })).toBe('=#REF!')
  })

  it('命名函数、文本、结构化引用、外部簿及三维引用不被局部字符替换破坏', () => {
    const 公式 = '=LOG10(A2)+"A2"&"a""B2"+Table1[[#Headers],[A2]]+[Book.xlsx]数据!A2+\'[Book.xlsx]数据\'!A2+Sheet1:数据!A2+数据!A2'
    expect(调整公式引用(公式, '数据', 行插入)).toBe(公式.replace('LOG10(A2)', 'LOG10(A3)').replace(/\+数据!A2$/, '+数据!A3'))
  })

  it('整行和整列引用只随相应轴变动，带空白的矩形仍按范围收缩', () => {
    expect(调整公式引用('=SUM($A:$C,1:3,A1 : A3)', '数据', 行插入)).toBe('=SUM($A:$C,1:4,A1:A4)')
    expect(调整公式引用('=SUM($A:$C,1:3)', '数据', { ...行插入, 轴: '列' })).toBe('=SUM($A:$D,1:3)')
    expect(调整公式引用('=SUM($B:$B,2:2,A2 : A3)', '数据', { ...行插入, 删除: true })).toBe('=SUM($B:$B,#REF!,A2:A2)')
  })

  it('实际插入/删除在本表及跨表更新一次，连写新单元后仍保留跨表事件，撤销快照无副作用', () => {
    let 数据 = 写入单元格(写入单元格(创建工作表('数据'), 'A1', '2'), 'A2', '3')
    数据 = 写入单元格(数据, 'B1', '=SUM($A$1:$A$2)')
    const 汇总 = 写入单元格(创建工作表('汇总'), 'A1', '=数据!A2+数据!B1')
    const 原簿 = 重算工作簿([数据, 汇总])
    const 插入 = 写入单元格(插入行(原簿[0], 1), 'A2', '7')
    const 新簿 = 重算工作簿([插入, 原簿[1]])
    expect(读取单元格(新簿[0], 'B1')).toMatchObject({ 原始值: '=SUM($A$1:$A$3)', 显示值: '12' })
    expect(读取单元格(新簿[1], 'A1')).toMatchObject({ 原始值: '=数据!A3+数据!B1', 显示值: '15' })
    expect(重算工作簿(新簿)).toBe(新簿)
    expect(读取单元格(原簿[1], 'A1').原始值).toBe('=数据!A2+数据!B1')
    const 删除 = 重算工作簿([删除行(新簿[0], 1), 新簿[1]])
    expect(读取单元格(删除[0], 'B1')).toMatchObject({ 原始值: '=SUM($A$1:$A$2)', 显示值: '5' })
    expect(读取单元格(删除[1], 'A1')).toMatchObject({ 原始值: '=数据!A2+数据!B1', 显示值: '8' })
    expect(重算工作簿([插入列(删除[0], 0), 删除[1]])[1].单元格.A1.原始值).toBe('=数据!B2+数据!C1')
    expect(重算工作簿([删除列(删除[0], 0), 删除[1]])[1].单元格.A1.原始值).toBe('=数据!#REF!+数据!A1')
  })

  it('来源公式和动态数组范围同步迁移，导出不包含临时事件，重复计算不再平移', () => {
    const 表 = 创建工作表('数据')
    表.单元格.A2 = { 原始值: '3', 显示值: '3', 格式: {} }
    表.单元格.A3 = { 原始值: '4', 显示值: '4', 格式: {} }
    表.单元格.B2 = { 原始值: '=_xlfn.UNIQUE(A2:A3)', 显示值: '3', 格式: {}, 公式来源: { 原始值: '=_xlfn.UNIQUE(A2:A3)', 结果: 3, 数组范围: 'B2:B3', 动态数组: true } }
    const 新簿 = 重算工作簿([插入列(插入行(表, 0), 0)])
    expect(新簿[0].单元格.C3.公式来源).toEqual({ 原始值: '=_xlfn.UNIQUE(B3:B4)', 结果: 3, 数组范围: 'C3:C4', 动态数组: true })
    const 单元 = 导出为Xlsx(新簿)!.工作表[0].数据[2][2]
    expect(单元).toMatchObject({ 公式: '_xlfn.UNIQUE(B3:B4)', 结果: 3, 数组范围: 'C3:C4', 动态数组: true })
    expect(Object.getOwnPropertySymbols(新簿[0])).toHaveLength(0)
    expect(重算工作簿(新簿)).toBe(新簿)
  })
})
