import { 字母转列, 列转字母 } from './address'
import type { Sheet, SheetCell } from './model'

type 引用调整 = { 名称: string; 轴: '行' | '列'; 索引: number; 删除: boolean }
type 结构事件 = 引用调整 & { 目标标识: string; 序号: number }
const 结构调整 = Symbol('工作簿结构引用调整')
type 带调整工作表 = Sheet & { [结构调整]?: 结构事件[] }
let 序号 = 0

/** 事件随对象展开传递，不进入 JSON；工作簿重算时统一更新其他表的引用并消费一次。 */
export function 标记结构调整(旧表: Sheet, 新表: Sheet, 轴: '行' | '列', 索引: number, 删除: boolean): Sheet {
  const 事件 = { 名称: 旧表.name, 目标标识: 旧表.id, 轴, 索引, 删除, 序号: ++序号 }
  return { ...更新引用单元格(新表, [事件]), [结构调整]: [...((旧表 as 带调整工作表)[结构调整] ?? []), 事件] } as 带调整工作表
}

const 同名 = (甲: string, 乙: string) => 甲.toUpperCase() === 乙.toUpperCase()
const 引用表达式 = /^((?:'(?:[^']|'')+'|[\p{L}_\\][\p{L}\p{N}_.\\]*)!)?(\$?)([A-Za-z]{1,3})(\$?)([1-9]\d{0,6})(?:\s*:\s*(\$?)([A-Za-z]{1,3})(\$?)([1-9]\d{0,6}))?(?![\p{L}\p{N}_.(!])/u
const 整行列表达式 = /^((?:'(?:[^']|'')+'|[\p{L}_\\][\p{L}\p{N}_.\\]*)!)?(\$?)([A-Za-z]{1,3}|[1-9]\d{0,6})\s*:\s*(\$?)([A-Za-z]{1,3}|[1-9]\d{0,6})(?![\p{L}\p{N}_.(!])/u
const 限定表名 = (限定?: string) => 限定?.startsWith("'") ? 限定.slice(1, -1).replace(/''/g, "'") : 限定

function 调整坐标(开始: number, 结束: number, 事件: 引用调整): [number, number] | null {
  const 正序 = 开始 <= 结束, 小 = Math.min(开始, 结束), 大 = Math.max(开始, 结束), 点 = 事件.索引
  let 新小 = 小, 新大 = 大
  if (!事件.删除) {
    if (点 <= 小) { 新小++; 新大++ }
    else if (点 <= 大) 新大++
  } else if (点 < 小) { 新小--; 新大-- }
  else if (点 <= 大) { if (小 === 大) return null; 新大-- }
  const 上限 = 事件.轴 === '行' ? 1048576 : 16384
  if (新小 < 0 || 新大 >= 上限) return null
  return 正序 ? [新小, 新大] : [新大, 新小]
}

/** 处理 A1 单元格/矩形/整行列引用，字符串、结构化引用、外部簿及 3D 引用保持原文。 */
export function 调整公式引用(公式: string, 当前表名: string, 事件: 引用调整): string {
  let 输出 = '', 位置 = 0
  while (位置 < 公式.length) {
    if (公式[位置] === '"') {
      const 开始 = 位置++
      while (位置 < 公式.length) {
        if (公式[位置++] === '"') { if (公式[位置] === '"') 位置++; else break }
      }
      输出 += 公式.slice(开始, 位置); continue
    }
    if (公式[位置] === '[') {
      const 开始 = 位置++; let 深度 = 1
      while (位置 < 公式.length && 深度) { if (公式[位置] === '[') 深度++; if (公式[位置++] === ']') 深度-- }
      // 外部簿的表名和坐标也不参加本工作簿结构调整。
      const 外部 = /^[^+\-*/(),;=<>\s]*![\$A-Za-z\d:]+/.exec(公式.slice(位置))
      if (外部) 位置 += 外部[0].length
      输出 += 公式.slice(开始, 位置); continue
    }
    // 跳过整个三维引用，避免把最后一个工作表误认为当前表。
    const 三维 = /^(?:'(?:[^']|'')+'|[\p{L}_][\p{L}\p{N}_.]*):(?:'(?:[^']|'')+'|[\p{L}_][\p{L}\p{N}_.]*)![\$A-Za-z\d:]+/u.exec(公式.slice(位置))
    if (三维) { 输出 += 三维[0]; 位置 += 三维[0].length; continue }
    const 整行列 = 整行列表达式.exec(公式.slice(位置))
    if (整行列 && !/[\p{L}\p{N}_.!]/u.test(公式[位置 - 1] ?? '')) {
      const 是列 = /^[A-Za-z]+$/.test(整行列[3]), 结尾是列 = /^[A-Za-z]+$/.test(整行列[5])
      const 首 = 是列 ? 字母转列(整行列[3]) : Number(整行列[3]) - 1
      const 尾 = 是列 ? 字母转列(整行列[5]) : Number(整行列[5]) - 1
      if (是列 !== 结尾是列 || 首 >= (是列 ? 16384 : 1048576) || 尾 >= (是列 ? 16384 : 1048576) ||
        (事件.轴 === '列') !== 是列 || !同名(限定表名(整行列[1]?.slice(0, -1)) ?? 当前表名, 事件.名称)) 输出 += 整行列[0]
      else {
        const 坐标 = 调整坐标(首, 尾, 事件)
        输出 += 坐标 ? `${整行列[1] ?? ''}${整行列[2]}${是列 ? 列转字母(坐标[0]) : 坐标[0] + 1}:${整行列[4]}${是列 ? 列转字母(坐标[1]) : 坐标[1] + 1}` : `${整行列[1] ?? ''}#REF!`
      }
      位置 += 整行列[0].length; continue
    }
    const 匹配 = 引用表达式.exec(公式.slice(位置))
    if (!匹配 || /[\p{L}\p{N}_.!]/u.test(公式[位置 - 1] ?? '')) { 输出 += 公式[位置++]; continue }
    const 限定 = 匹配[1]?.slice(0, -1)
    const 表名 = 限定表名(限定)
    const 起列 = 字母转列(匹配[3]), 起行 = Number(匹配[5]) - 1
    const 终列 = 匹配[7] ? 字母转列(匹配[7]) : 起列, 终行 = 匹配[9] ? Number(匹配[9]) - 1 : 起行
    if (起列 >= 16384 || 终列 >= 16384 || 起行 >= 1048576 || 终行 >= 1048576 || !同名(表名 ?? 当前表名, 事件.名称)) 输出 += 匹配[0]
    else {
      const 调整后 = 调整坐标(事件.轴 === '行' ? 起行 : 起列, 事件.轴 === '行' ? 终行 : 终列, 事件)
      if (!调整后) 输出 += `${匹配[1] ?? ''}#REF!`
      else {
        const 首 = `${匹配[2]}${事件.轴 === '列' ? 列转字母(调整后[0]) : 匹配[3]}${匹配[4]}${事件.轴 === '行' ? 调整后[0] + 1 : 匹配[5]}`
        const 尾 = 匹配[7] ? `:${匹配[6]}${事件.轴 === '列' ? 列转字母(调整后[1]) : 匹配[7]}${匹配[8]}${事件.轴 === '行' ? 调整后[1] + 1 : 匹配[9]}` : ''
        输出 += `${匹配[1] ?? ''}${首}${尾}`
      }
    }
    位置 += 匹配[0].length
  }
  return 输出
}

function 更新引用单元格(表: Sheet, 事件列表: readonly 引用调整[]): Sheet {
    let 新单元格: Record<string, SheetCell> | undefined
    Object.entries(表.单元格).forEach(([地址, 单元]) => {
      if (单元.值类型 === '文本' || !单元.原始值.startsWith('=')) return
      let 原始值 = 单元.原始值, 来源 = 单元.公式来源
      for (const 事件 of 事件列表) {
        原始值 = 调整公式引用(原始值, 表.name, 事件)
        if (来源?.原始值 === 单元.原始值 && 来源.数组范围 && 同名(表.name, 事件.名称)) {
          const 数组范围 = 调整公式引用(来源.数组范围, 表.name, 事件)
          if (数组范围 !== 来源.数组范围) 来源 = { ...来源, 数组范围 }
        }
      }
      if (来源?.原始值 === 单元.原始值 && 原始值 !== 单元.原始值) 来源 = { ...来源, 原始值 }
      if (原始值 !== 单元.原始值 || 来源 !== 单元.公式来源) {
        新单元格 ??= { ...表.单元格 }
        新单元格[地址] = { ...单元, 原始值, ...(来源 ? { 公式来源: 来源 } : {}) }
      }
    })
    return 新单元格 ? { ...表, 单元格: 新单元格 } : 表
}

export function 应用结构引用调整(工作簿: readonly Sheet[]): Sheet[] {
  const 事件列表 = 工作簿.flatMap(表 => (表 as 带调整工作表)[结构调整] ?? []).sort((甲, 乙) => 甲.序号 - 乙.序号)
  if (!事件列表.length) return 工作簿 as Sheet[]
  return 工作簿.map(表 => {
    const { [结构调整]: _已消费, ...清理表 } = 表 as 带调整工作表
    return 更新引用单元格(_已消费 ? 清理表 : 表, 事件列表.filter(事件 => 事件.目标标识 !== 表.id))
  })
}
