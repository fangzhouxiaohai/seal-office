import { afterEach, describe, expect, it, vi } from 'vitest'
import { dispatchShortcut, findShortcutConflicts, normalizeShortcut, readShortcutOverrides, resetShortcutOverrides, saveShortcutOverrides, shortcutDefinitions, shortcutFromEvent, SHORTCUT_STORAGE_KEY } from './shortcuts'

afterEach(() => { localStorage.removeItem(SHORTCUT_STORAGE_KEY); vi.restoreAllMocks(); document.body.innerHTML = '' })
const key = (value: string, init: KeyboardEventInit = {}) => new KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true, ...init })

describe('统一快捷键配置与调度', () => {
  it('全部默认键位在各自文档范围内无冲突，并规范化修改键和键名', () => {
    expect(findShortcutConflicts({})).toEqual([])
    expect(shortcutDefinitions.length).toBeGreaterThan(70)
    expect(normalizeShortcut('shift + cmd + z')).toBe('Ctrl+Shift+Z')
    expect(normalizeShortcut('Ctrl+Ctrl+S')).toBeNull()
    expect(normalizeShortcut('s')).toBeNull()
    expect(normalizeShortcut('Alt+F4')).toBeNull()
    expect(normalizeShortcut('Ctrl+Tab')).toBeNull()
    expect(normalizeShortcut('Ctrl+Alt+Delete')).toBeNull()
  })
  it('跨文档可共用键位，同一范围发现默认和自定义冲突，冲突配置不能写入', () => {
    const overrides = { 'word:font.bold': ['Ctrl+I'] }
    expect(findShortcutConflicts(overrides)).toEqual([{ scope: 'word', shortcut: 'Ctrl+I', commands: ['font.bold', 'font.italic'] }])
    expect(() => saveShortcutOverrides(overrides)).toThrow('冲突')
    expect(localStorage.getItem(SHORTCUT_STORAGE_KEY)).toBeNull()
  })
  it('持久保存改绑和禁用；旧键位停止触发，重载设置及恢复默认生效', () => {
    saveShortcutOverrides({ 'word:font.bold': ['Ctrl+Alt+B'], 'word:font.italic': [] })
    expect(readShortcutOverrides()).toEqual({ 'word:font.bold': ['Ctrl+Alt+B'], 'word:font.italic': [] })
    const execute = vi.fn()
    const removedBold = key('b', { ctrlKey: true })
    expect(dispatchShortcut(removedBold, 'word', execute)).toBe(true)
    expect(removedBold.defaultPrevented).toBe(true)
    expect(dispatchShortcut(key('i', { ctrlKey: true }), 'word', execute)).toBe(true)
    expect(execute).not.toHaveBeenCalled()
    const remapped = key('b', { ctrlKey: true, altKey: true })
    expect(dispatchShortcut(remapped, 'word', execute)).toBe(true)
    expect(remapped.defaultPrevented).toBe(true)
    expect(execute).toHaveBeenCalledWith('font.bold')
    resetShortcutOverrides()
    expect(dispatchShortcut(key('b', { ctrlKey: true }), 'word', execute)).toBe(true)
  })
  it('正确区分 Ctrl+Z / Ctrl+Shift+Z 与 F5 / Shift+F5，接受 Mac 和 Shift 标点', () => {
    const execute = vi.fn()
    dispatchShortcut(key('z', { ctrlKey: true, shiftKey: true }), 'word', execute)
    expect(execute).toHaveBeenLastCalledWith('edit.redo')
    dispatchShortcut(key('F5', { shiftKey: true }), 'ppt', execute)
    expect(execute).toHaveBeenLastCalledWith('slideshow.current')
    dispatchShortcut(key('s', { metaKey: true }), 'sheet', execute)
    expect(execute).toHaveBeenLastCalledWith('file.save')
    expect(shortcutFromEvent(key('>', { ctrlKey: true, shiftKey: true }))).toBe('Ctrl+Shift+.')
    expect(dispatchShortcut(key('b', { ctrlKey: true, shiftKey: true }), 'word', execute)).toBe(false)
  })
  it('输入法、AltGraph、已经消费的事件及长按保存不触发命令', () => {
    const execute = vi.fn()
    expect(dispatchShortcut(key('b', { ctrlKey: true, isComposing: true }), 'word', execute)).toBe(false)
    expect(dispatchShortcut(key('b', { ctrlKey: true, keyCode: 229 }), 'word', execute)).toBe(false)
    const graph = key('b', { ctrlKey: true, altKey: true })
    vi.spyOn(graph, 'getModifierState').mockImplementation(name => name === 'AltGraph')
    expect(dispatchShortcut(graph, 'word', execute, { 'word:font.bold': ['Ctrl+Alt+B'] })).toBe(false)
    const consumed = key('b', { ctrlKey: true }); consumed.preventDefault()
    expect(dispatchShortcut(consumed, 'word', execute)).toBe(false)
    expect(dispatchShortcut(key('s', { ctrlKey: true, repeat: true }), 'word', execute)).toBe(true)
    expect(execute).not.toHaveBeenCalled()
  })
  it('普通输入框保留本地撤销和文字格式行为，正文编辑区允许命令，弹窗不泄漏快捷键', () => {
    const input = document.createElement('input')
    const editor = document.createElement('div'); editor.className = 'wps-editor-canvas__content'; editor.setAttribute('contenteditable', 'true')
    const dialog = document.createElement('div'); dialog.setAttribute('role', 'dialog'); const textarea = document.createElement('textarea'); dialog.append(textarea)
    document.body.append(input, editor, dialog)
    const execute = vi.fn()
    const listener = (event: KeyboardEvent) => { dispatchShortcut(event, 'word', execute) }
    document.addEventListener('keydown', listener)
    try {
      const undo = key('z', { ctrlKey: true }); input.dispatchEvent(undo)
      expect(undo.defaultPrevented).toBe(false)
      expect(execute).not.toHaveBeenCalled()
      input.dispatchEvent(key('s', { ctrlKey: true }))
      expect(execute).toHaveBeenLastCalledWith('file.save')
      editor.dispatchEvent(key('b', { ctrlKey: true }))
      expect(execute).toHaveBeenLastCalledWith('font.bold')
      execute.mockClear(); textarea.dispatchEvent(key('s', { ctrlKey: true }))
      expect(execute).not.toHaveBeenCalled()
    } finally { document.removeEventListener('keydown', listener) }
  })
  it('未实现于当前处理器的命令不消费事件，损坏或无法读取的配置安全回退默认', () => {
    const print = key('p', { ctrlKey: true })
    expect(dispatchShortcut(print, 'pdf', () => false)).toBe(false)
    expect(print.defaultPrevented).toBe(false)
    localStorage.setItem(SHORTCUT_STORAGE_KEY, '{invalid')
    expect(() => readShortcutOverrides()).toThrow()
    const execute = vi.fn()
    expect(dispatchShortcut(key('s', { ctrlKey: true }), 'word', execute)).toBe(true)
    expect(execute).toHaveBeenCalledWith('file.save')
    const set = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('storage unavailable') })
    expect(() => saveShortcutOverrides({ 'word:font.bold': [] })).toThrow('storage unavailable')
    set.mockRestore()
  })
  it('行距键传递明确参数，数字 Shift 键位按物理数字匹配', () => {
    const execute=vi.fn()
    dispatchShortcut(key('2',{ctrlKey:true}),'word',execute)
    expect(execute).toHaveBeenLastCalledWith('para.lineSpacing','2')
    dispatchShortcut(key('%',{ctrlKey:true,shiftKey:true}),'sheet',execute)
    expect(execute).toHaveBeenLastCalledWith('number.percent')
    dispatchShortcut(key('*',{ctrlKey:true,shiftKey:true}),'word',execute)
    expect(execute).toHaveBeenLastCalledWith('view.paragraphMark')
  })
  it('演示正文格式可处理，文本选择与普通输入框的按键保持本地行为', () => {
    const textarea=document.createElement('textarea');textarea.dataset.sealShortcutEditor='ppt';document.body.append(textarea)
    const execute=vi.fn(),listener=(event:KeyboardEvent)=>{dispatchShortcut(event,'ppt',execute)}
    document.addEventListener('keydown',listener)
    try{
      textarea.dispatchEvent(key('b',{ctrlKey:true}));expect(execute).toHaveBeenCalledWith('text.bold')
      execute.mockClear();const select=key('a',{ctrlKey:true});textarea.dispatchEvent(select)
      expect(execute).not.toHaveBeenCalled();expect(select.defaultPrevented).toBe(false)
    }finally{document.removeEventListener('keydown',listener)}
  })
  it('放映单键仅在放映范围生效，可改绑或禁用，Esc 与 Tab 控件行为独立',()=>{
    const execute=vi.fn()
    expect(dispatchShortcut(key('b'),'ppt',execute)).toBe(false)
    expect(dispatchShortcut(key('b'),'slideshow',execute)).toBe(true)
    expect(execute).toHaveBeenLastCalledWith('show.black')
    saveShortcutOverrides({'slideshow:show.black':['K'],'slideshow:show.ink':[]})
    execute.mockClear();dispatchShortcut(key('b'),'slideshow',execute);dispatchShortcut(key('i'),'slideshow',execute)
    expect(execute).not.toHaveBeenCalled()
    dispatchShortcut(key('k'),'slideshow',execute);expect(execute).toHaveBeenCalledWith('show.black')
    dispatchShortcut(key('Escape'),'slideshow',execute);expect(execute).toHaveBeenLastCalledWith('show.exit')
    expect(dispatchShortcut(key('Tab'),'slideshow',execute)).toBe(false)
  })
})
