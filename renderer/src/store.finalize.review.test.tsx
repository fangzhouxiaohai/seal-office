import { act, render } from '@testing-library/react'
import { expect, it } from 'vitest'
import { AppProvider, useAppStore, type AppState } from './store'
import { 创建演示文稿, type 演示文稿 } from './ppt/deck'

const 准备定稿文稿 = () => {
  let 状态!: AppState
  const 探针 = () => { 状态 = useAppStore(); return null }
  render(<AppProvider><探针 /></AppProvider>)
  const 文稿 = 创建演示文稿('定稿核验')
  文稿.定稿 = { 时间: '2026-10-06T10:30:00.000Z', 标记人: '张三' }
  act(() => 状态.createDoc('ppt', 文稿, { 路径: 'C:\\资料\\定稿核验.pptx' }))
  return { 状态: () => 状态, 标识: () => 状态.activeDocumentId!, 原文稿: 文稿 }
}

const 改正文 = (文稿: 演示文稿, 文本: string): 演示文稿 => ({
  ...文稿,
  幻灯片列表: 文稿.幻灯片列表.map(页 => ({ ...页, 文本框列表: 页.文本框列表.map((框, 序号) => 序号 === 0 ? { ...框, text: 文本 } : 框) })),
})

it('定稿文稿的正文不能通过直接写库绕过只读（保留定稿标记）', () => {
  const { 状态, 标识, 原文稿 } = 准备定稿文稿()
  const 当前 = 状态().演示文档模型[标识()]
  act(() => 状态().更新演示文档模型(标识(), 改正文(当前, '助手改写正文')))
  expect(状态().演示文档模型[标识()].幻灯片列表[0].文本框列表[0].text).toBe(原文稿.幻灯片列表[0].文本框列表[0].text)
  expect(状态().演示文档模型[标识()].定稿).toEqual({ 时间: '2026-10-06T10:30:00.000Z', 标记人: '张三' })
})

it('定稿文稿不能在改写正文的同时静默丢掉定稿标记', () => {
  const { 状态, 标识, 原文稿 } = 准备定稿文稿()
  const 当前 = 状态().演示文档模型[标识()]
  const { 定稿: _定稿, ...无标记 } = 当前
  act(() => 状态().更新演示文档模型(标识(), 改正文(无标记 as 演示文稿, '顺手解除并改写')))
  expect(状态().演示文档模型[标识()].幻灯片列表[0].文本框列表[0].text).toBe(原文稿.幻灯片列表[0].文本框列表[0].text)
  expect(状态().演示文档模型[标识()].定稿).toBeTruthy()
})

it('只解除定稿仍然放行，解除后可以正常修改正文', () => {
  const { 状态, 标识 } = 准备定稿文稿()
  const 当前 = 状态().演示文档模型[标识()]
  const { 定稿: _定稿, ...解除后 } = 当前
  act(() => 状态().更新演示文档模型(标识(), 解除后 as 演示文稿))
  expect(状态().演示文档模型[标识()].定稿).toBeUndefined()
  act(() => 状态().更新演示文档模型(标识(), 改正文(状态().演示文档模型[标识()], '解除后改写')))
  expect(状态().演示文档模型[标识()].幻灯片列表[0].文本框列表[0].text).toBe('解除后改写')
})

it('定稿状态下翻页与改名不触发表冻结，正文保持只读', () => {
  const { 状态, 标识 } = 准备定稿文稿()
  act(() => 状态().更新演示文档模型(标识(), { ...状态().演示文档模型[标识()], 当前索引: 0 }))
  expect(状态().演示文档模型[标识()].定稿).toBeTruthy()
})
