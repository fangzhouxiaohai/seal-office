import { describe, expect, it } from 'vitest'
import { 初始下载状态, 更新下载界面, 应用下载进度, 应跳过自动检查, type 下载进度 } from './downloadState'

const 进度 = (阶段: 下载进度['阶段'], 额外: Partial<下载进度> = {}): 下载进度 => ({ 阶段, 已下载: 0, 总大小: 100, 版本: '2.7.3', 任务标识: 'a', ...额外 })
describe('安装包下载状态', () => {
  it('只展示真实进度，后台和前台切换不改变下载数据', () => {
    const 状态 = 应用下载进度(初始下载状态, 进度('下载中', { 已下载: 25 }))
    const 后台 = 更新下载界面(状态, '后台')
    expect(后台.进度?.已下载).toBe(25)
    expect(更新下载界面(后台, '前台').界面).toBe('前台')
  })
  it('不允许旧任务事件覆盖当前任务', () => {
    const 状态 = 应用下载进度(初始下载状态, 进度('下载中'))
    expect(应用下载进度(状态, 进度('已就绪', { 任务标识: 'old' }))).toEqual(状态)
  })
  it('仅下载、校验、待安装或安装中跳过自动检查', () => {
    for (const 阶段 of ['下载中', '校验中', '已就绪', '安装中'] as const) expect(应跳过自动检查(应用下载进度(初始下载状态, 进度(阶段)))).toBe(true)
    for (const 阶段 of ['空闲', '已取消', '失败'] as const) expect(应跳过自动检查(应用下载进度(初始下载状态, 进度(阶段)))).toBe(false)
    expect(应跳过自动检查(更新下载界面(初始下载状态, '前台'))).toBe(true)
  })
  it('拒绝错误字节、未知阶段与无版本的待安装状态', () => {
    expect(() => 应用下载进度(初始下载状态, 进度('下载中', { 已下载: -1 }))).toThrow()
    expect(() => 应用下载进度(初始下载状态, 进度('已就绪', { 版本: undefined }))).toThrow()
    expect(() => 应用下载进度(初始下载状态, { ...进度('下载中'), 阶段: '其他' } as unknown as 下载进度)).toThrow()
  })
})
