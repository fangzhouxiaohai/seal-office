const fs = require('node:fs'), path = require('node:path'), { parse } = require('@babel/parser')
const root = path.join(__dirname, '..')
const command = /^[a-z][\w-]*(?:\.[A-Za-z][\w-]*)+$/
const sources = {
  word: ['renderer/src/editor/commands.ts'],
  sheet: ['renderer/src/sheet/sheetCommands.ts'],
  ppt: ['renderer/src/ppt/pptCommands.ts', ...fs.readdirSync(path.join(root, 'renderer/src/ppt/commands')).filter(name => name.endsWith('.ts') && !name.includes('.test.')).map(name => 'renderer/src/ppt/commands/' + name)],
}
const catalog = {}
for (const [scope, files] of Object.entries(sources)) {
  const entries = new Map(), excluded = new Set()
  const literal = node => node?.type === 'StringLiteral' ? node.value : null
  const add = (id, label) => { if (id && label && (command.test(id) || /^design\.size\.(16:9|4:3)$/.test(id))) entries.set(id, label) }
  for (const file of files) {
    const tree = parse(fs.readFileSync(path.join(root, file), 'utf8'), { sourceType: 'module', plugins: ['typescript'] })
    const visit = node => {
      if (node.type === 'ArrayExpression') add(literal(node.elements[0]), literal(node.elements[1]))
      if (node.type === 'CallExpression') {
        const id = literal(node.arguments[0]), label = literal(node.arguments[1]), name = node.callee.name ?? ''
        if (/未实现|指引命令/.test(name)) { if (id) excluded.add(id) }
        else add(id, label)
      }
      if (node.type === 'ObjectExpression') {
        const props = Object.fromEntries(node.properties.filter(property => property.type === 'ObjectProperty').map(property => [property.key.name ?? property.key.value, literal(property.value)]))
        add(props.id, props.label)
      }
      for (const [key, value] of Object.entries(node)) {
        if (['loc','start','end','comments','tokens'].includes(key)) continue
        if (Array.isArray(value)) for (const child of value) { if (child?.type) visit(child) }
        else if (value?.type) visit(value)
      }
    }
    visit(tree)
  }
  if (scope === 'word') for (const [id, label] of [['style.body','正文'],['style.heading1','标题 1'],['style.heading2','标题 2'],['style.heading3','标题 3']]) add(id,label)
  if (scope === 'sheet') { add('data.sortAsc','升序');add('data.sortDesc','降序') }
  if (scope === 'sheet') excluded.add('cell.format')
  catalog[scope] = [...entries].filter(([id]) => !excluded.has(id)).sort(([a],[b]) => a.localeCompare(b))
}
const destination = path.join(root, 'renderer/src/shortcuts/commandCatalog.ts')
const output = '// Generated by scripts/generate-shortcut-catalog.cjs from implemented command registries.\nexport const commandCatalog = ' + JSON.stringify(catalog, null, 2) + ' as const\n'
if (process.argv.includes('--check')) { if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('快捷键命令目录已过期，请运行 node scripts/generate-shortcut-catalog.cjs') }
else fs.writeFileSync(destination, output)
console.log(Object.fromEntries(Object.entries(catalog).map(([scope, entries]) => [scope, entries.length])))
