// 验证独立 PHP-FPM 配置不会复用其他站点的主池。
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const conf = () => fs.readFileSync(path.join(root, 'server/deploy/seal-admin-php-fpm.conf'), 'utf8')
const unit = () => fs.readFileSync(path.join(root, 'server/deploy/seal-admin-php.service'), 'utf8')
const nginx = () => fs.readFileSync(path.join(root, 'server/deploy/nginx-tpadmin.conf'), 'utf8')

test('独立 FPM 池只监听专用套接字，限制权限并覆盖最长业务时长', () => {
  const text = conf()
  assert.match(text, /^user\s*=\s*www\s*$/m)
  assert.match(text, /^group\s*=\s*www\s*$/m)
  assert.match(text, /^listen\s*=\s*\/run\/seal-admin-php\/fpm\.sock\s*$/m)
  assert.match(text, /^listen\.owner\s*=\s*www\s*$/m)
  assert.match(text, /^listen\.group\s*=\s*www\s*$/m)
  assert.match(text, /^listen\.mode\s*=\s*0660\s*$/m)
  assert.ok(Number(text.match(/^request_terminate_timeout\s*=\s*(\d+)\s*$/m)?.[1]) >= 210)
  assert.match(text, /^clear_env\s*=\s*yes\s*$/m)
  assert.doesNotMatch(text, /php-cgi-82\.sock|127\.0\.0\.1:\d+/)
})

test('独立服务运行指定 PHP 8.2 和专用配置，运行目录归属受限', () => {
  const text = unit()
  assert.match(text, /^RuntimeDirectory=seal-admin-php\s*$/m)
  assert.match(text, /^RuntimeDirectoryMode=0750\s*$/m)
  assert.match(text, /^Group=www\s*$/m)
  assert.match(text, /^ExecStart=\/www\/server\/php\/82\/sbin\/php-fpm -F -y \/www\/wwwroot\/seal\.xingmasoft\.com\/seal-admin-php\/fpm\.conf\s*$/m)
  assert.doesNotMatch(text, /php-fpm\.conf|php-cgi-82\.sock/)
})

test('新静态路径与 PHP 桥接使用独立 location，不覆盖旧资源和站点入口', () => {
  const text = nginx()
  assert.match(text, /location\s+\^~\s+\/admin-assets\/\s*\{/)
  assert.match(text, /alias\s+\/www\/wwwroot\/seal\.xingmasoft\.com\/admin\//)
  assert.match(text, /location\s+\^~\s+\/seal-admin\/\s*\{/)
  assert.match(text, /fastcgi_pass\s+unix:\/run\/seal-admin-php\/fpm\.sock/)
  assert.match(text, /fastcgi_param\s+SCRIPT_FILENAME\s+\/www\/wwwroot\/seal\.xingmasoft\.com\/seal-admin-php\/current\/public\/index\.php/)
  assert.match(text, /fastcgi_param\s+HTTP_AUTHORIZATION\s+\$http_authorization/)
  assert.match(text, /client_max_body_size\s+2m/)
  assert.match(text, /fastcgi_read_timeout\s+210s/)
  assert.match(text, /fastcgi_cache\s+off/)
  assert.doesNotMatch(text, /location\s+(?:\^~\s+)?\/assets\/|location\s+\/\s*\{/)
})
