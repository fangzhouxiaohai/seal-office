const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const yaml = require('js-yaml')

test('通用包复测仅使用固定产物、只读权限和两种原生架构', () => {
  const file = path.join(__dirname, '../.github/workflows/macos-universal-retest.yml')
  const flow = yaml.load(fs.readFileSync(file, 'utf8'))
  assert.deepEqual(flow.permissions, { contents: 'read', actions: 'read' })
  const job = flow.jobs.verify
  assert.deepEqual(job.strategy.matrix.include.map(item => [item.runner, item.arch]), [['macos-15', 'arm64'], ['macos-15-intel', 'x86_64']])
  assert.ok(job['timeout-minutes'] <= 60)
  assert.ok(!job.permissions)
  const 下载 = job.steps.find(step => step.uses === 'actions/download-artifact@v4')
  assert.equal(String(下载.with['artifact-ids']), '14067402093')
  assert.equal(String(下载.with['run-id']), '43485198435')
  assert.equal(下载.with.repository, 'fangzhouxiaohai/seal-office')
  assert.ok(下载.with['github-token'])
  assert.equal(下载.with['merge-multiple'], true)
  const 命令 = job.steps.map(step => step.run || '').join('\n')
  for (const value of ['467583156', 'ee5239b483c4823016eee38f8902d60e552b196a45d72a3c190d0a244eacd256', 'hdiutil verify', 'codesign --verify --deep --strict', 'verify-macos-candidate.cjs', 'verify-macos-universal.cjs --canvas']) assert.ok(命令.includes(value), value)
  assert.ok(job.steps.filter(step => step.run).every(step => step['timeout-minutes'] > 0))
  assert.doesNotMatch(命令, /gh\s+release|git\s+push|release-assets/)
})
