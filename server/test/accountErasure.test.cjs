test('注销响应丢失后凭本机持久回执继续查询；重复提交不会重新创建账号',async t=>{
  const f=await createLocalCollaborationFixture(t,{clients:false}),phone='13800111907',a=await f.client(phone),local=path.join(f.directory,'response-loss-client')
  fs.mkdirSync(local);let drop=true
  const client=createService({directory:local,safeStorage:f.safeStorage,transport:async(url,options)=>{
    const response=await fetch(url,{method:options.method,headers:options.headers,body:options.body||undefined}),raw=Buffer.from(await response.arrayBuffer())
    const result=options.binary?raw:JSON.parse(raw.toString())
    if(!response.ok)throw Object.assign(new Error(result.error),{status:response.status})
    if(url.endsWith('/v1/auth/delete-account')&&drop){drop=false;throw new Error('controlled lost response')}
    return result
  }})
  f.locations.set(client,local);await client.setServer(f.url);f.advance(61000);await client.sendCode(phone);await client.login(phone,f.codes.get(phone))
  f.advance(61000);await client.sendCode(null,'delete-account')
  await assert.rejects(client.deleteAccount({code:f.codes.get(phone),confirm:'永久注销海豹办公账号'}),/lost response/)
  const receipt=f.localState(client).deletionReceipt;assert.ok(receipt)
  const reopened=f.reopen(client);await waitDeletion(reopened);assert.equal(reopened.status().account,null)
  const replay=await f.request('/v1/auth/delete-account',{method:'POST',data:{receipt}})
  assert.equal(replay.status,200);assert.equal(replay.body.deleted,true)
  assert.equal(f.cloud.db.one('SELECT id FROM users WHERE phone=?',[phone]),undefined)
  assert.equal((await f.request('/v1/me',{client:a})).status,401)
})

