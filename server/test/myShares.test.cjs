const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { randomUUID } = require('node:crypto')
const { createCloud } = require('../index.cjs')
const { listenLoopback } = require('./collaborationFixture.cjs')

async function fixture(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'seal-my-shares-'))
  const codes = new Map()
  let now = Date.now()
  const cloud = await createCloud({ directory: dir, clock: () => now, sms: { configured: true, send: async (phone, code) => codes.set(phone, code) }, env: {} })
  await listenLoopback(cloud.server)
  const url = `http://127.0.0.1:${cloud.server.address().port}`
  t.after(async () => { await cloud.close(); fs.rmSync(dir, { recursive: true, force: true }) })
  const raw = async (route, token, method = 'GET', data) => {
    const response = await fetch(url + route, { method, headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(data ? { 'Content-Type': 'application/json' } : {}) }, ...(data ? { body: JSON.stringify(data) } : {}) })
    return { status: response.status, body: await response.json() }
  }
  const account = async phone => {
    now += 61000
    await raw('/v1/auth/code', null, 'POST', { phone })
    const login = await raw('/v1/auth/login', null, 'POST', { phone, code: codes.get(phone) })
    assert.equal(login.status, 200)
    const enabled = await raw('/v1/space/enable', login.body.token, 'POST', { consent: true, envelope: 'encrypted-root', agreementVersion: '2026-10-08' })
    assert.equal(enabled.status, 200)
    return login.body
  }
  const node = owner => {
    const id = randomUUID()
    cloud.db.run('INSERT INTO nodes(id,user_id,parent,kind,meta,version,deleted,updated) VALUES(?,?,?,?,?,?,?,?)', [id, owner, null, 'file', 'encrypted-meta', 1, 0, now])
    return id
  }
  const link = (owner, nodeId, options = {}) => {
    const id = randomUUID()
    cloud.db.run('INSERT INTO share_links(id,user_id,node_id,access_hash,expires,revoked,created) VALUES(?,?,?,?,?,?,?)', [id, owner, nodeId, 'a'.repeat(64), options.expires ?? null, options.revoked ? 1 : 0, now++])
    return id
  }
  const share = (owner, recipient, nodeId, options = {}) => {
    const id = randomUUID()
    cloud.db.run('INSERT INTO shares(id,node_id,owner_id,recipient_id,permission,access_hash,envelope,expires,revoked,created) VALUES(?,?,?,?,?,?,?,?,?,?)', [id, nodeId, owner, recipient, 'read', 'b'.repeat(64), 'encrypted-envelope', options.expires ?? now + 86400000, options.revoked ? 1 : 0, now++])
    return id
  }
  return { cloud, raw, account, node, link, share, advance: ms => { now += ms }, now: () => now }
}

test('统一记录只列本人发起的两类分享，分页可翻过五百条且不泄露密钥', async t => {
  const f = await fixture(t)
  const owner = await f.account('13800111901')
  const other = await f.account('13800111902')
  const source = f.node(owner.account.id)
  for (let i = 0; i < 505; i++) f.link(owner.account.id, source)
  f.share(owner.account.id, other.account.id, source)
  f.share(other.account.id, owner.account.id, f.node(other.account.id))
  const first = await f.raw('/v1/my-shares?page=1&limit=100', owner.token)
  assert.equal(first.status, 200)
  assert.equal(first.body.total, 506)
  assert.equal(first.body.items.length, 100)
  assert.equal(first.body.items[0].kind, 'account')
  assert.equal(JSON.stringify(first.body).includes('access_hash'), false)
  assert.equal(JSON.stringify(first.body).includes('encrypted-envelope'), false)
  const last = await f.raw('/v1/my-shares?page=6&limit=100', owner.token)
  assert.equal(last.status, 200)
  assert.equal(last.body.items.length, 6)
  assert.equal((await f.raw('/v1/my-shares', other.token)).body.total, 1)
  assert.equal((await f.raw('/v1/my-shares')).status, 401)
  assert.equal((await f.raw('/v1/my-shares?page=0', owner.token)).status, 400)
  assert.equal((await f.raw('/v1/my-shares?status=active&limit=100', owner.token)).body.total, 506)
  assert.equal((await f.raw('/v1/my-shares?status=unknown', owner.token)).status, 400)
})

test('批量取消、删除记录和清理失效记录校验归属并保留源文件', async t => {
  const f = await fixture(t)
  const owner = await f.account('13800111903')
  const other = await f.account('13800111904')
  const source = f.node(owner.account.id)
  const link = f.link(owner.account.id, source)
  const accountShare = f.share(owner.account.id, other.account.id, source)
  const activeToDelete = f.link(owner.account.id, source)
  const foreign = f.link(other.account.id, f.node(other.account.id))
  const foreignShare = f.share(other.account.id, owner.account.id, f.node(other.account.id))
  const revoked = await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'revoke', entries: [{ kind: 'link', id: link }, { kind: 'account', id: accountShare }, { kind: 'link', id: foreign }, { kind: 'account', id: foreignShare }] })
  assert.equal(revoked.status, 200)
  assert.deepEqual(revoked.body.results.map(item => item.ok), [true, true, false, false])
  assert.equal(revoked.body.results[2].error, '分享记录不存在或无权操作')
  assert.equal(f.cloud.db.one('SELECT revoked FROM share_links WHERE id=?', [link]).revoked, 1)
  assert.equal(f.cloud.db.one('SELECT revoked FROM shares WHERE id=?', [accountShare]).revoked, 1)
  assert.equal((await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'revoke', entries: [{ kind: 'link', id: link }] })).body.results[0].ok, true)
  const removed = await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'delete', entries: [{ kind: 'link', id: link }, { kind: 'account', id: accountShare }, { kind: 'link', id: activeToDelete }] })
  assert.deepEqual(removed.body.results.map(item => item.ok), [true, true, true])
  assert.equal((await f.raw('/v1/share-links/' + activeToDelete)).status, 404)
  assert.equal(f.cloud.db.one('SELECT id FROM nodes WHERE id=?', [source]).id, source)
  assert.equal(f.cloud.db.one('SELECT id FROM share_links WHERE id=?', [foreign]).id, foreign)
  assert.equal(f.cloud.db.one('SELECT revoked FROM shares WHERE id=?', [foreignShare]).revoked, 0)
  assert.equal(f.cloud.db.one("SELECT COUNT(*) n FROM audit WHERE user_id=? AND action LIKE 'my-share-%'", [owner.account.id]).n >= 4, true)
})

test('清理失效记录按执行时状态重查，不删除有效记录', async t => {
  const f = await fixture(t)
  const owner = await f.account('13800111905')
  const other = await f.account('13800111906')
  const source = f.node(owner.account.id)
  const active = f.link(owner.account.id, source)
  const expired = f.link(owner.account.id, source, { expires: f.now() - 1 })
  const revoked = f.share(owner.account.id, other.account.id, source, { revoked: true })
  const missingSource = f.link(owner.account.id, f.node(owner.account.id))
  const changedAfterList = f.link(owner.account.id, source, { expires: f.now() - 1 })
  f.cloud.db.run('UPDATE nodes SET deleted=1 WHERE id=(SELECT node_id FROM share_links WHERE id=?)', [missingSource])
  const listed = await f.raw('/v1/my-shares', owner.token)
  assert.deepEqual(new Set(listed.body.items.map(item => item.status)), new Set(['active', 'expired', 'revoked', 'sourceRemoved']))
  assert.equal((await f.raw('/v1/my-shares?status=expired', owner.token)).body.total, 2)
  f.cloud.db.run('UPDATE share_links SET expires=? WHERE id=?', [f.now() + 86400000, changedAfterList])
  const clean = await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'cleanInvalid', limit: 100 })
  assert.equal(clean.status, 200)
  assert.equal(clean.body.results.length, 3)
  assert.equal(clean.body.hasMore, false)
  assert.equal(f.cloud.db.one('SELECT id FROM share_links WHERE id=?', [active]).id, active)
  assert.equal(f.cloud.db.one('SELECT id FROM share_links WHERE id=?', [changedAfterList]).id, changedAfterList)
  assert.equal(f.cloud.db.one('SELECT id FROM nodes WHERE id=?', [source]).id, source)
  assert.equal((await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'cleanInvalid' })).body.results.length, 0)
  const invalid = await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'delete', entries: [{ kind: 'link', id: 'bad' }] })
  assert.equal(invalid.status, 400)
})

test('按类型与已解锁客户端提供的来源标识筛选，并返回权限、到期与下载次数', async t => {
  const f = await fixture(t)
  const owner = await f.account('13800111907')
  const recipient = await f.account('13800111908')
  const source = f.node(owner.account.id)
  const second = f.node(owner.account.id)
  const link = f.link(owner.account.id, source, { expires: f.now() + 86400000 })
  const share = f.share(owner.account.id, recipient.account.id, second)
  f.cloud.db.run('UPDATE share_links SET downloads=7 WHERE id=?', [link])
  f.cloud.db.run("UPDATE shares SET permission='edit' WHERE id=?", [share])
  const links = await f.raw('/v1/my-shares?kind=link', owner.token)
  assert.equal(links.status, 200)
  assert.equal(links.body.total, 1)
  assert.equal(links.body.items[0].downloads, 7)
  assert.equal(links.body.items[0].permission, null)
  assert.equal(links.body.items[0].expiresAt > f.now(), true)
  const filtered = await f.raw('/v1/my-shares/query', owner.token, 'POST', { page: 1, limit: 50, kind: 'account', status: 'all', nodeIds: [source, second] })
  assert.equal(filtered.status, 200)
  assert.equal(filtered.body.total, 1)
  assert.equal(filtered.body.items[0].id, share)
  assert.equal(filtered.body.items[0].permission, 'edit')
  assert.equal(filtered.body.items[0].downloads, null)
  assert.equal(JSON.stringify(filtered.body).includes('encrypted-envelope'), false)
  assert.equal((await f.raw('/v1/my-shares/query', owner.token, 'POST', { nodeIds: [source], kind: 'account' })).body.total, 0)
  assert.equal((await f.raw('/v1/my-shares/query', owner.token, 'POST', { nodeIds: ['bad'] })).status, 400)
  assert.equal((await f.raw('/v1/my-shares/query', owner.token, 'POST', null)).status, 400)
  assert.equal((await f.raw('/v1/my-shares?kind=invalid', owner.token)).status, 400)
})

test('清理预览报告实时可清理数量，逐项异常不吞掉已成功和后续结果', async t => {
  const f = await fixture(t)
  const owner = await f.account('13800111909')
  const source = f.node(owner.account.id)
  const expired = f.link(owner.account.id, source, { expires: f.now() - 1 })
  const revoked = f.link(owner.account.id, source, { revoked: true })
  assert.equal((await f.raw('/v1/my-shares/cleanup-preview', owner.token)).body.count, 2)
  f.cloud.db.run('UPDATE share_links SET expires=? WHERE id=?', [f.now() + 86400000, expired])
  assert.equal((await f.raw('/v1/my-shares/cleanup-preview', owner.token)).body.count, 1)
  const first = f.link(owner.account.id, source)
  const middle = f.link(owner.account.id, source)
  const last = f.link(owner.account.id, source)
  f.cloud.db.run(`CREATE TRIGGER fail_middle_audit BEFORE INSERT ON audit WHEN NEW.action='my-share-revoke' AND NEW.detail='link:${middle}' BEGIN SELECT RAISE(ABORT,'测试审计失败'); END`)
  const result = await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'revoke', entries: [{ kind: 'link', id: first }, { kind: 'link', id: middle }, { kind: 'link', id: last }] })
  assert.equal(result.status, 200)
  assert.deepEqual(result.body.results.map(item => item.ok), [true, false, true])
  assert.match(result.body.results[1].error, /分享记录处理失败/)
  assert.equal(f.cloud.db.one('SELECT revoked FROM share_links WHERE id=?', [first]).revoked, 1)
  assert.equal(f.cloud.db.one('SELECT revoked FROM share_links WHERE id=?', [middle]).revoked, 0)
  assert.equal(f.cloud.db.one('SELECT revoked FROM share_links WHERE id=?', [last]).revoked, 1)
  assert.equal(f.cloud.db.one('SELECT id FROM share_links WHERE id=?', [revoked]).id, revoked)
})

test('批量清理用稳定游标越过首批失败项，继续处理更早的失效记录', async t => {
  const f = await fixture(t)
  const owner = await f.account('13800111910')
  const source = f.node(owner.account.id)
  const older = f.link(owner.account.id, source, { revoked: true })
  const failed = Array.from({ length: 100 }, () => f.link(owner.account.id, source, { revoked: true }))
  f.cloud.db.run(`CREATE TRIGGER fail_newer_delete BEFORE INSERT ON audit WHEN NEW.action='my-share-delete' AND NEW.detail!='link:${older}' BEGIN SELECT RAISE(ABORT,'测试首批删除失败'); END`)
  const originalError = console.error, reported = []
  let first
  try {
    console.error = (...args) => reported.push(args)
    first = await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'cleanInvalid', limit: 100 })
  } finally { console.error = originalError }
  assert.equal(reported.length, 100)
  assert.equal(first.status, 200)
  assert.equal(first.body.results.length, 100)
  assert.equal(first.body.results.every(item => !item.ok), true)
  assert.equal(first.body.hasMore, true)
  assert.equal(typeof first.body.nextCursor, 'string')
  const second = await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'cleanInvalid', limit: 100, cursor: first.body.nextCursor })
  assert.equal(second.status, 200)
  assert.deepEqual(second.body.results, [{ kind: 'link', id: older, ok: true }])
  assert.equal(second.body.hasMore, false)
  assert.equal(f.cloud.db.one('SELECT id FROM share_links WHERE id=?', [older]), undefined)
  assert.equal(f.cloud.db.one('SELECT COUNT(*) n FROM share_links WHERE user_id=?', [owner.account.id]).n, failed.length)
  assert.equal((await f.raw('/v1/my-shares/batch', owner.token, 'POST', { action: 'cleanInvalid', cursor: 'invalid' })).status, 400)
})
